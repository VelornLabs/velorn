// Actual React renderer; synthetic request/events only, no model or project files.
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5209')
if (base.hostname !== '127.0.0.1' || base.protocol !== 'http:') throw Error('Loopback fixture required')
;(async () => {
  const output = fs.mkdtempSync(path.join(os.tmpdir(),'velorn-agent-reviews-'))
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome',headless:true})
  try {
    const page = await browser.newPage({viewport:{width:1200,height:1000}}), errors=[]
    page.on('pageerror',e=>errors.push(e.message)); page.setDefaultTimeout(10000)
    await page.route('**/*',route=>new URL(route.request().url()).origin===base.origin?route.continue():route.abort())
    await page.routeWebSocket(()=>true,socket=>socket.close())
    await page.goto(new URL('/tests/fixtures/connected-agent.html?strict=1',base).href)
    await page.waitForFunction(()=>window.connectedAgentTest?.ready)
    const send = async text => {
      const count = await page.evaluate(()=>window.connectedAgentTest.snapshot().requests.length)
      await page.getByRole('textbox',{name:'Message your agent',exact:true}).fill(text)
      await page.getByRole('button',{name:'Send message',exact:true}).click()
      await page.waitForFunction(n=>window.connectedAgentTest.snapshot().requests.length>n,count)
      return page.evaluate(()=>window.connectedAgentTest.snapshot().requests.at(-1).requestId)
    }
    const baseline = await page.evaluate(()=>window.connectedAgentTest.snapshot().authored)
    const originalChat = await page.getByRole('combobox',{name:'Conversation',exact:true}).inputValue()
    const first = await send('Synthetic failed request')
    await page.evaluate(id=>window.connectedAgentTest.settle(id,{success:false,code:'CODEX_CONFIGURATION_UNSAFE',error:'No prompt was sent: synthetic environment rejection.'}),first)
    await page.locator('.ca-message').filter({hasText:'Request did not finish'}).waitFor()
    const second = await send('Synthetic preview request')
    assert.equal(await page.locator('.ca-message').filter({hasText:'Request did not finish'}).count(),1)
    assert.equal(await page.evaluate(()=>window.connectedAgentTest.snapshot().requests.at(-1).messages.some(m=>m.content.includes('Request did not finish'))),false)
    await page.evaluate(requestId=>{
      const canvas=document.createElement('canvas'); canvas.width=640;canvas.height=360
      const ctx=canvas.getContext('2d');ctx.fillStyle='#173651';ctx.fillRect(0,0,640,360);ctx.fillStyle='#efd7a3';ctx.font='36px sans-serif';ctx.fillText('Timeline review · 1.5s',80,190)
      window.connectedAgentTest.emitEvent({requestId,type:'review-frame',frame:{id:'review-synthetic',label:'Timeline frame',timeSeconds:1.5,
        timelineId:window.connectedAgentTest.editorView().timelineId,capturedAt:Date.now(),dataUrl:canvas.toDataURL('image/jpeg')}})
    },second)
    await page.getByRole('button',{name:'Enlarge Timeline frame · 1.500s',exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:'Show in editor',exact:true}).isDisabled(),true)
    await page.evaluate(id=>window.connectedAgentTest.settle(id,{success:true,text:'Synthetic review complete.'}),second)
    await page.getByText('Synthetic review complete.',{exact:true}).waitFor()
    await page.getByRole('button',{name:'Enlarge Timeline frame · 1.500s',exact:true}).click()
    assert.equal(await page.locator('dialog[open] img').count(),1)
    await page.screenshot({path:path.join(output,'desktop-review.png')})
    await page.getByRole('button',{name:'Close preview',exact:true}).click()
    await page.getByRole('button',{name:'Show in editor',exact:true}).click()
    assert.equal(await page.evaluate(()=>window.connectedAgentTest.editorView().playhead),1.5)
    assert.deepEqual(await page.evaluate(()=>window.connectedAgentTest.snapshot().authored),baseline)
    const generated = await send('Synthetic GPT image request')
    await page.evaluate(requestId=>{
      const canvas=document.createElement('canvas');canvas.width=300;canvas.height=300
      const ctx=canvas.getContext('2d');ctx.fillStyle='#e8dcc9';ctx.fillRect(0,0,300,300);ctx.fillStyle='#194d92';ctx.beginPath();ctx.arc(150,150,90,0,Math.PI*2);ctx.fill()
      window.connectedAgentTest.emitEvent({requestId,type:'review-frame',frame:{id:'review-generated',label:'Generated image · GPT Image',capturedAt:Date.now(),dataUrl:canvas.toDataURL('image/jpeg')}})
    },generated)
    await page.getByRole('button',{name:'Enlarge Generated image · GPT Image',exact:true}).waitFor()
    await page.evaluate(id=>window.connectedAgentTest.settle(id,{success:true,text:'Generated image imported into project assets.'}),generated)
    const later = await send('Continue the discussion')
    await page.evaluate(id=>window.connectedAgentTest.settle(id,{success:true,text:'A later reply without new images.'}),later)
    await page.getByText('A later reply without new images.',{exact:true}).waitFor()
    assert.equal(await page.locator('.ca-message').filter({hasText:'Generated image imported into project assets.'}).getByRole('button',{name:'Enlarge Generated image · GPT Image',exact:true}).count(),1)
    assert.equal(await page.locator('.ca-message').filter({hasText:'A later reply without new images.'}).locator('img').count(),0)
    await page.getByRole('button',{name:'Enlarge Generated image · GPT Image',exact:true}).click()
    await page.screenshot({path:path.join(output,'generated-image-review.png')})
    await page.getByRole('button',{name:'Close preview',exact:true}).click()
    await page.getByRole('button',{name:'New chat',exact:true}).click()
    assert.equal(await page.getByRole('region',{name:'Review stills',exact:true}).count(),0)
    await page.getByRole('combobox',{name:'Conversation',exact:true}).selectOption(originalChat)
    await page.locator('.ca-message').filter({hasText:'Request did not finish'}).waitFor()
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({success:true,output,checks:['persistent failure','failure excluded from provider history','actual image decode','enlarge','busy navigation blocked','seek without edits','chat isolation']}))
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
