// Isolated browser fixture: no model calls, native project IO or user storage.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199'
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-model-chats-'))
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } })
    const errors = [], blocked = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      if (url.origin === base && !/^\/(v1|api|prompt|queue|upload)(\/|$)/.test(url.pathname)) return route.continue()
      blocked.push(url.href); return route.abort()
    })
    await page.routeWebSocket(() => true, socket => socket.close())
    const button = name => page.getByRole('button', { name, exact: true })
    const chats = () => page.getByRole('combobox', { name: 'Conversation', exact: true })
    // Setup temporarily hides, but must not replace or clear, the composer.
    const composer = () => page.locator('textarea[aria-label="Message your agent"]')
    const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
    const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    const changeModel = () => page.getByRole('button', { name: /^(?:Change assistant(?: or model)?|Connect Codex|Set up Codex|Connect LM Studio)$/ })
    const open = async () => { if (await changeModel().getAttribute('aria-expanded') !== 'true') await changeModel().click() }
    const send = async text => {
      const count = (await snapshot()).requests.length
      await composer().fill(text); await button('Send message').click()
      await page.waitForFunction(n => window.connectedAgentTest.snapshot().requests.length > n, count)
      const request = (await snapshot()).requests.at(-1)
      assert.equal(await changeModel().isDisabled(), true)
      await page.evaluate(id => window.connectedAgentTest.settle(id, { success: true, text: 'Fixture reply.' }), request.requestId)
      await button('Stop response').waitFor({ state: 'hidden' }); await frame()
      return request
    }
    await page.goto(`${base}/tests/fixtures/connected-agent.html?strict=1`)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    const baseline = (await snapshot()).authored, first = await chats().inputValue()
    const firstRequest = await send('Yesterday task')
    const initialChatCount = await chats().locator('option').count()
    const originalReplyLabel = await page.locator('.ca-assistant .ca-requested-model').first().innerText()
    await button('Assistant settings').click(); await button('Full access').click()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant))
    await button('Back to chat').click(); await frame()
    const originalGrant = (await snapshot()).fullAccessGrant
    const accessCallCount = (await snapshot()).calls.filter(call => call.method === 'setFullAccess').length
    await composer().fill('Preserve same-provider draft')
    const workflow = '{"1":{"class_type":"Fixture","inputs":{"text":"RAM_ONLY_ATTACHMENT"}}}'
    await page.locator('input[type="file"]').setInputFiles({ name: 'workflow.json', mimeType: 'application/json', buffer: Buffer.from(workflow) })
    await button('Remove attachment workflow.json').waitFor()
    await open(); await page.getByLabel('Model', { exact: true }).selectOption('fixture-codex-fast'); await frame()
    assert.equal(await chats().inputValue(), first, 'Codex model changes keep the active conversation')
    assert.equal(await chats().locator('option').count(), initialChatCount, 'Model changes do not create hidden chats')
    assert.equal(await composer().inputValue(), 'Preserve same-provider draft')
    assert.equal(await page.locator('.ca-message').count(), 2)
    assert.equal(await page.locator('.ca-assistant .ca-requested-model').first().innerText(), originalReplyLabel)
    assert.deepEqual((await snapshot()).fullAccessGrant, originalGrant, 'Changing models within Codex does not revoke or replace existing access')
    assert.equal((await snapshot()).calls.filter(call => call.method === 'setFullAccess').length, accessCallCount)
    await button('Remove attachment workflow.json').waitFor()
    assert.equal(await changeModel().getAttribute('aria-expanded'), 'false')
    assert.equal(await composer().evaluate(node => node === document.activeElement), true)
    await button('Close assistant panel').click(); await button('Open agent').click(); await frame()
    assert.equal(await chats().inputValue(), first)
    assert.match(await page.getByLabel('Selected model', { exact: true }).innerText(), /fixture-codex-fast/)
    assert.equal(await composer().inputValue(), 'Preserve same-provider draft')
    await button('Remove attachment workflow.json').waitFor()
    const secondRequest = await send('Continue using the new model')
    assert.equal(secondRequest.model, 'fixture-codex-fast')
    assert.equal(secondRequest.messages.length, 3); assert.equal(secondRequest.conversationId, firstRequest.conversationId)
    assert.deepEqual(secondRequest.messages[0], firstRequest.messages[0])
    assert.deepEqual(secondRequest.messages[1], { role: 'assistant', content: 'Fixture reply.' })
    assert.deepEqual(secondRequest.documents, [{ name: 'workflow.json', text: workflow }])
    assert.equal(await page.locator('.ca-assistant .ca-requested-model').first().innerText(), originalReplyLabel, 'Historical reply retains its original model')
    assert.match(await page.locator('.ca-assistant .ca-requested-model').last().innerText(), /fixture-codex-fast/)
    await composer().fill('Keep Codex draft when changing providers')
    await open(); await page.getByLabel('Assistant selection', { exact: true }).selectOption('lmstudio')
    assert.equal(await chats().inputValue(), first, 'Choosing another agent previews the switch, not a new chat')
    assert.equal(await composer().inputValue(), 'Keep Codex draft when changing providers')
    await button('Keep this chat').click()
    assert.equal(await chats().inputValue(), first, 'Cancel leaves the original chat active')
    assert.equal(await composer().inputValue(), 'Keep Codex draft when changing providers')
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('lmstudio')
    await button('Start LM Studio chat').click(); await frame()
    const local = await chats().inputValue()
    assert.notEqual(local, first); assert.equal(await composer().inputValue(), '')
    assert.equal(await page.locator('.ca-message').count(), 0)
    assert.equal(await page.getByLabel('Message attachments', { exact: true }).count(), 0)
    const localSetup = page.getByRole('region', { name: 'LM Studio setup', exact: true })
    if (!await localSetup.isVisible()) await open()
    if (await localSetup.isVisible()) {
      // A new, unconfigured local chat now uses the explicit setup flow;
      // choosing an existing model still must not create or replace its chat.
      await localSetup.getByLabel('LM Studio model', { exact: true }).selectOption('fixture-model')
      await localSetup.getByRole('button', { name: 'Use model', exact: true }).click()
    } else await page.getByLabel('Model', { exact: true }).selectOption('fixture-model')
    await frame()
    assert.equal(await chats().inputValue(), local)
    const localFirst = await send('First local task')
    assert.equal(localFirst.messages.length, 1)
    const localChatCount = await chats().locator('option').count()
    const localReplyLabel = await page.locator('.ca-assistant .ca-requested-model').first().innerText()
    await composer().fill('Preserve local follow-up draft')
    await open(); await page.getByLabel('Model', { exact: true }).selectOption('__custom__')
    await page.getByLabel('Custom model ID', { exact: true }).fill('custom-local-model')
    assert.equal(await chats().inputValue(), local, 'Typing does not create chats')
    await button('Use model').click(); await frame()
    assert.equal(await chats().inputValue(), local, 'Custom LM Studio models keep the local conversation')
    assert.equal(await chats().locator('option').count(), localChatCount)
    assert.equal(await composer().inputValue(), 'Preserve local follow-up draft')
    assert.equal(await page.locator('.ca-assistant .ca-requested-model').first().innerText(), localReplyLabel)
    await button('Close assistant panel').click(); await button('Open agent').click(); await frame()
    assert.equal(await chats().inputValue(), local)
    assert.match(await page.getByLabel('Selected model', { exact: true }).innerText(), /custom-local-model/)
    assert.equal(await composer().inputValue(), 'Preserve local follow-up draft')
    const localRequest = await send('Continue local task with another model')
    assert.equal(localRequest.model, 'custom-local-model'); assert.equal(localRequest.messages.length, 3)
    assert.equal(localRequest.conversationId, localFirst.conversationId)
    assert.deepEqual(localRequest.messages[0], localFirst.messages[0])
    assert.deepEqual(localRequest.messages[1], { role: 'assistant', content: 'Fixture reply.' })
    assert.equal(await page.locator('.ca-assistant .ca-requested-model').first().innerText(), localReplyLabel)
    assert.match(await page.locator('.ca-assistant .ca-requested-model').last().innerText(), /custom-local-model/)
    await open(); await page.getByLabel('Assistant selection', { exact: true }).selectOption('codex'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click(); await frame()
    assert.notEqual(await chats().inputValue(), first); assert.notEqual(await chats().inputValue(), local)
    assert.equal(await page.locator('.ca-message').count(), 0)
    assert.equal(await composer().inputValue(), '')
    await chats().selectOption(`lmstudio:${local}`); await frame()
    assert.equal(await chats().inputValue(), local)
    assert.match(await page.getByLabel('Selected model', { exact: true }).innerText(), /custom-local-model/)
    assert.equal(await page.locator('.ca-message').count(), 4)
    await chats().selectOption(`codex:${first}`); await frame()
    assert.equal(await chats().inputValue(), first)
    assert.match(await page.getByLabel('Selected model', { exact: true }).innerText(), /fixture-codex-fast/)
    assert.equal(await composer().inputValue(), 'Keep Codex draft when changing providers')
    assert.equal(await page.locator('.ca-message').count(), 4)
    await button('Close assistant panel').click(); await button('Open agent').click(); await frame()
    assert.equal(await chats().inputValue(), first)
    assert.match(await page.getByLabel('Selected model', { exact: true }).innerText(), /fixture-codex-fast/)
    await open(); await page.getByLabel('Model', { exact: true }).locator('option[value="fixture-codex-fast"]').waitFor({ state: 'attached' })
    await page.screenshot({ path: path.join(output, 'model-picker.png') })
    assert.deepEqual((await snapshot()).authored, baseline)
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    assert.deepEqual((await snapshot()).forbiddenCalls, [])
    console.log(JSON.stringify({ passed: true, screenshot: path.join(output, 'model-picker.png'), checks: ['same-provider model switch retains chat', 'prior messages sent to new model', 'draft and attachment preserved', 'existing access preserved', 'historical model labels unchanged', 'fresh provider chat', 'history/model restore across providers', 'custom ID keeps local chat', 'selection persists before next send', 'picker closes and composer focuses', 'busy disabled', 'project untouched'] }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
