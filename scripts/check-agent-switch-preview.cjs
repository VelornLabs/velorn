// Real renderer, synthetic IPC and RAM-only chats. No user data or provider IO.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
;(async () => {
  const base = process.env.VELORN_TEST_URL || 'http://127.0.0.1:5173', out = await fs.mkdtemp(path.join(os.tmpdir(), 'velorn-agent-switch-'))
  const fixtureUrl = new URL(base)
  if (fixtureUrl.protocol !== 'http:' || fixtureUrl.hostname !== '127.0.0.1' || fixtureUrl.username || fixtureUrl.password) throw Error('Loopback fixture required')
  const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/google-chrome' })
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } }), errors = [], blocked = []
  page.setDefaultTimeout(10000)
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', r => new URL(r.request().url()).origin === base ? r.continue() : (blocked.push(r.request().url()), r.abort()))
  await page.routeWebSocket(() => true, s => s.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const picker = () => page.getByLabel('Assistant selection', { exact: true })
  const confirmation = () => page.getByRole('group', { name: 'Confirm assistant switch' })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  try {
    await page.goto(base + '/tests/fixtures/connected-agent.html?strict=1')
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    await button('Assistant settings').click()
    await picker().selectOption('luna')
    // Regression: the old dropdown immediately displayed codex instead of luna.
    assert.equal(await picker().inputValue(), 'luna')
    await button('Start Velo chat').click()
    await page.getByLabel('Selected assistant', { exact: true }).waitFor()
    const draft = page.getByRole('textbox', { name: 'Message your agent', exact: true })
    await draft.fill('Keep this unsent Velo draft')
    await page.locator('input[type="file"]').setInputFiles({ name: 'preview-test.json', mimeType: 'application/json', buffer: Buffer.from('{"synthetic":true}') })
    await button('Remove attachment preview-test.json').waitFor()
    const chat = await page.getByLabel('Conversation', { exact: true }).inputValue()
    for (const surface of ['inline', 'settings']) {
      if (surface === 'inline') await button(/^(?:Change assistant|Change assistant or model)$/).click()
      else await button('Assistant settings').click()
      const before = await snapshot()
      for (const [target, label] of [['codex', 'Codex'], ['lmstudio', 'LM Studio']]) {
        await picker().selectOption(target)
        assert.equal(await picker().inputValue(), target)
        assert.equal(await page.locator('.ca-options').isVisible(), false, 'Current model controls are hidden while another assistant is proposed')
        await confirmation().getByRole('button', { name: `Start ${label} chat`, exact: true }).waitFor()
        await picker().selectOption('luna')
        await confirmation().waitFor({ state: 'hidden' })
        assert.equal(await picker().inputValue(), 'luna')
        assert.equal(await page.locator('.ca-options').isVisible(), true, 'Returning to the current assistant restores its model controls')
      }
      await picker().selectOption('codex')
      await picker().selectOption('lmstudio')
      assert.equal(await picker().inputValue(), 'lmstudio')
      assert.equal(await button('Start Codex chat').count(), 0)
      await button('Start LM Studio chat').waitFor()
      await page.screenshot({ path: path.join(out, surface + '-pending.png') })
      await button('Keep this chat').click()
      assert.equal(await picker().inputValue(), 'luna')
      await confirmation().waitFor({ state: 'hidden' })
      await picker().selectOption('codex')
      await page.keyboard.press('Escape')
      await confirmation().waitFor({ state: 'hidden' })
      assert.equal(await picker().inputValue(), 'luna')
      assert.deepEqual((await snapshot()).storage, before.storage, 'Preview/cancel cannot create chats or save a provider choice')
      assert.deepEqual((await snapshot()).requests, before.requests, 'Preview/cancel cannot send')
      assert.deepEqual((await snapshot()).authored, before.authored)
      if (surface === 'inline') await button(/^(?:Change assistant|Change assistant or model)$/).click()
      else await button('Back to chat').click()
      assert.equal(await draft.inputValue(), 'Keep this unsent Velo draft')
      assert.equal(await page.getByLabel('Conversation', { exact: true }).inputValue(), chat)
      await button('Remove attachment preview-test.json').waitFor()
      console.log(`PASS: ${surface} proposed target, re-selection, cancellation and Escape stay in sync; chat/draft/attachment/storage unchanged`)
    }
    await button(/^(?:Change assistant|Change assistant or model)$/).click()
    await picker().selectOption('lmstudio')
    await picker().selectOption('codex')
    await button('Start Codex chat').click()
    assert.equal(await picker().inputValue(), 'codex', 'Confirm switches only to the latest proposed assistant')
    assert.equal((await snapshot()).requests.length, 0)
    assert.deepEqual((await snapshot()).forbiddenCalls, [])
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    console.log('PASS: Explicit confirmation uses the latest target, without inference')
    console.log(out)
  } catch (error) { await page.screenshot({ path: path.join(out, 'failure.png') }); console.log(out); throw error }
  finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
