// Synthetic renderer test only. All external requests and WebSockets blocked.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199'
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-funded-luna-ui-'))
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } })
    const errors = [], blocked = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      if (url.origin === base && !/^\/(v1|api|prompt|queue|upload)(\/|$)/.test(url.pathname)) return route.continue()
      blocked.push(url.href); return route.abort()
    })
    await page.routeWebSocket(() => true, socket => socket.close())
    const button = name => page.getByRole('button', { name, exact: true })
    const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
    const composer = () => page.getByRole('textbox', { name: 'Message your agent', exact: true })
    await page.goto(`${base}/tests/fixtures/connected-agent.html?strict=1`)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    // This regression starts from an already-connected Codex chat. Newer
    // setup UI correctly says "Set up Codex" until the first native check;
    // resolve the synthetic connection before exercising provider switching.
    await button('Assistant settings').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().calls.some(c => c.method === 'inspect' && c.options.provider === 'codex'))
    await button('Back to chat').click()
    const originalChat = await page.getByLabel('Conversation', { exact: true }).inputValue()
    await composer().fill('Preserve original Codex draft')
    await page.locator('input[type="file"]').setInputFiles({ name: 'keep.json', mimeType: 'application/json', buffer: Buffer.from('{"keep":true}') })
    await button('Remove attachment keep.json').waitFor()
    await page.getByRole('button', { name: /^(?:Change assistant(?: or model)?|Connect Codex)$/ }).click()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('luna'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click()
    assert.equal(await page.getByLabel('Assistant selection', { exact: true }).locator('option:checked').textContent(), 'Velo')
    await page.getByText('About Velo and sharing', { exact: true }).click()
    assert.match(await page.getByLabel('Velo connection').innerText(), /Velorn’s built-in AI assistant/)
    const veeDescription = 'Velorn’s built-in AI assistant.'
    assert.ok((await page.getByLabel('Velo connection').innerText()).includes(veeDescription))
    await page.screenshot({ path: path.join(output, 'vee-settings.png'), fullPage: true })
    assert.equal(await composer().inputValue(), '')
    assert.equal(await button('Remove attachment keep.json').count(), 0)
    assert.equal(await page.getByLabel('Custom model ID', { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('Thinking level', { exact: true }).count(), 0)
    assert.match(await page.getByLabel('Velo connection').innerText(), /Velorn service and OpenAI/)
    const before = (await snapshot()).requests.length
    assert.equal(await button('Check connection').count(), 0, 'Velo discovers access without a manual connection step')
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().calls.some(c => c.method === 'inspect' && c.options.provider === 'luna'))
    assert.equal((await snapshot()).requests.length, before, 'status lookup cannot start inference')
    const inspect = (await snapshot()).calls.filter(c => c.method === 'inspect' && c.options.provider === 'luna').at(-1)
    assert.equal(inspect.options.endpoint, undefined)
    await button('Assistant settings').click()
    const currentChat = await page.getByLabel('Conversation', { exact: true }).inputValue()
    const beforeThinking = await snapshot()
    assert.equal(await page.getByLabel('Thinking level', { exact: true }).count(), 0)
    await page.locator('.ca-more-options > summary').click()
    assert.equal(await page.locator('.ca-thinking-options').count(), 0)
    assert.deepEqual((await snapshot()).storage, beforeThinking.storage, 'Opening advanced options changes no saved preference')
    assert.deepEqual((await snapshot()).authored, beforeThinking.authored)
    await button('Back to chat').click()
    await button('Close assistant panel').click()
    // Seed an older saved Velo chat using Max. The fixture still advertises the
    // old six-option native catalog to exercise mixed-version compatibility.
    const legacyKey = await page.evaluate(id => {
      const key = Object.keys(window.connectedAgentTest.snapshot().storage).find(key => key.includes('.conversations.v1.luna.'))
      if (!key) throw Error('Missing Velo fixture history')
      const saved = JSON.parse(localStorage.getItem(key))
      saved.conversations.find(chat => chat.id === id).selection = { model: 'gpt-6-luna', reasoningEffort: 'max' }
      localStorage.setItem(key, JSON.stringify(saved))
      return key
    }, currentChat)
    await button('Open agent').click()
    await button('Assistant settings').click()
    await page.locator('.ca-more-options > summary').click()
    assert.equal(await page.getByLabel('Thinking level', { exact: true }).count(), 0, 'No selector even with saved Max and a legacy native catalog')
    assert.equal(await page.getByLabel('Conversation', { exact: true }).inputValue(), currentChat)
    assert.equal(JSON.parse((await snapshot()).storage[legacyKey]).conversations.find(chat => chat.id === currentChat).selection.reasoningEffort, 'max', 'Reading old history must not rewrite it')
    assert.equal((await snapshot()).requests.length, before, 'UI changes never send a request')
    await page.screenshot({ path: path.join(output, 'velo-fixed-light.png'), fullPage: true })
    await button('Work in Velorn').click()
    assert.equal(await button('Full access').count(), 1)
    await page.getByText('Access options', { exact: true }).click()
    assert.equal(await page.getByRole('checkbox', { name: 'Research & setup', exact: true }).count(), 1)
    assert.equal(await page.getByRole('radio', { name: 'Auto-approve editing', exact: true }).count(), 1)
    assert.equal(await page.getByRole('checkbox', { name: 'Share images', exact: true }).count(), 1)
    await button('Full access').click()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant))
    assert.equal(await page.locator('.ca-editing-approvals').isVisible(), false)
    assert.doesNotMatch(await page.locator('.ca-access-modes').innerText(), /funded allowance remains separate/)
    assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
    await button('Learn more about Full access').click()
    await page.getByText('No Codex installation or sign-in is needed. Shared context, images, file content and command output go through Velorn to OpenAI. Your Velo inference allowance still applies; Full access does not add or refill it. Earlier tool-only approval does not grant computer access; fresh confirmation is required.', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'velo-full-access-details.png'), fullPage: true })
    await page.getByText('Access options', { exact: true }).click()
    await page.screenshot({ path: path.join(output, 'velo-full-access-compact.png'), fullPage: true })
    await button('Work in Velorn').click()
    await page.getByRole('heading', { name: 'When should it ask?', exact: true }).waitFor()
    await button('Work in Velorn').click()
    await page.getByText('Access options', { exact: true }).click()
    await page.getByRole('checkbox', { name: 'Include current view', exact: true }).uncheck()
    await page.getByRole('checkbox', { name: 'Share images', exact: true }).uncheck()
    await button('Back to chat').click()
    assert.equal(await page.getByLabel('Start a conversation').getByText(veeDescription, { exact: true }).isVisible(), true)
    await page.screenshot({ path: path.join(output, 'vee-welcome.png'), fullPage: true })
    assert.equal(await button('Attach images or JSON').isDisabled(), false)
    await composer().fill('Only funded Luna sees this')
    await button('Send message').click()
    await page.waitForFunction(n => window.connectedAgentTest.snapshot().requests.length > n, before)
    const request = (await snapshot()).requests.at(-1)
    assert.equal(await page.getByLabel('Start a conversation').count(), 0, 'welcome disappears when conversation starts')
    assert.equal(request.provider, 'luna'); assert.equal(request.model, 'gpt-6-luna')
    assert.equal(request.reasoningEffort, 'low', 'Velo always sends Light despite saved Max and old native catalog')
    assert.equal(request.endpoint, undefined)
    assert.equal(request.vision, true); assert.equal(request.fullAccess, false)
    assert.equal(request.researchEnabled, true); assert.equal(request.autoApproveEdits, false)
    assert.equal(request.toolsEnabled, true); assert.deepEqual(request.images, []); assert.deepEqual(request.documents, [])
    assert.equal(request.messages.length, 1)
    await page.evaluate(id => window.connectedAgentTest.settle(id, { success: false, code: 'LUNA_EXHAUSTED', error: 'Funded allowance used up.', promptNotSent: true }), request.requestId)
    await button('Stop response').waitFor({ state: 'hidden' })
    assert.equal(await composer().inputValue(), 'Only funded Luna sees this', 'proven unsent request returns to draft')
    assert.equal(await button('Send message').isDisabled(), true)
    assert.equal((await snapshot()).requests.length, before + 1, 'no automatic retry or fallback')
    if (await button(/^(?:Change assistant|Change assistant or model)$/).getAttribute('aria-expanded') !== 'true') await button(/^(?:Change assistant|Change assistant or model)$/).click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().calls.filter(c => c.method === 'inspect' && c.options.provider === 'luna').length > 1)
    await button(/^(?:Change assistant|Change assistant or model)$/).click()
    await composer().fill('Original second attempt')
    await button('Send message').click()
    await page.waitForFunction(n => window.connectedAgentTest.snapshot().requests.length > n, before + 1)
    const second = (await snapshot()).requests.at(-1)
    await composer().fill('Newer draft typed while waiting')
    await page.evaluate(id => window.connectedAgentTest.settle(id, { success: false, code: 'LUNA_EXHAUSTED', error: 'Funded allowance used up.', promptNotSent: true }), second.requestId)
    await button('Stop response').waitFor({ state: 'hidden' })
    assert.equal(await composer().inputValue(), 'Newer draft typed while waiting', 'late unsent failure cannot overwrite a newer draft')
    assert.match(await page.getByRole('log', { name: 'Agent conversation' }).innerText(), /Unsent message:\s*Original second attempt/)
    await page.screenshot({ path: path.join(output, 'luna-draft-recovery.png'), fullPage: true })
    await page.getByLabel('Conversation', { exact: true }).selectOption(`codex:${originalChat}`)
    assert.equal(await composer().inputValue(), 'Preserve original Codex draft')
    await button('Remove attachment keep.json').waitFor()
    assert.equal(await page.getByText(veeDescription, { exact: true }).count(), 0, 'Codex does not inherit Velo introduction')
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    console.log('PASS: funded Luna explicit availability, fixed request, shared access controls, provider isolation and unsent-draft recovery.')
    console.log(`Artifacts: ${output}`)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
