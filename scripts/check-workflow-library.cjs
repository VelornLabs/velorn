const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5206')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw new Error('Use an isolated loopback fixture')
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-workflow-library-')), errors = [], blocked = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|api|v1)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const dialog = () => page.getByRole('dialog', { name: 'My Workflows', exact: true })
  const card = name => page.getByRole('article', { name, exact: true })
  const state = () => page.evaluate(() => window.workflowLibraryTest.snapshot())
  const organization = async () => Object.values((await state()).settings).find(value => value?.version === 1 && value?.entries && value?.folders)
  const folderFilter = () => page.getByRole('combobox', { name: 'Workflow folder', exact: true })
  const sort = () => page.getByRole('combobox', { name: 'Sort workflows', exact: true })
  const titles = () => dialog().getByRole('article').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))
  const details = async name => {
    const disclosure = card(name).locator('details')
    if (!await disclosure.evaluate(node => node.open)) await disclosure.locator('summary').click()
  }
  const open = async () => { await button('My Workflows').click(); await page.getByText('3 workflows saved', { exact: true }).waitFor() }
  let groups = 0
  const pass = text => console.log(`PASS ${++groups}: ${text}`)
  try {
    await page.goto(new URL('/tests/fixtures/workflow-library.html', base).href)
    await open()
    assert.equal(await page.getByLabel('Search saved workflows').evaluate(node => document.activeElement === node), true)
    assert.equal(await card('My portrait animation').count(), 1)
    assert.equal(await card('My upscale workflow').count(), 1)
    assert.deepEqual(await titles(), ['My portrait animation', 'My upscale workflow', 'My older landscape workflow'])
    assert.equal(await card('My portrait animation').locator('details').evaluate(node => node.open), false)
    assert.equal(await card('My portrait animation').getByText('A gentle portrait performance with my favorite local workflow.', { exact: true }).isVisible(), false)
    assert.match(await card('My portrait animation').innerText(), /Image/)
    assert.match(await card('My upscale workflow').innerText(), /Video/)
    await page.screenshot({ path: path.join(output, 'library-desktop.png') })
    pass('One searchable drawer contains existing ComfyUI captures and imported API recipes')
    await page.getByLabel('Search saved workflows').fill('resolution')
    await page.getByText('1 workflow found', { exact: true }).waitFor()
    assert.equal(await card('My upscale workflow').count(), 1)
    await page.getByLabel('Search saved workflows').fill('nothing matches')
    await page.getByText('No matching workflows', { exact: true }).waitFor()
    await page.getByLabel('Search saved workflows').fill('')
    await details('My older landscape workflow')
    assert.match(await card('My older landscape workflow').innerText(), /save it to Velorn again/)
    pass('Searches descriptions and names; legacy UI-only saves have honest setup guidance')
    await card('My portrait animation').getByRole('button', { name: 'Use with agent', exact: true }).click()
    await dialog().waitFor({ state: 'hidden' })
    assert.equal(await page.getByLabel('Staged workflow reference').inputValue(), 'my-workflow:portrait')
    assert.equal(await page.getByLabel('Staged workflow reference').evaluate(node => document.activeElement === node), true)
    assert.deepEqual((await state()).calls.filter(x => x !== 'list'), ['stage'])
    pass('Use with agent stages only and hands focus to chat without reading a graph or running anything')
    await open()
    await details('My portrait animation')
    await button('Edit details for My portrait animation').click()
    await card('My portrait animation').getByLabel('Workflow name', { exact: true }).fill('My favorite portrait')
    await card('My portrait animation').getByLabel('Workflow description', { exact: true }).fill('Use this for subtle motion.')
    await button('Save details').click()
    await card('My favorite portrait').waitFor()
    const updated = (await state()).records.find(r => r.id === 'portrait')
    assert.equal(updated.title, 'My favorite portrait')
    assert.equal(updated.apiWorkflow['1'].inputs.image, 'portrait.png')
    pass('Renames and describes a capture while preserving its ID and saved API graph')
    await card('My older landscape workflow').getByRole('button', { name: 'Open in ComfyUI', exact: true }).click()
    assert.equal((await state()).calls.includes('read'), false)
    await button('Cancel').click()
    assert.equal((await state()).calls.includes('open'), false)
    await card('My older landscape workflow').getByRole('button', { name: 'Open in ComfyUI', exact: true }).click()
    await button('Replace graph and open').click()
    await dialog().waitFor({ state: 'hidden' })
    assert.equal((await state()).calls.filter(x => x === 'open').length, 1)
    pass('Opening explicitly confirms graph replacement and does not submit generation')
    await open()
    await button('Add My older landscape workflow to favorites').click()
    await button('Remove My older landscape workflow from favorites').waitFor()
    assert.equal(await button('Remove My older landscape workflow from favorites').getAttribute('aria-pressed'), 'true')
    assert.equal((await titles())[0], 'My older landscape workflow')
    assert.equal((await organization()).entries['my-workflow:legacy'].favorite, true)
    await sort().selectOption('name')
    await page.waitForFunction(() => Object.values(window.workflowLibraryTest.snapshot().settings).some(value => value?.sort === 'name'))
    assert.deepEqual(await titles(), ['My older landscape workflow', 'My favorite portrait', 'My upscale workflow'])
    await folderFilter().selectOption('favorites')
    await page.getByText('1 workflow found', { exact: true }).waitFor()
    assert.deepEqual(await titles(), ['My older landscape workflow'])
    await button('Remove My older landscape workflow from favorites').click()
    await page.getByText('No favorites yet', { exact: true }).waitFor()
    assert.equal(await folderFilter().evaluate(node => document.activeElement === node), true)
    await folderFilter().selectOption('all')
    await button('Add My older landscape workflow to favorites').click()
    await button('Remove My older landscape workflow from favorites').waitFor()
    pass('Favorites pin above alphabetical rows and the favorites filter uses persisted organization')
    await button('New folder').click()
    await page.getByLabel('Folder name', { exact: true }).fill('Advertisements')
    await button('Create folder').click()
    await page.waitForFunction(() => Object.values(window.workflowLibraryTest.snapshot().settings).some(value => value?.folders?.some(folder => folder.name === 'Advertisements')))
    assert.equal(await folderFilter().evaluate(node => document.activeElement === node), true)
    const adsId = (await organization()).folders.find(folder => folder.name === 'Advertisements').id
    await folderFilter().selectOption('all')
    await details('My favorite portrait')
    await page.getByLabel('Folder for My favorite portrait', { exact: true }).selectOption(adsId)
    await page.waitForFunction(id => Object.values(window.workflowLibraryTest.snapshot().settings).some(value => value?.entries?.['my-workflow:portrait']?.folderId === id), adsId)
    await folderFilter().selectOption(adsId)
    await page.getByText('1 workflow found', { exact: true }).waitFor()
    assert.deepEqual(await titles(), ['My favorite portrait'])
    await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    await open()
    assert.equal(await sort().inputValue(), 'name')
    assert.equal(await button('Remove My older landscape workflow from favorites').getAttribute('aria-pressed'), 'true')
    await folderFilter().selectOption(adsId)
    await page.getByText('1 workflow found', { exact: true }).waitFor()
    assert.deepEqual(await titles(), ['My favorite portrait'])
    pass('Folders, assignments, favorites and sort survive drawer unmount/remount without modifying graph files')
    await button('Rename folder').click()
    await page.getByLabel('Folder name', { exact: true }).fill('Client advertisements')
    await button('Save folder').click()
    await page.waitForFunction(() => Object.values(window.workflowLibraryTest.snapshot().settings).some(value => value?.folders?.some(folder => folder.name === 'Client advertisements')))
    assert.equal(await folderFilter().evaluate(node => document.activeElement === node), true)
    assert.equal((await organization()).folders.find(folder => folder.name === 'Client advertisements').id, adsId)
    await button('Remove folder').click()
    await page.waitForFunction(id => Object.values(window.workflowLibraryTest.snapshot().settings).some(value => value?.folders && !value.folders.some(folder => folder.id === id)), adsId)
    assert.equal(await folderFilter().evaluate(node => document.activeElement === node), true)
    await folderFilter().selectOption('unfiled')
    await page.getByText('3 workflows found', { exact: true }).waitFor()
    assert.equal((await state()).records.length, 2)
    assert.equal((await organization()).entries['my-workflow:portrait']?.folderId || '', '')
    assert.equal((await state()).calls.filter(call => call === 'metadata-write').length, 1)
    pass('Renaming preserves folder identity; removing a folder unfiles its workflows without deleting any recipe')
    await folderFilter().selectOption('all')
    const beforeFailedWrite = await organization()
    await page.evaluate(() => window.workflowLibraryTest.setFailSettingsWrite(true))
    await button('Add My upscale workflow to favorites').click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic organization write failed.' }).waitFor()
    assert.equal(await button('Add My upscale workflow to favorites').getAttribute('aria-pressed'), 'false')
    assert.deepEqual(await organization(), beforeFailedWrite)
    await page.evaluate(() => window.workflowLibraryTest.setFailSettingsWrite(false))
    await button('Refresh My Workflows').click()
    await page.getByText('3 workflows saved', { exact: true }).waitFor()
    pass('Failed organization persistence stays visible and does not claim a favorite was saved')
    await page.evaluate(() => window.workflowLibraryTest.setDisabled(true))
    await page.getByText('Workflow actions are paused during export. You can still browse your library.').waitFor()
    assert.equal(await card('My favorite portrait').getByRole('button', { name: 'Use with agent', exact: true }).isDisabled(), true)
    assert.equal(await card('My favorite portrait').getByRole('button', { name: 'Open in ComfyUI', exact: true }).isDisabled(), true)
    await page.evaluate(() => window.workflowLibraryTest.setDisabled(false))
    await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    assert.equal(await button('My Workflows').evaluate(node => document.activeElement === node), true)
    pass('Export disables actions; Escape restores focus to the library opener')
    await open()
    const listReadsBeforeSave = (await state()).calls.filter(call => call === 'list').length
    await page.evaluate(() => window.workflowLibraryTest.holdSettingsWrite(true))
    await button('Add My upscale workflow to favorites').click()
    await page.waitForFunction(() => window.workflowLibraryTest.snapshot().settingsWritePending)
    await page.evaluate(() => { window.workflowLibraryTest.setLongList(true); window.dispatchEvent(new Event('comfystudio:imported-workflows-changed')) })
    await page.waitForFunction(count => window.workflowLibraryTest.snapshot().calls.filter(call => call === 'list').length > count, listReadsBeforeSave)
    await page.evaluate(() => { window.workflowLibraryTest.holdSettingsWrite(false); window.workflowLibraryTest.releaseSettingsWrite() })
    await page.getByText('51 workflows saved', { exact: true }).waitFor()
    await button('Remove My upscale workflow from favorites').waitFor()
    assert.equal((await organization()).entries['tpl-mcp-upscale'].favorite, true)
    assert.equal(await button('Remove My upscale workflow from favorites').isDisabled(), false)
    await page.evaluate(() => window.workflowLibraryTest.setLongList(false))
    await button('Refresh My Workflows').click()
    await page.getByText('3 workflows saved', { exact: true }).waitFor()
    pass('Concurrent catalog refresh retains newly imported rows and the successfully saved favorite')
    const beforeEmptyList = await organization()
    await page.evaluate(() => window.workflowLibraryTest.setEmpty(true))
    await button('Refresh My Workflows').click()
    await page.getByText('Keep your next workflow here', { exact: true }).waitFor()
    assert.deepEqual(await organization(), beforeEmptyList)
    await page.evaluate(() => window.workflowLibraryTest.setEmpty(false))
    await button('Refresh My Workflows').click()
    await page.getByText('3 workflows saved', { exact: true }).waitFor()
    assert.equal(await button('Remove My older landscape workflow from favorites').getAttribute('aria-pressed'), 'true')
    await page.evaluate(() => window.workflowLibraryTest.setLongList(true))
    await button('Refresh My Workflows').click()
    await page.getByText('51 workflows saved', { exact: true }).waitFor()
    assert.equal(await dialog().getByRole('article').count(), 51)
    await page.screenshot({ path: path.join(output, 'library-organized-desktop.png') })
    await page.setViewportSize({ width: 420, height: 760 })
    await page.screenshot({ path: path.join(output, 'library-narrow.png') })
    assert.ok(await dialog().evaluate(node => node.scrollWidth <= node.clientWidth))
    assert.ok(await dialog().getByRole('article').evaluateAll(nodes => nodes.every(node => node.scrollWidth <= node.clientWidth)))
    await card('Long workflow 48 — saved recipe with a longer name').scrollIntoViewIfNeeded()
    await details('Long workflow 48 — saved recipe with a longer name')
    await page.screenshot({ path: path.join(output, 'library-long-list-details.png') })
    assert.ok(await dialog().evaluate(node => node.scrollWidth <= node.clientWidth))
    await dialog().locator('summary').last().evaluate(node => { node.parentElement.open = false; node.focus() })
    await page.keyboard.press('Tab')
    assert.equal(await dialog().evaluate(node => node.contains(document.activeElement)), true)
    pass('Empty catalog refresh preserves organization; 51 compact workflows remain navigable at phone width')
    await page.evaluate(() => window.workflowLibraryTest.setEmpty(true))
    await button('Refresh My Workflows').click()
    await page.getByText('Keep your next workflow here', { exact: true }).waitFor()
    await page.evaluate(() => window.workflowLibraryTest.setFailList(true))
    await button('Refresh My Workflows').click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic library read failed.' }).waitFor()
    await page.evaluate(() => { window.workflowLibraryTest.setEmpty(false); window.workflowLibraryTest.setFailList(false); window.workflowLibraryTest.setLongList(false); window.workflowLibraryTest.setFailSettingsRead(true) })
    await button('Refresh My Workflows').click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic organization read failed.' }).waitFor()
    assert.equal(await button('Remove My older landscape workflow from favorites').isDisabled(), true)
    assert.equal(await card('My favorite portrait').getByRole('button', { name: 'Use with agent', exact: true }).isDisabled(), false)
    assert.equal(await card('My favorite portrait').getByRole('button', { name: 'Open in ComfyUI', exact: true }).isDisabled(), false)
    assert.deepEqual(await organization(), beforeEmptyList)
    await page.evaluate(() => window.workflowLibraryTest.setFailSettingsRead(false))
    await button('Refresh My Workflows').click()
    await page.getByText('3 workflows saved', { exact: true }).waitFor()
    assert.equal(await button('Remove My older landscape workflow from favorites').isDisabled(), false)
    pass('Failed settings reads preserve saved organization and do not block opening or using workflow recipes')
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    pass('Narrow layout, empty library and failed refresh are usable with no external traffic')
    console.log(JSON.stringify({ success: true, groups, output }))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {})
    fs.writeFileSync(path.join(output, 'failure.txt'), await dialog().innerText().catch(() => 'Dialog unavailable'))
    console.error(`Fixture failure artifacts: ${output}`)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
