'use strict'
// Renderer fixture only: no provider, command, account or real project access.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
async function main() {
  const base = process.env.VELORN_TEST_URL || 'http://127.0.0.1:5265'
  assert.equal(new URL(base).origin, base)
  assert.equal(new URL(base).hostname, '127.0.0.1'); assert.equal(new URL(base).protocol, 'http:')
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'velorn-continuation-ui-'))
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 }, serviceWorkers: 'block' })
  const errors = [], blocked = [], checks = []
  page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(10000)
  await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : (blocked.push(route.request().url()), route.abort()))
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const input = () => page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const activity = () => page.getByTestId('agent-activity')
  let request
  const emit = event => page.evaluate(event => window.connectedAgentTest.emitEvent(event), { requestId: request.requestId, ...event })
  try {
    await page.goto(base + '/tests/fixtures/connected-agent.html?strict=1')
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    const baseline = (await snapshot()).authored
    await button('Assistant settings').click()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('luna')
    await button('Start Velo chat').click()
    await button('Assistant settings').click(); await button('Work in Velorn').click()
    await button('Back to chat').click()
    await input().fill('Synthetic long-command recovery fixture only.')
    await button('Send message').click()
    if (await button('Allow and send').count()) await button('Allow and send').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().requests.length === 1)
    request = (await snapshot()).requests[0]
    await input().fill('Keep this next draft while the request waits.')
    await emit({ type: 'tool', callId: 'same-command', toolName: 'Shell command', status: 'running', summary: 'Synthetic command', durationMs: 1000, output: 'Synthetic output\n' })
    await page.waitForFunction(() => document.querySelector('[data-testid="agent-activity"]')?.dataset.state === 'tool')
    await emit({ type: 'tool', callId: 'same-command', toolName: 'Shell command', status: 'running', summary: 'Synthetic command', durationMs: 15000, output: 'Synthetic output\nStill running\n' })
    assert.equal(await page.locator('[data-activity-id="tool:same-command"]').count(), 1)
    assert.equal(await page.locator('[data-activity-id="tool:same-command"] .ca-tool-duration').getAttribute('title'), '15000 ms elapsed')
    checks.push('Long-command activity updates elapsed time and output in one row')
    await emit({ type: 'status', waitingFor: 'velo-service', text: 'Velo is waiting for its request limit to reset. Continuing in 60s… Stop to cancel.' })
    await page.waitForFunction(() => document.querySelector('[data-testid="agent-activity"]')?.dataset.state === 'service-wait')
    assert.match(await activity().innerText(), /Waiting for Velo…/)
    assert.match(await activity().innerText(), /Continuing in 60s/)
    assert.doesNotMatch(await activity().innerText(), /approval/)
    assert.equal(await button('Stop response').isEnabled(), true)
    await emit({ type: 'status', waitingFor: 'velo-service', text: 'Velo is waiting for its request limit to reset. Continuing in 59s… Stop to cancel.' })
    await page.waitForFunction(() => document.querySelector('[data-testid="agent-activity"]')?.textContent.includes('59s'))
    assert.equal(await activity().count(), 1)
    await page.screenshot({ path: path.join(output, 'service-wait.png'), fullPage: true })
    checks.push('Countdown stays visible during a turn and background tool, with Stop available')
    await emit({ type: 'tool', callId: 'same-command', toolName: 'Shell command', status: 'completed', durationMs: 25000, summary: 'Synthetic command finished', output: 'Synthetic output\nFinished\n' })
    await emit({ type: 'status', text: 'Velo is reviewing the Velorn tool results…' })
    await page.waitForFunction(() => document.querySelector('[data-testid="agent-activity"]')?.dataset.state === 'working')
    assert.equal(await input().inputValue(), 'Keep this next draft while the request waits.')
    assert.equal((await snapshot()).requests.length, 1)
    assert.equal(await page.locator('[data-activity-id="tool:same-command"]').count(), 1)
    checks.push('Resume does not resubmit the user message or duplicate the command row/draft')
    await emit({ type: 'status', waitingFor: 'velo-service', text: 'Velo is busy. Continuing in 2s… Stop to cancel.' })
    await page.waitForFunction(() => document.querySelector('[data-testid="agent-activity"]')?.dataset.state === 'service-wait')
    await button('Stop response').click()
    await activity().waitFor({ state: 'detached' })
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === request.requestId))
    await emit({ type: 'status', waitingFor: 'velo-service', text: 'Stale service countdown must not return.' })
    assert.equal(await activity().count(), 0)
    assert.equal(await input().inputValue(), 'Keep this next draft while the request waits.')
    checks.push('Stop cancels waiting and ignores stale events without changing the next draft')
    assert.deepEqual((await snapshot()).authored, baseline)
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    console.log(JSON.stringify({ success: true, checks, output, realProviderRequests: 0 }, null, 2))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
    console.error(output); throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
