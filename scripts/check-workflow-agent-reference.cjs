// Real agent composer and persistent dock, synthetic RAM-only project/provider.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5206')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw new Error('Use an isolated loopback fixture')
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage(), errors = [], blocked = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|api|v1)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const composer = () => page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const state = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const stage = entry => page.evaluate(entry => window.connectedAgentTest.stageWorkflow(entry), entry)
  const tick = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const entry = { id: 'tpl-mcp-portrait', title: 'My portrait animation', filePath: '/private/original.json' }
  let groups = 0
  const pass = text => console.log(`PASS ${++groups}: ${text}`)
  try {
    await page.goto(new URL('/tests/fixtures/connected-agent.html?dock=1&strict=1', base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready && window.connectedAgentTest.stageWorkflow)
    await tick()
    const baseline = await state()
    assert.equal((await stage(entry)).success, true)
    await composer().waitFor()
    assert.match(await composer().inputValue(), /Workflow ID: tpl-mcp-portrait/)
    assert.doesNotMatch(await composer().inputValue(), /private/)
    assert.equal((await state()).requests.length, 0)
    pass('Closed agent dock opens with a named draft reference, no provider request or file path')
    await composer().fill('Local only please. Keep my exact draft.  ')
    await button('ComfyUI').click()
    assert.equal((await stage(entry)).success, true)
    await tick()
    const text = await composer().inputValue()
    assert.ok(text.startsWith('Local only please. Keep my exact draft.  \n\n'))
    await stage(entry); await tick()
    assert.equal(await composer().inputValue(), text)
    pass('Preserves existing draft and avoids duplicate references across workspace navigation')
    await button('Assistant settings').click()
    await stage({ id: 'my-workflow:upscale', title: 'My upscale workflow' }); await tick()
    assert.equal(await button('Assistant settings').getAttribute('aria-expanded'), 'false')
    assert.equal(await composer().evaluate(node => document.activeElement === node), true)
    assert.match(await composer().inputValue(), /my-workflow:upscale/)
    pass('Returns from settings to composer without granting tools, image sharing or full access')
    const staged = await composer().inputValue()
    assert.equal((await stage({ id: '../../secret' })).success, false)
    await tick(); assert.equal(await composer().inputValue(), staged)
    await composer().fill('x'.repeat(11999))
    assert.equal((await stage(entry)).success, false)
    assert.equal((await composer().inputValue()).length, 11999)
    pass('Rejects invalid references and overlong drafts without losing user text')
    await composer().fill('Inspect this synthetic project; do not edit.')
    await button('Send message').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().requests.length === 1)
    assert.equal((await stage(entry)).success, false)
    const request = (await state()).requests.at(-1)
    assert.equal(request.toolsEnabled, false)
    await page.evaluate(requestId => window.connectedAgentTest.settle(requestId, { success: true, text: 'Synthetic review complete.' }), request.requestId)
    await button('Stop response').waitFor({ state: 'hidden' })
    pass('Cannot inject a reference into an in-flight turn; normal explicit Send remains required')
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(true)); await tick()
    assert.equal((await stage(entry)).success, false)
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(false)); await tick()
    assert.deepEqual((await state()).authored, baseline.authored)
    assert.equal((await state()).forbiddenCalls.length, 0)
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    pass('Export priority holds; no project, timeline, asset, undo, permission or external network writes')
    console.log(JSON.stringify({ success: true, groups }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
