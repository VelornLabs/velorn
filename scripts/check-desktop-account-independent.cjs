// Real account controller + panel; synthetic IPC and RAM-only state. No real
// sign-in, account writes, entitlement updates, provider calls or external IO.
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
;(async()=>{
 const {createServer}=await import('vite'),server=await createServer({root:path.resolve(__dirname,'..'),server:{host:'127.0.0.1',port:0,hmr:false}})
 await server.listen();const origin=`http://127.0.0.1:${server.httpServer.address().port}`
 const output=await fs.mkdtemp(path.join(os.tmpdir(),'velorn-independent-account-'))
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/google-chrome'}),page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[],blocked=[]
 page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():(blocked.push(r.request().url()),r.abort()))
 const panel=page.getByRole('dialog',{name:'Your Velorn account'}),button=name=>panel.getByRole('button',{name,exact:true})
 const calls=()=>page.evaluate(()=>window.desktopAccountFixture.calls)
 const mutations=async()=> (await calls()).filter(c=>c.method==='desktop-account')
 const open=async()=>{if(!await panel.count())await page.getByRole('button',{name:'Velorn account',exact:true}).click()}
 const state=async(mode,project=false)=>{await page.evaluate(([m,p])=>window.desktopAccountFixture.setState(m,p),[mode,project]);await open()}
 try {
  await page.goto(origin+'/tests/fixtures/desktop-account.html?independent=1');await open()
  await button('Sign in').waitFor();assert.equal(await button('Sign in').isEnabled(),true)
  assert.equal(await button('Stop phone sharing').count(),0)
  assert.equal((await calls()).some(c=>c.method==='attach'||c.method==='request-agent'),false)
  await button('Rename').click();await panel.getByLabel('Computer name',{exact:true}).fill('Welcome desktop')
  await button('Sign in').click();await button('Waiting for sign-in…').waitFor()
  assert.deepEqual((await mutations())[0],{method:'desktop-account',action:'sign-in',name:'Welcome desktop',userActivated:true})
  console.log('PASS: Welcome sign-in uses remembered/optional name, a user gesture, and no project/phone snapshot')
  const beforeStatusChecks=(await mutations()).length
  await state('paused-running',true)
  await panel.getByText('Signed in. Phone sharing is off.',{exact:true}).waitFor()
  assert.equal(await button('Enable phone sharing').isVisible(),true)
  assert.equal(await button('Stop phone sharing').count(),0)
  assert.equal(await button('Stop private-link sharing').count(),0)
  await page.screenshot({path:path.join(output,'service-running-sharing-off.png')})
  await state('private-only',true)
  await panel.getByText('Account phone sharing is off. Private-link phone sharing is on.',{exact:true}).waitFor()
  assert.equal(await button('Enable account phone sharing').isVisible(),true)
  assert.equal(await button('Stop private-link sharing').isVisible(),true)
  assert.equal(await button('Stop phone sharing').count(),0)
  assert.equal((await mutations()).length,beforeStatusChecks)
  console.log('PASS: Background service is not shown as sharing; actual private-link sharing is explicit; no settings mutated')
  await state('paused');await panel.getByText('Available for this account',{exact:true}).waitFor()
  assert.equal(await button('Sign out').isEnabled(),true);assert.equal(await button('Enable phone sharing').isEnabled(),true)
  await page.screenshot({path:path.join(output,'welcome-signed-in-phone-off.png')})
  await button('Enable phone sharing').click();await button('Stop phone sharing').waitFor()
  await button('Stop phone sharing').click();await panel.getByText('Signed in. Phone sharing is off.',{exact:true}).waitFor()
  await panel.getByText('Available for this account',{exact:true}).waitFor()
  assert.equal(await panel.getByText('Jaime Example',{exact:true}).count(),1)
  console.log('PASS: Velo and signed-in identity remain available with phone sharing off, without a project')
  await panel.getByText('Connected devices · 2',{exact:true}).click()
  await panel.locator('li').filter({hasText:'Fixture Android'}).getByRole('button',{name:'Disconnect'}).click()
  await panel.getByText('Fixture Android',{exact:true}).waitFor({state:'hidden'})
  assert.equal(await panel.getByText('Fixture iPhone',{exact:true}).count(),1)
  console.log('PASS: Paused device removal targets only the selected fixture device')
  await page.evaluate(()=>window.desktopAccountFixture.vee({success:true,provider:'luna',available:false,status:'not-eligible'}))
  await button('Refresh Velo availability').click();await panel.getByText('Velo access has not been enabled for this account',{exact:true}).waitFor()
  assert.match(await panel.innerText(),/Verified accounts can receive a free starter allowance while launch funding is available/)
  assert.match(await panel.innerText(),/No automatic refills/)
  assert.doesNotMatch(await panel.innerText(),/\$|USD|dollar/i)
  assert.equal(await panel.getByRole('link',{name:'accounts@velorn.ai'}).count(),1)
  console.log('PASS: Missing allowance is distinct from connectivity and offers account help without granting credit')
  await page.evaluate(()=>window.desktopAccountFixture.accountDecision('cancel'))
  const before=(await mutations()).length
  await button('Sign out').click();await button('Switch account').click()
  assert.equal((await mutations()).length,before);assert.equal(await panel.getByText('Jaime Example',{exact:true}).count(),1)
  await page.evaluate(()=>window.desktopAccountFixture.accountDecision('accept'))
  await button('Sign out').click();await button('Sign in').waitFor()
  await panel.getByText('Fixture desktop',{exact:true}).waitFor()
  assert.equal(await button('Stop phone sharing').count(),0)
  console.log('PASS: Cancelled account actions preserve identity; confirmed sign-out keeps the computer name')
  await state('busy',true);assert.equal(await button('Sign out').isDisabled(),true)
  await page.keyboard.press('Escape');await panel.waitFor({state:'hidden'})
  assert.equal(await page.getByRole('button',{name:'Velorn account',exact:true}).evaluate(e=>e===document.activeElement),true)
  assert.deepEqual(errors,[]);assert.deepEqual(blocked,[])
  assert.deepEqual(await page.evaluate(()=>window.desktopAccountFixture.forbiddenCalls),[])
  console.log('PASS: Busy protection and dialog focus retained; no inference or unrelated operations. Artifacts: '+output)
 }finally{await browser.close();await server.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
