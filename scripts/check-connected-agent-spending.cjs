// Synthetic device-policy UI only. No native settings, account, provider,
// generation, filesystem or external network operations are connected here.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.username || base.password) throw new Error('Loopback fixture only')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-agent-spending-'))
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, serviceWorkers: 'block' })
  const page = await context.newPage(), errors = [], blocked = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|view|ws|v1|api)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const checkbox = name => page.getByRole('checkbox', { name, exact: true })
  const select = page.getByRole('combobox', { name: 'Generation spending', exact: true })
  const badge = page.getByRole('status', { name: 'Generation spending status', exact: true })
  const composer = page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const openSettings = async () => {
    if (await button('Assistant settings').getAttribute('aria-expanded') !== 'true') await button('Assistant settings').click()
    if (!await page.locator('.ca-generation-options').evaluate(e => e.open)) await page.getByText('Generation and performance', { exact: true }).click()
    // These legacy regressions intentionally exercise the individual controls.
    if (!await page.locator('.ca-more-options').evaluate(node => node.open)) await page.locator('.ca-more-options > summary').click()
    const advanced = page.locator('summary').filter({ hasText: /^Access options$/ })
    if (!(await advanced.evaluate(node => node.parentElement.open))) await advanced.click()
  }
  const back = async () => { if (await button('Back to chat').isVisible()) await button('Back to chat').click() }
  const currentPolicy = async policy => {
    await page.waitForFunction(expected => document.querySelector('[aria-label="Generation spending"]')?.value === expected, policy)
  }
  const policyCalls = async () => (await snapshot()).calls.filter(call => call.method === 'spending.setPolicy')
  const navigate = async query => {
    await page.goto(new URL(`/tests/fixtures/connected-agent.html${query || ''}`, base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    await composer.waitFor()
  }
  let groups = 0
  const pass = label => console.log(`PASS ${++groups}: ${label}`)
  try {
    await navigate()
    const baseline = (await snapshot()).authored
    await currentPolicy('local-only')
    assert.match(await badge.innerText(), /Velorn-managed generation · Local only/)
    await openSettings()
    assert.equal(await select.isEnabled(), true)
    assert.equal((await policyCalls()).length, 0)
    await page.locator('summary').filter({ hasText: /^Spending details$/ }).click()
    const copy = await page.locator('.ca-generation-spending').innerText()
    for (const phrase of ['Local only (default)', 'Ask before cloud', 'each cloud or unverified submission', 'all Velorn-managed generation', 'not Codex chat billing', 'not a global spending cap', 'direct ComfyUI']) assert.ok(copy.includes(phrase), phrase)
    pass('Native local-only default is read without mutation; scope and per-submission approval are explicit')

    await page.evaluate(() => { window.connectedAgentTest.setHoldSpending(true); window.connectedAgentTest.setSpendingResponse({ success: true, cancelled: true }) })
    await select.selectOption('ask-cloud'); await frame()
    assert.equal(await select.inputValue(), 'local-only'); assert.equal(await select.isDisabled(), true)
    assert.equal(await button('New chat').isDisabled(), true)
    assert.equal(await page.getByRole('combobox', { name: 'Assistant' }).isDisabled(), true)
    assert.equal(await checkbox('Full computer access (experimental)').isDisabled(), true)
    await back(); await composer.fill('This message must not start during permission confirmation.')
    assert.equal(await button('Send message').isDisabled(), true)
    await composer.press('Enter'); assert.equal((await snapshot()).requests.length, 0)
    await page.evaluate(() => { window.connectedAgentTest.releaseSpending(); window.connectedAgentTest.setHoldSpending(false) })
    await openSettings(); await page.getByRole('status').filter({ hasText: 'Generation spending was not changed.' }).waitFor()
    assert.equal(await select.inputValue(), 'local-only')
    pass('Pending native confirmation never displays a relaxed policy; cancellation preserves the previous policy')

    await page.evaluate(() => window.connectedAgentTest.setSpendingResponse(null))
    await select.selectOption('ask-cloud'); await currentPolicy('ask-cloud')
    assert.equal((await snapshot()).spendingPolicy, 'ask-cloud')
    await back(); assert.match(await badge.innerText(), /Ask before cloud/)
    await button('New chat').click(); await currentPolicy('ask-cloud')
    await button('Storyboard').click(); await currentPolicy('ask-cloud')
    await button('Editor').click(); await currentPolicy('ask-cloud')
    await openSettings(); await page.getByRole('combobox', { name: 'Assistant' }).selectOption('lmstudio'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click()
    await currentPolicy('ask-cloud')
    await page.evaluate(() => window.connectedAgentTest.switchProject('beta')); await currentPolicy('ask-cloud')
    await page.evaluate(() => window.connectedAgentTest.switchProject('alpha')); await currentPolicy('ask-cloud')
    await openSettings(); await page.getByRole('combobox', { name: 'Assistant' }).selectOption('codex'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click(); await currentPolicy('ask-cloud')
    assert.equal((await policyCalls()).length, 2)
    assert.equal(/generationSpending|ask-cloud|local-only/.test(JSON.stringify((await snapshot()).storage)), false)
    pass('Policy is shared across chat/workspace/provider/project changes without renderer preference or history persistence')

    await openSettings(); await select.selectOption('local-only'); await currentPolicy('local-only')
    await checkbox('Velorn tools').check(); await checkbox('Full computer access (experimental)').check()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant))
    assert.equal(await checkbox('Full computer access (experimental)').isChecked(), true)
    await select.selectOption('ask-cloud'); await currentPolicy('ask-cloud')
    await select.selectOption('local-only'); await currentPolicy('local-only')
    assert.equal(await checkbox('Full computer access (experimental)').isChecked(), true)
    const fullAccessDetails = page.locator('.ca-full-access-details')
    if (!(await fullAccessDetails.evaluate(node => node.open))) await fullAccessDetails.locator('summary').click()
    assert.match(await fullAccessDetails.innerText(), /Velorn-managed generation still follows Generation spending/)
    assert.match(await page.locator('.ca-approval-help').innerText(), /Generation spending stays separate/)
    assert.match(await fullAccessDetails.innerText(), /Direct computer commands can bypass those spending controls/)
    const warning = await page.locator('.ca-settings .ca-full-access-consent').innerText()
    assert.match(warning, /Full access · automatic/)
    assert.match(warning, /Learn more/)
    assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
    await back()
    assert.equal(await page.locator('.ca-full-access-badge').isVisible(), false)
    assert.equal(await page.getByTestId('agent-approval-status').isVisible(), false)
    assert.ok((await snapshot()).fullAccessGrant)
    pass('Full access remains enabled; settings retain status and managed-gate/direct-tool warnings without permanent chat banners')

    await composer.fill('Synthetic pending agent turn.'); await button('Send message').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().requests.length > 0)
    await openSettings(); assert.equal(await select.isDisabled(), true)
    await button('Stop response').click(); await frame()
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(true)); await frame()
    assert.equal(await select.isDisabled(), true)
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(false)); await frame()
    await checkbox('Full computer access (experimental)').uncheck()
    await page.evaluate(() => window.connectedAgentTest.setHoldFullAccess(true))
    await checkbox('Full computer access (experimental)').click(); await frame()
    assert.equal(await select.isDisabled(), true)
    await page.evaluate(() => { window.connectedAgentTest.releaseFullAccess(); window.connectedAgentTest.setHoldFullAccess(false) })
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant)); await frame()
    assert.equal(await select.isEnabled(), true)
    pass('Busy turns, export priority and pending full-access confirmation disable spending changes')

    await page.evaluate(() => window.connectedAgentTest.setSpendingResponse({ success: false, error: 'Synthetic settings write failed.' }))
    await select.selectOption('ask-cloud')
    await page.locator('.ca-spending-error').waitFor(); assert.equal(await select.isDisabled(), true)
    assert.equal(await select.inputValue(), '')
    await back(); assert.match(await badge.innerText(), /restart required/)
    await openSettings(); await page.evaluate(() => window.connectedAgentTest.setSpendingResponse(null))
    await button('Check spending protection').click(); await currentPolicy('local-only')
    await page.evaluate(() => window.connectedAgentTest.emitSpending({ success: true, policy: 'ask-cloud', scope: 'global' }))
    await frame(); assert.equal(await select.isDisabled(), true)
    await button('Check spending protection').click(); await currentPolicy('local-only')
    pass('Failed writes and malformed status never claim protection; explicit native recheck restores verified status')

    await back(); await button('Close assistant panel').click()
    assert.equal((await snapshot()).spendingListenerCount, 0)
    await page.evaluate(() => window.connectedAgentTest.setHoldSpendingStatus(true))
    await button('Open agent').click(); await frame()
    await page.evaluate(() => window.connectedAgentTest.emitSpending({ success: true, policy: 'ask-cloud', scope: 'velorn-managed' }))
    await currentPolicy('ask-cloud')
    await page.evaluate(() => { window.connectedAgentTest.releaseSpendingStatus(); window.connectedAgentTest.setHoldSpendingStatus(false) })
    await frame(); await currentPolicy('ask-cloud')
    assert.equal((await snapshot()).spendingListenerCount, 2, 'Policy status and remembered-local-workflow settings each own one listener')
    pass('Native change events win over late initial reads; policy and remembered-workflow subscriptions clean up on unmount')

    for (const width of [900, 760]) {
      await page.setViewportSize({ width, height: 700 }); await openSettings()
      await page.locator('.ca-generation-spending').scrollIntoViewIfNeeded()
      const geometry = await page.locator('.ca-generation-spending').evaluate(node => ({ client: node.clientWidth, scroll: node.scrollWidth }))
      assert.ok(geometry.scroll <= geometry.client + 1)
      await page.screenshot({ path: path.join(output, `settings-${width}.png`), fullPage: true })
      await back(); assert.equal(await badge.isVisible(), true)
    }
    assert.deepEqual((await snapshot()).authored, baseline)
    const devicePolicy = (await snapshot()).spendingPolicy
    await context.addInitScript(policy => { window.__connectedAgentFixtureSpending = policy }, devicePolicy)
    await navigate(); await currentPolicy(devicePolicy)
    assert.equal((await policyCalls()).length, 0)
    pass('Narrow UI fits, authored state remains unchanged, and a new renderer uses the native policy without resetting it')

    await navigate('?legacySpending=1'); await openSettings()
    assert.equal(await select.isDisabled(), true)
    assert.equal(await select.inputValue(), '')
    assert.match(await page.locator('.ca-spending-error').innerText(), /Fully quit and reopen Velorn/)
    await back(); assert.match(await badge.innerText(), /restart required/)
    assert.doesNotMatch(await badge.innerText(), /Local only|Ask before cloud/)
    await openSettings(); await checkbox('Velorn tools').check(); await checkbox('Full computer access (experimental)').check()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant))
    await fullAccessDetails.locator('summary').click()
    assert.match(await page.locator('.ca-generation-spending').innerText(), /Spending protection is unverified; restart before generating/)
    assert.match(await fullAccessDetails.innerText(), /Direct computer commands can bypass those spending controls/)
    assert.match(await page.locator('.ca-full-access-active').innerText(), /Full access · automatic/)
    assert.equal((await policyCalls()).length, 0)
    pass('Old preload fails visibly with restart required, never a fake Local only badge')

    assert.deepEqual(errors, []); assert.deepEqual(blocked, []); assert.deepEqual((await snapshot()).forbiddenCalls, [])
    pass('No real native settings, provider, auth, external network or generation operations ran')
    console.log(`Artifacts: ${output}`)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
