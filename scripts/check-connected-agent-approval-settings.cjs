// Actual renderer in a RAM-only fixture. Native confirmation and provider
// responses are deterministic mocks; no project IO or live tool is executed.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.username || base.password) throw new Error('Loopback fixture only')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-agent-approval-settings-'))

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  const page = await context.newPage(), errors = [], blocked = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|view|ws|v1|api|system_stats)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const composer = page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const status = page.getByTestId('agent-approval-status')
  const section = page.locator('.ca-editing-approvals')
  const settings = page.locator('.ca-settings')
  const accessOptions = page.locator('summary').filter({ hasText: /^Access options$/ })
  const ask = page.getByRole('radio', { name: 'Ask first', exact: true })
  const auto = page.getByRole('radio', { name: 'Auto-approve editing', exact: true })
  const mode = name => settings.getByRole('button', { name, exact: true })
  const conversations = page.getByRole('combobox', { name: 'Conversation', exact: true })
  const provider = page.getByRole('combobox', { name: 'Assistant selection', exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const back = async () => { if (await button('Back to chat').isVisible()) await button('Back to chat').click(); await frame() }
  const openSettings = async () => { if (await button('Assistant settings').getAttribute('aria-expanded') !== 'true') await button('Assistant settings').click(); await frame() }
  const permissionCalls = async () => (await snapshot()).calls.filter(call => ['approveTool', 'setFullAccess', 'spending.setPolicy'].includes(call.method))
  const openApprovalSettings = async key => {
    const before = await permissionCalls()
    await openSettings()
    await status.focus()
    if (key) await page.keyboard.press(key)
    else await status.click()
    await section.waitFor(); await frame()
    assert.equal(await section.evaluate(node => node.closest('details') === null), true, 'Approval choices are directly available, not buried under advanced options')
    assert.equal(await button('Assistant settings').getAttribute('aria-expanded'), 'true')
    assert.equal(await section.evaluate(node => document.activeElement === node), true, 'Focus moves directly to editing approvals')
    assert.equal(await section.evaluate(node => {
      const rect = node.getBoundingClientRect()
      const parent = node.closest('.ca-settings').getBoundingClientRect()
      return rect.top >= parent.top - 1 && rect.top < parent.bottom && rect.left >= parent.left - 1
    }), true, 'The settings scroller reveals the approval section')
    assert.deepEqual(await permissionCalls(), before, 'Inspecting settings does not grant or decide anything')
  }
  const send = async text => {
    await back(); const before = (await snapshot()).requests.length
    await composer.fill(text); await button('Send message').click()
    await page.waitForFunction(count => window.connectedAgentTest.snapshot().requests.length > count, before)
    return (await snapshot()).requests.at(-1)
  }
  const settle = async request => {
    await page.evaluate(requestId => window.connectedAgentTest.settle(requestId, { success: true, text: 'Synthetic approval-settings reply only.' }), request.requestId)
    await button('Stop response').waitFor({ state: 'hidden' }); await frame()
  }
  let groups = 0
  const pass = label => console.log(`PASS ${++groups}: ${label}`)
  try {
    await page.goto(new URL('/tests/fixtures/connected-agent.html?dock=1', base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    const baseline = (await snapshot()).authored
    await button('Assistant').click(); await composer.waitFor()
    assert.equal(await status.innerText(), 'Chat only')
    assert.equal(await status.isVisible(), false, 'Routine permissions stay inside settings')
    assert.equal(await page.locator('.ca-chat [data-testid="agent-approval-status"]').count(), 0)
    assert.equal(await page.locator('.ca-chat input[type="radio"]').count(), 0)
    assert.equal(await page.locator('.ca-chat .ca-approval-help').count(), 0)
    await composer.fill('Retain this draft while I inspect permissions.')
    const initialConversation = await conversations.inputValue()
    await openSettings()
    assert.equal(await accessOptions.evaluate(node => node.parentElement.open), false)
    assert.equal(await section.isVisible(), true, 'Approval choices are visible on the ordinary settings screen')
    assert.equal(await mode('Chat only').count(), 1, 'Chat only is an explicit mode alongside project work')
    for (const name of ['Work in Velorn', 'Full access']) await mode(name).waitFor()
    assert.equal((await snapshot()).fullAccessGrant, null)
    await back()
    await openApprovalSettings('Enter')
    assert.equal(await ask.isChecked(), true); assert.equal(await auto.isDisabled(), true)
    assert.equal(await page.locator('summary').filter({ hasText: /^Advanced permissions$/ }).count(), 0)
    await back()
    assert.equal(await composer.inputValue(), 'Retain this draft while I inspect permissions.')
    assert.equal(await conversations.inputValue(), initialConversation)
    assert.equal((await snapshot()).requests.length, 0)
    pass('Chat has no routine permission indicators; Enter on the settings shortcut focuses approvals without losing the draft')

    await openSettings(); await mode('Work in Velorn').click(); await back()
    assert.equal(await status.innerText(), 'Ask before changes')
    await openApprovalSettings('Space')
    assert.equal(await ask.isChecked(), true); assert.equal(await auto.isEnabled(), true)
    await auto.check(); await back()
    assert.equal(await status.innerText(), 'Auto-approve editing')
    assert.equal(await composer.inputValue(), 'Retain this draft while I inspect permissions.')
    const automatic = await send('Synthetic automatic edit request; no real edit.')
    assert.equal(automatic.autoApproveEdits, true); assert.equal(automatic.toolsEnabled, true)
    assert.equal(automatic.fullAccess, false)
    await composer.fill('Draft survives while the mock is busy.')
    await openApprovalSettings()
    assert.equal(await ask.isDisabled(), true); assert.equal(await auto.isDisabled(), true)
    await back(); assert.equal(await composer.inputValue(), 'Draft survives while the mock is busy.')
    await settle(automatic)
    pass('Space activates the settings shortcut; choosing auto-approve affects the next mock request, while a busy turn freezes permission mutations')

    await openApprovalSettings(); await ask.check(); await back()
    assert.equal(await status.innerText(), 'Ask before changes')
    const manual = await send('Synthetic pending approval; do not execute.')
    assert.equal(manual.autoApproveEdits, false)
    await page.evaluate(requestId => window.connectedAgentTest.emitEvent({ requestId, type: 'approval', approvalId: 'settings-review',
      toolName: 'edit_timeline', arguments: { operation: 'move', clipId: 'fixture-clip', startTime: 2 },
      warnings: ['Synthetic request only; no actual timeline edit.'] }), manual.requestId)
    await button('Approve').waitFor()
    assert.equal(await page.locator('.ca-chat [data-testid="agent-approval-status"]').count(), 0, 'Pending approval keeps priority in the short chat viewport')
    for (const selector of ['.ca-selected-model', '.ca-chat-status', '.ca-spending-badge']) {
      assert.equal(await page.locator(selector).isVisible(), false, 'Disabled routine metadata gives the pending action room for review')
    }
    await openSettings(); assert.equal(await auto.isDisabled(), true)
    await back(); await button('Approve').waitFor()
    assert.equal((await snapshot()).calls.filter(call => call.method === 'approveTool').length, 0)
    await button('Deny').click(); await settle(manual)
    for (const selector of ['.ca-selected-model', '.ca-chat-status', '.ca-spending-badge']) {
      assert.equal(await page.locator(selector).isVisible(), true, 'Existing metadata returns after the explicit decision')
    }
    assert.deepEqual((await snapshot()).calls.filter(call => call.method === 'approveTool').map(call => [call.approvalId, call.approved]), [['settings-review', false]])
    pass('Ask first sends false; visiting settings with a pending approval neither auto-approves nor consumes it')

    await openApprovalSettings(); await auto.check(); await back()
    await composer.fill('Workspace and conversation draft.')
    const savedConversation = await conversations.inputValue()
    const nav = page.getByRole('navigation', { name: 'Fixture workspace modes' })
    for (const name of ['Generate', 'Stock', 'ComfyUI', 'Export', 'Discover', 'Editor', 'Storyboard']) {
      await nav.getByRole('button', { name, exact: true }).click(); await frame()
      assert.equal(await status.innerText(), 'Auto-approve editing')
      assert.equal(await composer.inputValue(), 'Workspace and conversation draft.')
      assert.equal(await conversations.inputValue(), savedConversation)
      assert.equal(await page.locator('.ca-chat input[type="radio"]').count(), 0)
    }
    await button('New chat').click(); await frame()
    assert.equal(await status.innerText(), 'Ask before changes')
    await conversations.selectOption(savedConversation); await frame()
    assert.equal(await status.innerText(), 'Auto-approve editing')
    assert.equal(await composer.inputValue(), 'Workspace and conversation draft.')
    pass('Workspace changes retain approval mode and draft; a new conversation starts Ask first and the original retains its session choice')

    await openSettings(); await provider.selectOption('lmstudio'); await button('Start LM Studio chat').click(); await frame(); await openSettings()
    await mode('Work in Velorn').click(); await page.getByLabel('Model', { exact: true }).selectOption('__custom__')
    await page.getByLabel('Custom model ID', { exact: true }).fill('fixture-local-model')
    await button('Use model').click(); await frame()
    await back(); await openApprovalSettings()
    assert.equal(await ask.isChecked(), true)
    await auto.check(); await back(); assert.equal(await status.innerText(), 'Auto-approve editing')
    const local = await send('Synthetic LM Studio request.')
    assert.equal(local.provider, 'lmstudio'); assert.equal(local.autoApproveEdits, true); assert.equal(local.fullAccess, false)
    await settle(local)
    await openSettings(); await provider.selectOption('codex'); await button('Start Codex chat').click(); await frame(); await back()
    assert.equal(await status.innerText(), 'Chat only')
    pass('Both providers use the existing edit policy; changing providers does not transfer live permission authority')

    await openSettings(); await mode('Work in Velorn').click(); await back()
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(true)); await frame()
    assert.equal(await status.innerText(), 'Ask before changes')
    await openApprovalSettings(); assert.equal(await ask.isDisabled(), true); assert.equal(await auto.isDisabled(), true)
    await back(); await page.evaluate(() => window.connectedAgentTest.setExportBusy(false)); await frame()
    await openApprovalSettings(); assert.equal(await auto.isEnabled(), true)
    pass('During export the policy remains inspectable but cannot change, and becomes editable again when export ends')

    await page.evaluate(() => { window.connectedAgentTest.setHoldFullAccess(true); window.connectedAgentTest.setFullAccessResponse({ success: true, enabled: false }) })
    await mode('Full access').click(); await frame()
    assert.equal(await ask.isDisabled(), true); assert.equal(await auto.isDisabled(), true)
    await back()
    assert.equal(await status.innerText(), 'Ask before changes', 'Pending native approval must not be advertised as granted')
    assert.equal(await status.isDisabled(), true, 'The native confirmation remains the active permission decision')
    await page.evaluate(() => { window.connectedAgentTest.releaseFullAccess(); window.connectedAgentTest.setHoldFullAccess(false) })
    await frame(); assert.equal((await snapshot()).fullAccessGrant, null)
    await openApprovalSettings()
    assert.equal(await auto.isEnabled(), true)
    pass('A pending native confirmation freezes the existing radio controls without claiming Full access or granting by navigation')

    await page.evaluate(() => window.connectedAgentTest.setFullAccessResponse(null))
    await mode('Full access').click()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant)); await frame(); await back()
    assert.equal(await status.innerText(), 'Full access · automatic')
    const grant = (await snapshot()).fullAccessGrant
    await openApprovalSettings()
    assert.equal(await page.getByRole('radio', { name: 'Ask first', exact: true, includeHidden: true }).count(), 0)
    assert.equal(await page.getByRole('radio', { name: 'Auto-approve editing', exact: true, includeHidden: true }).count(), 0)
    assert.match(await section.innerText(), /automatic/i)
    assert.match(await section.innerText(), /generation|spending/i)
    assert.deepEqual((await snapshot()).fullAccessGrant, grant)
    await page.screenshot({ path: path.join(output, 'full-access-approval-settings.png'), fullPage: true })
    await back()
    const full = await send('Synthetic Full access request only.')
    assert.equal(full.fullAccess, true); assert.equal(full.autoApproveEdits, false)
    assert.equal(full.fullAccessToken, grant.token)
    await settle(full)
    pass('Full access has a settings-only shortcut and overriding explanation instead of misleading radios; native token and send semantics are unchanged')

    await openSettings(); await mode('Work in Velorn').click(); await back()
    for (const width of [900, 760]) {
      await page.setViewportSize({ width, height: 800 }); await frame()
      assert.equal(await status.isVisible(), false)
      const composerGeometry = await page.locator('.ca-compose').evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth }))
      assert.ok(composerGeometry.scroll <= composerGeometry.width + 1, `Composer overflow at ${width}px`)
      await page.screenshot({ path: path.join(output, `chat-${width}px.png`), fullPage: true })
      await openApprovalSettings('Enter')
      const geometry = await section.evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth }))
      assert.ok(geometry.scroll <= geometry.width + 1, `Approval section overflow at ${width}px`)
      await page.screenshot({ path: path.join(output, `settings-${width}px.png`), fullPage: true })
      await back()
    }
    pass('Chat remains uncluttered and permission settings remain reachable and readable in the narrow side panel without horizontal overflow')

    assert.deepEqual((await snapshot()).authored, baseline)
    assert.equal((await snapshot()).calls.filter(call => call.method === 'spending.setPolicy').length, 0)
    assert.equal((await snapshot()).spendingPolicy, 'local-only')
    assert.deepEqual((await snapshot()).forbiddenCalls, [])
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    pass('All checks preserve authored project, assets, timeline, Undo and spending policy, with no external calls or file operations')
    console.log(`Artifacts: ${output}`)
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    console.error(`Approval-settings fixture artifacts: ${output}`)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
