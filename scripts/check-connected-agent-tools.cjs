// Renderer-only MCP consent and approval checks. Every native/provider method
// is a deterministic fixture mock; no project IO, model or tool is executed.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.username || base.password) throw new Error('Tool fixture requires loopback HTTP')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-connected-agent-tools-'))

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'en-US', serviceWorkers: 'block' })
  const page = await context.newPage(), errors = [], blockedRequests = [], groups = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    const forbidden = /^\/(?:prompt|queue|interrupt|system_stats|history|upload|view|ws|v1|api)(?:\/|$)/.test(url.pathname)
    if (url.origin === base.origin && !forbidden) return route.continue()
    blockedRequests.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const checkbox = name => page.getByRole('checkbox', { name, exact: true })
  const input = () => page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const openSettings = async () => {
    if (await button('Assistant settings').getAttribute('aria-expanded') !== 'true') await button('Assistant settings').click()
    // These legacy regressions intentionally exercise the individual controls.
    const advanced = page.locator('summary').filter({ hasText: /^Access options$/ })
    if (!(await advanced.evaluate(node => node.parentElement.open))) await advanced.click()
  }
  const backToChat = async () => { if (await button('Back to chat').isVisible()) await button('Back to chat').click() }
  const setting = async (name, method) => {
    await openSettings()
    const result = await checkbox(name)[method]()
    await backToChat()
    return result
  }
  const tab = name => page.getByRole('navigation', { name: 'Fixture workspace modes' }).getByRole('button', { name, exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const pass = text => { groups.push(text); console.log(`PASS ${groups.length}: ${text}`) }
  const emit = (request, event) => page.evaluate(event => window.connectedAgentTest.emitEvent(event), { requestId: request.requestId, ...event })
  const send = async text => {
    await backToChat()
    const count = (await snapshot()).requests.length
    await input().fill(text); await button('Send message').click()
    await page.waitForFunction(count => window.connectedAgentTest.snapshot().requests.length > count, count)
    return (await snapshot()).requests.at(-1)
  }
  const settle = async (request, text = 'Fixture tool request finished.') => {
    await page.evaluate(({ requestId, text }) => window.connectedAgentTest.settle(requestId, { success: true, text }), { requestId: request.requestId, text })
    await frame()
  }
  const approval = (request, id, extra = {}) => emit(request, { type: 'approval', approvalId: id,
    toolName: 'edit_timeline', arguments: { operation: 'move', clipId: 'fixture-clip', startTime: 2 }, ...extra })
  const decisions = async id => (await snapshot()).calls.filter(call => call.method === 'approveTool' && (!id || call.approvalId === id))
  try {
    await page.goto(new URL('/tests/fixtures/connected-agent.html?dock=1', base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    const baseline = (await snapshot()).authored
    await button('Assistant').click(); await input().waitFor()
    assert.equal(await setting('Velorn tools', 'isChecked'), false)
    assert.match(await page.locator('.ca-chat').innerText(), /Review only/)
    const review = await send('Read-only discussion without tool access.')
    assert.equal(review.toolsEnabled, false)
    assert.equal(review.vision, true)
    assert.equal(review.allowToolImages, false, 'Codex vision support is not image consent')
    assert.equal(review.expectedContext.schemaVersion, 1)
    assert.ok(review.expectedContext.projectKey.includes('PRIVATE_PATH'))
    assert.ok(!JSON.stringify({ context: review.context, messages: review.messages }).includes('PRIVATE_PATH'), 'Expected context stays outside model prompt/context')
    await approval(review, 'review-must-ignore'); await frame()
    assert.equal(await button('Approve').count(), 0)
    await settle(review)
    pass('Tools default off; native context is separated from model metadata and vision capability does not grant image consent')

    await setting('Velorn tools', 'check')
    assert.match(await page.locator('.ca-chat').innerText(), /Tools enabled/)
    const allowed = await send('Propose a timeline edit, then ask me before making it.')
    assert.equal(allowed.toolsEnabled, true)
    assert.equal(await setting('Velorn tools', 'isDisabled'), true)
    await input().fill('Draft survives approval interrupting agent settings.')
    await openSettings()
    assert.equal(await button('Assistant settings').getAttribute('aria-expanded'), 'true')
    await emit(allowed, { type: 'delta', text: 'Pending response survives inspecting settings.' })
    assert.equal(await button('Assistant settings').getAttribute('aria-expanded'), 'true', 'Ordinary stream events do not interrupt settings')
    const detailsToken = 'TRANSIENT_PRIVATE_TOOL_DETAIL'
    const largeArguments = { instruction: '<img src=x onerror="window.approvalInjected=true">', detailsToken,
      steps: [{ operation: 'move', note: 'x'.repeat(120000) }, { operation: 'delete', clipId: 'LAST_ACTION_MUST_BE_REVIEWABLE' }] }
    await approval(allowed, 'approve-once', { arguments: largeArguments,
      preview: { changes: ['Move the selected clip by two seconds.'] }, warnings: ['This changes timeline timing.'] })
    await button('Approve').waitFor()
    assert.equal(await button('Assistant settings').getAttribute('aria-expanded'), 'false', 'A pending approval returns from settings to chat for review')
    assert.equal(await input().inputValue(), 'Draft survives approval interrupting agent settings.')
    const renderedArguments = await page.locator('.ca-tool-approval pre').first().innerText()
    assert.deepEqual(JSON.parse(renderedArguments), largeArguments, 'All requested arguments remain available, including the final batch action near the native bound')
    assert.ok(renderedArguments.includes('LAST_ACTION_MUST_BE_REVIEWABLE'))
    assert.ok(!renderedArguments.includes('Details truncated.'))
    assert.equal(await page.locator('.ca-tool-approval img').count(), 0)
    assert.equal(await page.evaluate(() => window.approvalInjected), undefined)
    await page.getByText('This changes timeline timing.', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'approval-review.png'), fullPage: true, animations: 'disabled' })
    await page.evaluate(() => window.connectedAgentTest.setHoldApproval(true))
    await button('Approve').evaluate(node => { node.click(); node.click() })
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().calls.some(call => call.method === 'approveTool'))
    assert.equal((await decisions('approve-once')).length, 1)
    assert.equal((await decisions('approve-once'))[0].approved, true)
    assert.equal(await button('Approve').isDisabled(), true)
    assert.equal(await button('Deny').isDisabled(), true)
    await page.evaluate(() => { window.connectedAgentTest.releaseApproval(); window.connectedAgentTest.setHoldApproval(false) })
    await button('Approve').waitFor({ state: 'hidden' })
    await approval(allowed, 'approve-once'); await frame()
    assert.equal(await button('Approve').count(), 0, 'Replayed consumed approval stays consumed')
    await emit(allowed, { type: 'tool', callId: 'edit-1', toolName: 'edit_timeline', status: 'completed', summary: 'Synthetic edit completed; fixture did not change the project.' })
    await settle(allowed, 'Approved operation reported by the mock.')
    pass('Complete arguments near the 128 KiB bound retain the final batch action; text-only rendering, duplicate clicks and replay remain safe')

    const oversized = await send('Reject an approval whose full arguments cannot be displayed.')
    await approval(oversized, 'oversized-arguments', { arguments: { note: 'é'.repeat(70000), finalAction: 'NEVER_APPROVE_UNREVIEWABLE_ARGUMENTS' } })
    await page.getByRole('alert').filter({ hasText: 'complete requested arguments cannot be reviewed' }).waitFor()
    assert.equal(await button('Approve').isDisabled(), true, 'Byte bound accounts for multibyte UTF-8, not just character count')
    assert.equal(await button('Deny').isEnabled(), true)
    await button('Approve').evaluate(node => node.click())
    assert.equal((await decisions('oversized-arguments')).length, 0)
    await button('Deny').click(); await button('Deny').waitFor({ state: 'hidden' })
    assert.deepEqual((await decisions('oversized-arguments')).map(item => item.approved), [false])
    await settle(oversized)
    pass('Oversized UTF-8 arguments visibly disable approval while preserving an explicit Deny action')

    const denied = await send('Ask before this second change.')
    await approval(denied, 'deny-once'); await button('Deny').click()
    await button('Deny').waitFor({ state: 'hidden' })
    assert.equal((await decisions('deny-once')).length, 1)
    assert.equal((await decisions('deny-once'))[0].approved, false)
    await emit(denied, { type: 'tool', callId: 'denied-1', toolName: 'edit_timeline', status: 'denied', summary: 'Declined by the user.' })
    await settle(denied)
    pass('Deny sends a single explicit false decision and reports the tool outcome without authoring changes')

    const hidden = await send('Keep my pending approval while I inspect the timeline.')
    await approval(hidden, 'hidden-pending'); await button('Approve').waitFor()
    await input().fill('Draft retained beside a pending approval.')
    await button('Inspector').click()
    assert.equal(await button('Approve').count(), 0)
    assert.equal((await decisions('hidden-pending')).length, 0)
    await tab('Storyboard').click(); await button('Assistant').click(); await button('Approve').waitFor()
    assert.equal(await input().inputValue(), 'Draft retained beside a pending approval.')
    assert.equal((await decisions('hidden-pending')).length, 0)
    await button('Deny').click(); await settle(hidden)
    await tab('Editor').click()
    pass('Inspector/Storyboard navigation preserves draft and pending approval without deciding it automatically')

    const stopped = await send('Pause on approval so I can stop the request.')
    await approval(stopped, 'cancel-pending'); await button('Approve').waitFor()
    await button('Stop response').click(); await button('Approve').waitFor({ state: 'hidden' })
    await approval(stopped, 'late-after-stop')
    await settle(stopped, 'STALE_TOOL_RESPONSE_MUST_NOT_APPEAR')
    assert.equal((await decisions('cancel-pending')).length, 0)
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === stopped.requestId))
    assert.ok(!(await page.locator('body').innerText()).includes('STALE_TOOL_RESPONSE'))
    await page.getByText('Stopped. Any completed tool actions remain in the project; use Undo where available.', { exact: true }).waitFor()
    pass('Stop clears approval, cancels the request, ignores stale events and never falsely promises that completed edits were undone')

    const staleDecision = await send('Do not reuse a stale approval.')
    await approval(staleDecision, 'server-stale')
    await page.evaluate(() => window.connectedAgentTest.setApprovalError('The preview is stale.'))
    await button('Approve').click(); await button('Approve').waitFor({ state: 'hidden' })
    await page.getByRole('alert').filter({ hasText: 'The preview is stale.' }).waitFor()
    assert.equal((await decisions('server-stale')).length, 1)
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === staleDecision.requestId))
    await page.evaluate(() => window.connectedAgentTest.setApprovalError(''))
    await settle(staleDecision)
    pass('A rejected/uncertain approval stops the request and surfaces its error without retrying the one-use decision')

    const awaitingDecision = await send('Hold the approval transport while I stop this request.')
    await approval(awaitingDecision, 'held-decision')
    await page.evaluate(() => window.connectedAgentTest.setHoldApproval(true))
    await button('Approve').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().calls.some(call => call.method === 'approveTool' && call.approvalId === 'held-decision'))
    await button('Stop response').click()
    const afterHeld = await send('New request must survive the old approval reply.')
    await page.evaluate(() => { window.connectedAgentTest.releaseApproval(); window.connectedAgentTest.setHoldApproval(false) })
    await frame()
    assert.equal(await button('Stop response').isVisible(), true)
    assert.ok(!(await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === afterHeld.requestId))
    await approval(awaitingDecision, 'old-decision-event'); await settle(awaitingDecision, 'STALE_HELD_APPROVAL_RESULT')
    assert.equal(await button('Approve').count(), 0)
    await settle(afterHeld)
    pass('Stopping an in-flight approval submission ignores its later reply and cannot cancel or approve a newer request')

    const providerSwitch = await send('Cancel this approval when the provider changes.')
    await approval(providerSwitch, 'old-provider')
    await openSettings()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('lmstudio'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click()
    assert.equal(await setting('Velorn tools', 'isChecked'), false)
    await approval(providerSwitch, 'late-provider'); await frame()
    assert.equal(await button('Approve').count(), 0)
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === providerSwitch.requestId))
    await openSettings(); await button('Check connection').click()
    await page.waitForFunction(() => document.querySelector('select[aria-label="Model"]').value === 'fixture-model')
    assert.equal(await setting('Share images', 'isDisabled'), false, 'Phone review sharing does not require model vision')
    await setting('Velorn tools', 'check')
    const localText = await send('Local text tools still cannot share images.')
    assert.equal(localText.allowToolImages, false)
    assert.equal(localText.vision, false)
    await settle(localText)
    await setting('Vision-capable model', 'check'); await setting('Share images', 'check')
    const localImages = await send('Explicitly allow tool images with the local vision model.')
    assert.equal(localImages.allowToolImages, true)
    assert.equal(localImages.vision, true)
    await settle(localImages)
    pass('Provider changes cancel approvals and reset consent; local tool images require both vision capability and explicit image sharing')

    const projectSwitch = await send('Cancel this approval when the project changes.')
    await approval(projectSwitch, 'old-project')
    await page.evaluate(() => window.connectedAgentTest.switchProject('beta'))
    await input().waitFor(); await frame()
    assert.equal(await setting('Velorn tools', 'isChecked'), false)
    await approval(projectSwitch, 'late-project'); await settle(projectSwitch, 'STALE_PROJECT_TOOL_RESPONSE')
    assert.equal(await button('Approve').count(), 0)
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === projectSwitch.requestId))
    assert.ok(!(await page.locator('body').innerText()).includes('STALE_PROJECT_TOOL_RESPONSE'))
    await page.evaluate(() => window.connectedAgentTest.switchProject('alpha'))
    await openSettings()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('codex'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click()
    assert.equal(await setting('Velorn tools', 'isChecked'), false)
    pass('Project replacement cancels pending approval and rejects late events/results without leaking consent to the next project')

    await setting('Velorn tools', 'check')
    const activity = await send('Show a bounded transient activity list.')
    for (let index = 0; index < 65; index++) await emit(activity, { type: 'tool', callId: `activity-${index}`, toolName: 'inspect_project', status: 'running', summary: `${detailsToken}-${index}` })
    await emit(activity, { type: 'tool', callId: 'activity-64', toolName: 'inspect_project', status: 'completed', summary: 'Last inspection complete.' })
    await frame()
    assert.equal(await page.locator('.ca-tool-activity li').count(), 60)
    assert.ok((await page.locator('.ca-tool-activity li').last().innerText()).includes('Completed'))
    await approval(activity, 'unmount-pending')
    await tab('Export').click(); await frame()
    assert.equal((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === activity.requestId), false)
    assert.equal(await page.locator('.ca-tool-activity li').count(), 60)
    assert.equal(await button('Approve').count(), 1)
    // Export is now another home for the same chat, not an unmount. A genuine
    // project change still invalidates the old request and ephemeral approvals.
    await page.evaluate(() => window.connectedAgentTest.switchProject('beta')); await frame()
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === activity.requestId))
    await approval(activity, 'late-unmounted'); await settle(activity)
    await page.evaluate(() => window.connectedAgentTest.switchProject('alpha')); await frame()
    await tab('Editor').click(); await input().waitFor()
    assert.equal(await setting('Velorn tools', 'isChecked'), false)
    assert.equal(await page.locator('.ca-tool-activity li').count(), 0)
    assert.equal(await button('Approve').count(), 0)
    const state = await snapshot()
    assert.ok(!Object.values(state.storage).join('\n').includes(detailsToken), 'Approval arguments and activity summaries never persist')
    assert.deepEqual(state.authored, baseline)
    assert.deepEqual(state.forbiddenCalls, [])
    assert.deepEqual(errors, [])
    assert.deepEqual(blockedRequests, [])
    pass('Bounded transient activity and approvals survive Export navigation but clear on actual project unmount without persistence')
    await page.screenshot({ path: path.join(output, 'completed.png'), fullPage: true, animations: 'disabled' })
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ success: true, groups, errors, blockedRequests }, null, 2))
    console.log('CONNECTED_AGENT_TOOLS_RESULT ' + JSON.stringify({ success: true, groups, output }))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({ error: error.stack, errors, blockedRequests,
      snapshot: await snapshot().catch(() => null), body: await page.locator('body').innerText().catch(() => '') }, null, 2))
    console.error(`Tool fixture artifacts: ${output}`)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
