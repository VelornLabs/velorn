// Actual GuidedComfySetup UI with synthetic RAM-only bridge operations.
// This script must never target a running desktop, account or model endpoint.
'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const baseInput = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5224')
if (baseInput.protocol !== 'http:' || baseInput.hostname !== '127.0.0.1' || baseInput.username || baseInput.password
  || baseInput.pathname !== '/' || baseInput.search || baseInput.hash) throw new Error('Use an exact loopback fixture origin: http://127.0.0.1:PORT')
const base = new URL(baseInput.origin)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-guided-setup-'))

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1100, height: 900 }, serviceWorkers: 'block', locale: 'en-US' })
  const page = await context.newPage(), errors = [], blocked = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|view|ws|v1|api)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const snapshot = () => page.evaluate(() => window.guidedSetupTest.snapshot())
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const count = async method => (await snapshot()).calls.filter(call => call.method === method).length
  const inspection = value => page.evaluate(value => window.guidedSetupTest.setInspection(value), value)
  const unavailable = { success: true, state: 'unavailable', configuredPort: 8188, connections: [],
    summary: 'No ComfyUI server responded on the checked local ports. It may be stopped or use another port; this does not prove it is uninstalled.', nextActions: ['open-comfyui', 'check'] }
  const ready = { success: true, state: 'ready', configuredPort: 8188,
    summary: 'The configured ComfyUI connection is ready on port 8188.', connections: [{ port: 8188, httpBase: 'http://127.0.0.1:8188' }], nextActions: [] }
  const multiple = { ...unavailable, summary: 'Two running ComfyUI connections were found. Choose one to connect.',
    connections: [8000, 8189].map(port => ({ port, httpBase: `http://127.0.0.1:${port}`, deviceNames: ['Synthetic GPU'] })) }
  const fresh = async (query = '') => {
    await page.goto(new URL(`/tests/fixtures/guided-setup.html${query}`, base).href)
    await page.waitForFunction(() => window.guidedSetupTest?.ready)
    await button(query.includes('hub') ? 'Set up AI generation' : 'Use this computer').waitFor()
    await frame()
  }
  const local = async value => {
    if (value) await inspection(value)
    await button('Use this computer').click()
    await button('Check this computer').waitFor()
    assert.equal(await count('inspect'), 0, 'Choosing local does not automatically inspect')
  }
  const check = async () => { await button('Check this computer').click(); await frame() }
  const preserved = async baseline => {
    const current = await snapshot()
    for (const key of ['agent', 'editor', 'account', 'generation']) assert.deepEqual(current.settings[key], baseline.settings[key], `${key} must remain unchanged`)
    for (const key of ['fixture-agent-preferences', 'fixture-chat-history']) assert.equal(current.storage[key], baseline.storage[key])
    assert.deepEqual(current.forbiddenCalls, [], 'No prompts, auth, software/model downloads, process control or access escalation')
  }
  const noWrites = async () => {
    assert.equal(await count('setSetting'), 0)
    assert.equal(await count('probeConnection'), 0)
  }
  let groups = 0
  const pass = label => console.log(`PASS ${++groups}: ${label}`)
  try {
    await fresh()
    const baseline = await snapshot()
    assert.deepEqual(baseline.calls, [], 'Initial view is passive')
    await button('Skip for now').click()
    await page.getByRole('region', { name: 'editor fixture' }).waitFor()
    assert.deepEqual((await snapshot()).calls, [{ method: 'navigate', destination: 'editor' }])
    await preserved(baseline)
    pass('Passive mount and Skip reach the editor without checks, connections, sign-in, generation or downloads')

    await fresh()
    await button('Back').click()
    await page.getByRole('region', { name: 'hub fixture' }).waitFor()
    await button('Reopen guided setup').click()
    await button('Configure manually').click()
    await page.getByRole('region', { name: 'manual fixture' }).waitFor()
    assert.deepEqual((await snapshot()).calls.map(call => call.method), ['navigate', 'navigate'])
    await preserved(baseline)
    pass('Back and Configure manually are explicit navigation, without implicit setup work')

    await fresh()
    await button('Help me choose').click()
    assert.match(await page.locator('main').innerText(), /local|this computer/i)
    assert.match(await page.locator('main').innerText(), /paid|API|cloud/i)
    assert.equal(await count('inspect'), 0)
    await noWrites()
    await preserved(baseline)
    pass('Help me choose explains alternatives without probing or choosing an integration')

    await fresh()
    await button('Use paid API services').click()
    const cloudText = await page.locator('main').innerText()
    assert.match(cloudText, /local|runner/i)
    assert.match(cloudText, /hosted|Comfy Cloud/i)
    assert.match(cloudText, /credit|paid|cost|spend/i)
    assert.equal(await count('inspect'), 0)
    await noWrites()
    const credentialButton = page.getByRole('button').filter({ hasText: /API key|credential|API settings/i })
    assert.equal(await credentialButton.count(), 1)
    await credentialButton.click()
    await page.getByRole('region', { name: 'cloud fixture' }).waitFor()
    await preserved(baseline)
    pass('Paid API path distinguishes a local runner from hosted cloud and opens only the supplied credential settings')

    await fresh('?without-cloud=1')
    await button('Use paid API services').click()
    assert.equal(await page.getByRole('button').filter({ hasText: /API key|credential|API settings/i }).count(), 0)
    assert.equal(await count('inspect'), 0)
    await noWrites()
    await preserved(baseline)
    pass('A surface without a cloud-settings callback does not invent an actionable credential flow')

    await fresh()
    await local(ready)
    await page.evaluate(() => window.guidedSetupTest.hold('inspect'))
    await check()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().pending.includes('inspect'))
    assert.match(await page.locator('main').innerText(), /checking/i)
    const checks = await count('inspect')
    assert.equal(await button('Check this computer').count(), 0, 'The running check has no duplicate-submit action')
    assert.equal(await count('inspect'), checks, 'Duplicate checks cannot race')
    await page.evaluate(() => window.guidedSetupTest.release('inspect'))
    await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).waitFor()
    await noWrites()
    assert.deepEqual((await snapshot()).calls.filter(call => call.method === 'inspect'), [{ method: 'inspect', integration: 'comfyui' }])
    await preserved(baseline)
    await page.screenshot({ path: path.join(output, 'guided-ready.png'), fullPage: true })
    pass('Explicit read-only check reaches already-configured Ready without rewriting settings or starting generation')

    await fresh()
    await local(multiple)
    await check()
    await button('Connect on port 8000').waitFor()
    await button('Connect on port 8189').waitFor()
    await noWrites()
    await button('Connect on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().connection.port === 8189)
    const connected = await snapshot()
    assert.equal(connected.settings.comfyConnection.port, 8189)
    assert.deepEqual(connected.calls.filter(call => call.method === 'probeConnection').map(call => call.port), [8189])
    assert.equal(connected.calls.filter(call => call.method === 'setSetting').length, 1)
    await preserved(baseline)
    pass('Multiple candidates never auto-connect; explicit choice verifies and saves only the selected port')

    await fresh()
    await local(multiple)
    await check()
    await page.evaluate(() => window.guidedSetupTest.setProbeFailure('Synthetic selected server stopped.'))
    await button('Connect on port 8189').click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic selected server stopped.' }).waitFor()
    assert.equal(await count('setSetting'), 0)
    assert.equal((await snapshot()).connection.port, 8188)
    await page.evaluate(() => { window.guidedSetupTest.setProbeFailure(''); window.guidedSetupTest.setSaveFailure('Synthetic save denied.') })
    await button('Connect on port 8189').click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic save denied.' }).waitFor()
    assert.equal((await snapshot()).connection.port, 8188)
    assert.equal((await snapshot()).settings.comfyConnection.port, 8188)
    await page.evaluate(() => window.guidedSetupTest.setSaveFailure(''))
    await button('Connect on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().connection.port === 8189)
    await preserved(baseline)
    pass('Fresh-probe and save failures preserve the old connection and permit an explicit retry')

    await fresh()
    await local(multiple)
    await check()
    await page.evaluate(() => window.guidedSetupTest.setLauncher({ ownership: 'ours', state: 'running', httpBase: 'http://127.0.0.1:8188' }))
    await button('Connect on port 8189').click()
    await page.getByRole('alert').filter({ hasText: /managing another ComfyUI/ }).waitFor()
    await noWrites()
    await preserved(baseline)
    pass('Guided connection retains the managed-launcher switch guard')

    await fresh()
    await local(unavailable)
    await check()
    await button('Check again').waitFor()
    const absentText = await page.locator('main').innerText()
    assert.match(absentText, /stopped|another port|not prove|not tell|not mean/i)
    assert.doesNotMatch(absentText, /ComfyUI (?:is |was )?not installed\./i)
    await button('Installation help').waitFor()
    await noWrites()
    assert.equal(await count('toolSetup.plan'), 0)
    await button('Installation help').click()
    await page.getByText(/Automatic ComfyUI installation is not available/).waitFor()
    assert.equal(await count('toolSetup.plan'), 0, 'Linux must not offer or probe a Mac installer plan')
    assert.equal(await button('Download installer').count(), 0)
    assert.match(await page.locator('main').innerText(), /Linux/i)
    await button('Official ComfyUI installation guide').click()
    assert.deepEqual((await snapshot()).calls.filter(call => call.method === 'openExternalUrl').map(call => call.url), ['https://docs.comfy.org/installation/manual_install'])
    await preserved(baseline)
    await page.screenshot({ path: path.join(output, 'guided-linux-install-help.png'), fullPage: true })
    pass('No server is not treated as uninstalled; Linux installation help uses the fixed manual guide without planning or downloading an installer')

    await fresh()
    await local({ success: false, error: 'Synthetic native inspection failed.' })
    await check()
    await page.getByRole('alert').filter({ hasText: 'Synthetic native inspection failed.' }).waitFor()
    await inspection(ready)
    await button('Check again').click()
    await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).waitFor()
    assert.equal(await count('inspect'), 2)
    await noWrites()
    await preserved(baseline)
    pass('Failed inspection is explicit and recovers only after a deliberate retry')

    await fresh()
    await local(ready)
    await page.evaluate(() => window.guidedSetupTest.hold('inspect'))
    await check()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().pending.includes('inspect'))
    await button('Skip for now').click()
    await page.getByRole('region', { name: 'editor fixture' }).waitFor()
    await page.evaluate(() => window.guidedSetupTest.release('inspect'))
    await frame()
    assert.equal(await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).count(), 0)
    await button('Reopen guided setup').click()
    await button('Use this computer').waitFor()
    assert.equal(await count('inspect'), 1)
    assert.equal(await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).count(), 0)
    await noWrites()
    await preserved(baseline)
    pass('Leaving during inspection ignores its late reply; reopening does not inherit stale success or start another check')

    await fresh()
    await local(multiple)
    await check()
    await page.evaluate(() => window.guidedSetupTest.hold('probeConnection'))
    await button('Connect on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().pending.includes('probeConnection'))
    await button('Skip for now').click()
    await page.getByRole('region', { name: 'editor fixture' }).waitFor()
    await page.evaluate(() => window.guidedSetupTest.release('probeConnection'))
    await frame()
    assert.equal(await count('setSetting'), 0)
    assert.equal((await snapshot()).connection.port, 8188)
    assert.equal((await snapshot()).settings.comfyConnection.port, 8188)
    await preserved(baseline)
    pass('Leaving during delayed connection verification prevents a later settings write')

    await fresh()
    await local(multiple)
    await check()
    await page.evaluate(() => window.guidedSetupTest.hold('probeConnection'))
    await button('Connect on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().pending.includes('probeConnection'))
    await page.evaluate(() => { window.guidedSetupTest.setExportBusy(true); window.guidedSetupTest.release('probeConnection') })
    await page.getByRole('alert').filter({ hasText: /stopped before saving|export/ }).waitFor()
    assert.equal(await count('setSetting'), 0)
    assert.equal((await snapshot()).settings.comfyConnection.port, 8188)
    assert.equal((await snapshot()).connection.port, 8188)
    const probesDuringExport = await count('probeConnection')
    await button('Connect on port 8189').click()
    await page.getByRole('alert').filter({ hasText: /current export/ }).waitFor()
    assert.equal(await count('probeConnection'), probesDuringExport)
    await page.evaluate(() => window.guidedSetupTest.setExportBusy(false))
    await button('Connect on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().connection.port === 8189)
    await preserved(baseline)
    pass('An export starting during verification prevents the save; active export blocks new connection attempts until explicit retry')

    await fresh()
    await local({ ...ready, connections: [] })
    await check()
    await button('Installation help').waitFor()
    assert.equal(await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).count(), 0)
    await noWrites()
    await preserved(baseline)
    pass('A remembered Ready label without a verified responding saved endpoint cannot claim a ready connection')

    for (const malformed of [
      { ...unavailable, success: 1 },
      { ...unavailable, integration: 'lmstudio' },
      { ...unavailable, state: 'unknown' },
      { ...unavailable, configuredPort: '8188' },
      { ...unavailable, configuredPort: 70000 },
      { ...unavailable, connections: null },
      { ...unavailable, connections: [{ port: -1 }] },
      { ...unavailable, connections: Array.from({ length: 13 }, (_, index) => ({ port: 8000 + index })) },
    ]) {
      await fresh()
      await local(malformed)
      await check()
      await page.getByRole('alert').filter({ hasText: /could not be checked/ }).waitFor()
      assert.equal(await button('Installation help').count(), 0, 'Malformed native data is not evidence that no server exists')
      assert.equal(await page.getByRole('heading', { name: 'Your ComfyUI connection is ready' }).count(), 0)
      assert.equal(await page.getByRole('button', { name: /^Connect on port / }).count(), 0)
      await button('Check again').waitFor()
      await noWrites()
      await preserved(baseline)
    }
    pass('Malformed native success, integration, state, configured port and connection metadata fail closed instead of implying readiness or missing installation')

    await fresh('?hub=1')
    assert.deepEqual((await snapshot()).calls, [])
    await button('Set up AI generation').click()
    await button('Use this computer').waitFor()
    assert.equal(await count('inspect'), 0)
    await button('Back').click()
    await button('Set up AI generation').waitFor()
    await button('Set up AI generation').click()
    await button('Configure manually').click()
    await page.getByRole('region', { name: 'ComfyUI setup', exact: true }).waitFor()
    assert.equal(await count('inspect'), 0)
    await noWrites()
    await preserved(baseline)
    pass('Actual optional-tools hub starts passively, opens the guided generation flow and preserves manual setup access')

    await inspection(multiple)
    await button('Check ComfyUI setup').click()
    await button('Connect to ComfyUI on port 8189').waitFor()
    await page.evaluate(() => window.guidedSetupTest.hold('probeConnection'))
    await button('Connect to ComfyUI on port 8189').click()
    await page.waitForFunction(() => window.guidedSetupTest.snapshot().pending.includes('probeConnection'))
    await button('Back to guided setup').click()
    await button('Set up AI generation').waitFor()
    await page.evaluate(() => window.guidedSetupTest.release('probeConnection'))
    await frame()
    assert.equal(await count('setSetting'), 0)
    assert.equal((await snapshot()).settings.comfyConnection.port, 8188)
    assert.equal((await snapshot()).connection.port, 8188)
    await preserved(baseline)
    pass('Returning from manual setup during a held probe cannot save a late connection into the guided hub')

    await fresh('?hub=1')
    assert.equal(await page.evaluate(() => document.activeElement.tagName), 'BODY', 'The hub does not steal focus on mount')
    const keyboardOpen = async (label, heading) => {
      await button(label).focus()
      await page.keyboard.press('Enter')
      await page.waitForFunction(text => document.activeElement?.tagName === 'H2' && document.activeElement.textContent === text, heading)
    }
    await keyboardOpen('Set up AI generation', 'How would you like to create AI media?')
    await keyboardOpen('Configure manually', 'Connect tools')
    await keyboardOpen('Back to guided setup', 'What would you like help setting up?')
    await keyboardOpen('Set up an editing assistant', 'Choose your editing assistant')
    await keyboardOpen('Back to guided setup', 'What would you like help setting up?')
    assert.equal(await count('inspect'), 0)
    await noWrites()
    await preserved(baseline)
    pass('Keyboard hub navigation focuses each new generation/manual/assistant heading and restores the hub heading without mount-time focus theft')

    await page.setViewportSize({ width: 390, height: 844 })
    await fresh()
    await page.screenshot({ path: path.join(output, 'guided-intent-narrow.png'), fullPage: true })
    await local(multiple)
    await check()
    await button('Connect on port 8189').waitFor()
    await page.screenshot({ path: path.join(output, 'guided-candidates-narrow.png'), fullPage: true })
    const geometry = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth,
      buttons: [...document.querySelectorAll('button')].filter(node => node.offsetParent).map(node => {
        const rect = node.getBoundingClientRect(); return { label: node.textContent.trim(), left: rect.left, right: rect.right }
      }) }))
    assert.ok(geometry.scroll <= geometry.width, '390px layout has no horizontal overflow')
    assert.ok(geometry.buttons.every(item => item.left >= 0 && item.right <= geometry.width + 1), 'Every visible action stays on screen')
    await preserved(baseline)
    pass('390px intent/candidate screens stay readable and every action remains within the viewport')

    assert.deepEqual(errors, [], 'No uncaught renderer errors')
    assert.deepEqual(blocked, [], 'No external requests, provider calls or integration endpoints')
    console.log(`${groups} guided setup groups passed. Screenshots: ${output}`)
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
