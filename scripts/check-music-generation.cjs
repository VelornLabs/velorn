// Real popover, stores and importer, isolated profile/project. Optional live local GPU smoke.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium, _electron } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.VELORN_TEST_URL || 'http://127.0.0.1:5198'
const live = process.env.VELORN_MUSIC_LIVE === '1', native = process.env.VELORN_TEST_ELECTRON === '1'
async function main() {
  if (live) {
    const queue = await (await fetch('http://127.0.0.1:8189/queue')).json()
    assert.equal(queue.queue_running.length + queue.queue_pending.length, 0, 'Do not interfere with an occupied GPU queue')
  }
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-music-'))
  const project = path.join(out, 'project'); fs.mkdirSync(project)
  const browser = native ? await _electron.launch({ executablePath: require('electron'),
    args: [path.resolve(__dirname, '../tests/fixtures/inspector-electron.cjs')], env: { ...process.env, VELORN_TEST_URL: base } })
    : await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  try {
    const page = native ? await browser.firstWindow() : await browser.newPage({ viewport: { width: 1280, height: 960 } })
    if (native) await browser.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].showInactive())
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.setDefaultTimeout(15000)
    await page.routeWebSocket(url => url.hostname === new URL(base).hostname && url.port === new URL(base).port, socket => socket.close())
    await page.exposeFunction('musicTestFiles', ({ action, args }) => {
      const target = action === 'join' ? path.join(...args) : args[0]
      assert.ok(target === project || target.startsWith(project + path.sep), 'Fixture filesystem confined to temporary project')
      if (action === 'join') return target
      if (action === 'basename') return path.basename(target)
      if (action === 'mkdir') { fs.mkdirSync(target, { recursive: true }); return { success: true } }
      if (action === 'exists') return fs.existsSync(target)
      if (action === 'write') { fs.writeFileSync(target, Buffer.from(args[1])); return { success: true } }
      if (action === 'stat') return { info: { size: fs.statSync(target).size } }
      if (action === 'url') return 'data:audio/' + (target.endsWith('.flac') ? 'flac' : 'wav') + ';base64,' + fs.readFileSync(target).toString('base64')
      throw new Error('Unknown fixture bridge action')
    })
    await page.addInitScript(value => { window.musicTestProject = value }, project)
    await page.goto(base + '/tests/fixtures/music-generation.html' + (live ? '?live=1' : ''))
    await page.waitForFunction(() => Boolean(window.musicTest))
    const dialog = page.getByRole('dialog', { name: 'Generate Music', exact: true })
    const generate = dialog.getByRole('button', { name: 'Generate music', exact: true })
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Generate music')?.disabled)
    assert.equal(await dialog.getByLabel('Music model').inputValue(), 'yue2')
    assert.equal(await dialog.getByLabel('BPM', { exact: true }).count(), 0)
    assert.equal(await dialog.getByLabel('Song length', { exact: true }).inputValue(), live ? 'custom' : 'automatic')
    assert.equal(await dialog.getByLabel('Maximum length (seconds)').count(), live ? 1 : 0)
    if (!live) await dialog.getByText(/up to 6 minutes/).waitFor()
    await page.screenshot({ path: path.join(out, 'yue2.png') })
    if (!live) {
      await dialog.getByLabel('Song length', { exact: true }).selectOption('custom')
      await dialog.getByLabel('Maximum length (seconds)').fill('310')
      await dialog.getByLabel('Music style').click()
      assert.equal(await page.evaluate(() => window.musicTest.form.getState().yue2CustomDurationSeconds), 310)
      await dialog.getByLabel('Music model').selectOption('ace-step')
      assert.equal(await dialog.getByLabel('Duration (seconds)').inputValue(), '12')
      await dialog.getByLabel('BPM', { exact: true }).fill('117')
      await dialog.getByLabel('Music style').click()
      assert.equal(await page.evaluate(() => window.musicTest.form.getState().bpm), 117)
      await page.screenshot({ path: path.join(out, 'ace-step.png') })
      await dialog.getByLabel('Music model').selectOption('yue2')
      assert.equal(await dialog.getByLabel('Song length', { exact: true }).inputValue(), 'custom')
      assert.equal(await dialog.getByLabel('Maximum length (seconds)').inputValue(), '310')
      await dialog.getByLabel('Song length', { exact: true }).selectOption('automatic')
      await dialog.getByLabel('Instrumental', { exact: true }).uncheck()
      await dialog.getByLabel('Lyrics', { exact: true }).fill('[verse]\nA small melody')
      await dialog.getByLabel('Instrumental', { exact: true }).check()
      await dialog.getByRole('button', { name: 'Close music generator' }).click()
      await page.getByRole('button', { name: 'Open music', exact: true }).click()
      assert.equal(await dialog.getByLabel('Music model').inputValue(), 'yue2')
      assert.equal(await page.evaluate(() => window.musicTest.form.getState().lyrics), '[verse]\nA small melody')
      // An In/Out range must not silently choose Custom or reduce Automatic.
      await page.evaluate(() => window.musicTest.timeline.setState({ inPoint: 2, outPoint: 22 }))
      await dialog.getByRole('button', { name: 'Close music generator' }).click()
      await page.getByRole('button', { name: 'Open music', exact: true }).click()
      assert.equal(await dialog.getByLabel('Song length', { exact: true }).inputValue(), 'automatic')
      assert.equal(await dialog.getByLabel('Maximum length (seconds)').count(), 0)
      await dialog.getByLabel('Song length', { exact: true }).selectOption('custom')
      assert.equal(await dialog.getByLabel('Maximum length (seconds)').inputValue(), '310')
      assert.equal(await dialog.getByText(/Maximum length \(s\).*In\/Out/).count(), 0)
      await dialog.getByRole('button', { name: 'Close music generator' }).click()
      await page.getByRole('button', { name: 'Open music', exact: true }).click()
      await page.waitForFunction(() => document.querySelector('input[aria-label="Maximum length (seconds)"]')?.value === '20')
      assert.equal(await dialog.getByLabel('Maximum length (seconds)').inputValue(), '20')
      await dialog.getByLabel('Song length', { exact: true }).selectOption('automatic')
      await page.evaluate(() => window.musicTest.timeline.setState({ inPoint: null, outPoint: null }))
    }
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Generate music')?.disabled)
    await generate.click()
    await page.waitForFunction(() => window.musicTest.jobs().length > 0)
    console.log('Queued', await page.evaluate(() => window.musicTest.jobs()))
    const started = Date.now()
    for (;;) {
      const jobs = await page.evaluate(() => window.musicTest.refresh())
      const job = jobs[0]
      if (job.status === 'failed') throw new Error(job.error)
      if (job.status === 'completed') break
      if (Date.now() - started > 12 * 60000) throw new Error('Smoke generation timed out; queued job remains in ComfyUI')
      await page.waitForTimeout(3000)
    }
    const result = await page.evaluate(() => ({ job: window.musicTest.jobs()[0], asset: window.musicTest.assets.getState().assets[0] }))
    assert.equal(result.job.backend, 'yue2'); assert.equal(result.job.durationMode, 'maximum')
    assert.ok(result.asset.duration > 0); assert.equal(result.job.measuredDurationSeconds, result.asset.duration)
    assert.ok(result.asset.path.startsWith('assets/audio/')); assert.ok(fs.existsSync(result.asset.absolutePath))
    if (!live) {
      assert.equal(result.asset.duration, 2)
      assert.equal(result.job.lengthMode, 'automatic')
      assert.equal(result.job.durationSeconds, 360)
      assert.equal(result.job.completion.status, 'unknown')
      assert.equal(result.job.completionWarning, null)
      assert.equal(await page.evaluate(() => window.musicTest.queued[0]['95'].inputs.max_duration), 360)
      await dialog.getByText('Automatic · up to 6 min').waitFor()
    }
    await dialog.getByRole('button', { name: /Add at playhead/ }).click()
    const clips = await page.evaluate(() => window.musicTest.timeline.getState().clips)
    assert.equal(clips.length, 1); assert.equal(clips[0].startTime, 6)
    assert.equal(clips[0].duration, result.asset.duration)
    await page.evaluate(() => window.musicTest.timeline.getState().undo())
    assert.equal(await page.evaluate(() => window.musicTest.timeline.getState().clips.length), 0)
    await page.evaluate(() => window.musicTest.timeline.getState().redo())
    assert.equal(await page.evaluate(() => window.musicTest.timeline.getState().clips.length), 1)
    const audio = dialog.locator('audio')
    await audio.evaluate(element => element.play())
    await page.waitForTimeout(700)
    assert.ok(await audio.evaluate(element => element.currentTime > 0))
    await audio.evaluate(element => element.pause())
    await page.screenshot({ path: path.join(out, 'completed.png') })
    if (!live) {
      // Simulated audio at a Custom maximum warns, but stays importable at its
      // measured length. It must not be padded, trimmed or regenerated.
      await dialog.getByLabel('Song length', { exact: true }).selectOption('custom')
      await dialog.getByLabel('Maximum length (seconds)').fill('5')
      await dialog.getByLabel('Music style').click()
      await page.evaluate(() => window.musicTest.setMockAudioSeconds(5))
      await generate.click()
      await page.waitForFunction(() => window.musicTest.jobs().length === 2)
      await page.evaluate(() => window.musicTest.refresh())
      await page.waitForFunction(() => window.musicTest.jobs().every(job => job.status === 'completed'))
      await dialog.getByText('This take is at the 5-second limit and may be unfinished. Listen to the ending.').waitFor()
      const capped = await page.evaluate(() => ({ job: window.musicTest.jobs()[0], count: window.musicTest.queued.length }))
      assert.equal(capped.job.lengthMode, 'custom')
      assert.equal(capped.job.measuredDurationSeconds, 5)
      assert.equal(capped.job.completion.status, 'limit-reached')
      assert.equal(capped.count, 2)
      await page.screenshot({ path: path.join(out, 'custom-limit-warning.png') })
      await page.evaluate(() => { window.musicTest.setOffline(true) })
      await dialog.getByRole('button', { name: 'Close music generator' }).click()
      await page.getByRole('button', { name: 'Open music', exact: true }).click()
      await dialog.getByText('Connect ComfyUI to generate music.', { exact: false }).waitFor()
      assert.ok(await generate.isDisabled())
      await page.evaluate(() => window.musicTest.setOffline(false))
      await dialog.getByRole('button', { name: 'Check again' }).click()
      await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Generate music')?.disabled)
      await page.evaluate(() => window.musicTest.setMissing(true))
      await dialog.getByRole('button', { name: 'Close music generator' }).click()
      await page.getByRole('button', { name: 'Open music', exact: true }).click()
      await dialog.getByText('Update ComfyUI to add the required music nodes, then check again.', { exact: false }).waitFor()
      assert.ok(await generate.isDisabled())
      assert.equal(await dialog.getByRole('button', { name: 'Download model', exact: true }).count(), 0)
      await page.evaluate(() => window.musicTest.setMissing(false))
      await dialog.getByRole('button', { name: 'Check again' }).click()
      await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Generate music')?.disabled)
      await page.evaluate(() => window.musicTest.project.setState({ currentProjectHandle: null }))
      await dialog.getByText('Create or open a project to save generated music.', { exact: true }).waitFor()
      assert.ok(await generate.isDisabled())
    }
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ passed: true, native, live, output: result.asset.absolutePath,
      duration: result.asset.duration, promptId: result.job.promptId, artifacts: out }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
