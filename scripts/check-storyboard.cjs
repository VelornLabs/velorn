// Isolated real-renderer Storyboard smoke test. Requires a loopback fixture
// server with ComfyUI proxies disabled. No App, normal profile, native bridge,
// user project, model endpoint, download or generation is used.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.username || base.password) {
  throw new Error('Storyboard fixture requires a loopback HTTP server')
}
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-storyboard-'))

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'en-US', serviceWorkers: 'block' })
  const page = await context.newPage(), groups = [], errors = [], blockedRequests = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    const endpoint = /^\/(?:prompt|queue|interrupt|system_stats|history|upload|view|ws)(?:\/|$)/.test(url.pathname)
    if (url.origin === base.origin && !endpoint) return route.continue()
    blockedRequests.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const pass = label => { groups.push(label); console.log(`PASS ${groups.length}: ${label}`) }
  const snapshot = () => page.evaluate(() => window.storyboardTest.snapshot())
  const rpc = (action, payload = {}) => page.evaluate(({ action, payload }) => window.storyboardTest.runMcpAction(action, payload), { action, payload })
  const apply = async request => {
    const preview = await rpc('edit_storyboard', request)
    assert.equal(preview.previewOnly, true)
    assert.ok(preview.suggestedApplyPayload.previewToken)
    assert.ok(preview.suggestedApplyPayload.expectedContext)
    return rpc('edit_storyboard', preview.suggestedApplyPayload)
  }
  const tryApply = payload => page.evaluate(async payload => {
    try { return { result: await window.storyboardTest.runMcpAction('edit_storyboard', payload) } }
    catch (error) { return { error: error.message } }
  }, payload)
  const cards = () => page.getByTestId('storyboard-shot')
  const selectShot = async id => {
    const state = await snapshot(), index = state.board.shots.findIndex(shot => shot.id === id)
    assert.ok(index >= 0, 'Target shot exists'); await cards().nth(index).click()
  }
  const capture = async name => page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true, animations: 'disabled' })
  const safe = async () => {
    assert.deepEqual((await snapshot()).forbiddenCalls, [], 'No native writes, preparation, Trash, pickers or process controls')
    assert.deepEqual(blockedRequests, [], 'No external or generation endpoint requests')
    assert.deepEqual(errors, [], 'No renderer exceptions')
  }
  const noOverflow = async width => {
    await page.setViewportSize({ width, height: 1000 })
    await page.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
    const layout = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth,
      fixture: document.querySelector('[data-testid="storyboard-fixture"]').scrollWidth,
      regions: [...document.querySelectorAll('.sb-workspace, .sb-board-column, .sb-shot-details')]
        .map(node => ({ name: node.className, client: node.clientWidth, scroll: node.scrollWidth })),
      cards: [...document.querySelectorAll('[data-testid="storyboard-shot"]')].map(node => node.getBoundingClientRect().width) }))
    assert.ok(layout.document <= width + 1 && layout.fixture <= width + 1, JSON.stringify(layout))
    assert.ok(layout.cards.every(value => value > 0 && value <= width), 'All shot cards fit the viewport')
    assert.ok(layout.regions.every(region => region.scroll <= region.client + 1), JSON.stringify(layout.regions))
  }
  try {
    await page.goto(new URL('/tests/fixtures/storyboard.html?view=storyboard', base).href)
    await page.waitForFunction(() => window.storyboardTest?.ready)
    await cards().nth(3).waitFor()
    const initial = await snapshot()
    assert.equal(initial.board.shots.length, 4)
    assert.equal(initial.board.songAssetId, 'song-1')
    assert.equal(initial.board.shots[1].takes.length, 2, 'The interactive demo exposes alternate takes on initial load')
    assert.equal(initial.dirty, false)
    assert.equal(initial.historyCount, 0)
    assert.equal(await cards().count(), 4)
    await page.waitForFunction(() => [...document.querySelectorAll('[data-testid="storyboard-shot"] img')]
      .every(image => image.complete && image.naturalWidth > 0))
    await capture('01-four-shot-board')
    pass('Four synthetic reference shots render from shared authored project data without generation')

    await page.locator('.sb-board-details > summary').click()
    await page.getByLabel('Board title', { exact: true }).fill('SIGNAL / Together through technology')
    await page.getByLabel('Brief', { exact: true }).fill('A human-authored brief for a four-shot technology story.')
    await page.getByLabel('Song', { exact: true }).selectOption('song-1')
    assert.deepEqual((await snapshot()).board, initial.board, 'Board detail drafts are not authored until Save')
    await page.getByRole('button', { name: 'Save board details', exact: true }).click()
    assert.equal((await snapshot()).board.title, 'SIGNAL / Together through technology')
    assert.equal((await snapshot()).board.brief, 'A human-authored brief for a four-shot technology story.')
    assert.equal((await snapshot()).board.songAssetId, 'song-1')
    await page.locator('.sb-board-details > summary').click()
    pass('Board title, creative brief and existing-song association save explicitly into shared project data')

    await page.getByRole('button', { name: 'Add shot', exact: true }).click()
    await page.waitForFunction(() => window.storyboardTest.snapshot().board.shots.length === 5)
    let state = await snapshot(), added = state.board.shots.find(shot => !initial.board.shots.some(previous => previous.id === shot.id))
    await selectShot(added.id)
    await page.getByLabel('Shot title', { exact: true }).fill('The next chapter')
    await page.getByLabel('Shot description', { exact: true }).fill('A human edit, with a deliberate duration and review status.')
    await page.getByLabel('Duration', { exact: true }).fill('3.5')
    await page.getByLabel('Status', { exact: true }).selectOption('review')
    assert.deepEqual((await snapshot()).board, state.board, 'Local form drafts do not silently author project changes')
    await page.getByRole('button', { name: 'Save shot', exact: true }).click()
    await page.waitForFunction(id => window.storyboardTest.snapshot().board.shots.find(shot => shot.id === id)?.title === 'The next chapter', added.id)
    const edited = await snapshot(), editedShot = edited.board.shots.find(shot => shot.id === added.id)
    assert.equal(editedShot.durationSeconds, 3.5); assert.equal(editedShot.status, 'review')
    assert.equal(edited.historyCount, state.historyCount + 1, 'One Save creates one project history entry')
    assert.equal(edited.dirty, true); assert.equal(edited.timeline, initial.timeline, 'Storyboard editing never edits the timeline')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.deepEqual((await snapshot()).board, state.board)
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    assert.deepEqual((await snapshot()).board, edited.board)
    pass('Human Add/Save edits title, description, duration and status with one standard Undo/Redo step')

    await page.getByLabel('Reference asset', { exact: true }).selectOption('reference-3')
    await page.getByRole('button', { name: 'Add reference', exact: true }).click()
    assert.deepEqual((await snapshot()).board.shots.find(shot => shot.id === added.id).referenceAssetIds, ['reference-3'])
    await page.getByLabel('Take asset', { exact: true }).selectOption('take-1')
    await page.getByRole('button', { name: 'Add take', exact: true }).click()
    let takeShot = (await snapshot()).board.shots.find(shot => shot.id === added.id)
    assert.equal(takeShot.takes.length, 1); assert.equal(takeShot.selectedTakeId, takeShot.takes[0].id)
    const firstTake = takeShot.takes[0].id
    await page.getByLabel('Take asset', { exact: true }).selectOption('take-2')
    await page.getByRole('button', { name: 'Add take', exact: true }).click()
    takeShot = (await snapshot()).board.shots.find(shot => shot.id === added.id)
    assert.equal(takeShot.takes.length, 2); assert.equal(takeShot.selectedTakeId, firstTake)
    await page.getByRole('button', { name: /Select take/ }).last().click()
    takeShot = (await snapshot()).board.shots.find(shot => shot.id === added.id)
    assert.equal(takeShot.selectedTakeId, takeShot.takes[1].id)
    await capture('02-human-takes')
    pass('References and alternate takes attach existing media; first selection and explicit take choice are preserved')

    const video = await page.locator('.sb-selected-preview video').elementHandle()
    await page.waitForFunction(() => document.querySelector('.sb-selected-preview video')?.readyState >= 1)
    await video.evaluate(async node => { node.muted = true; await node.play() })
    await cards().first().click()
    assert.equal(await video.evaluate(node => node.paused && !node.hasAttribute('src')), true, 'Leaving a take stops playback and releases its source')
    await video.dispose()
    await selectShot(added.id)
    pass('Synthetic video takes decode and play; navigating away stops and releases detached previews')

    const beforeDetach = await snapshot()
    await page.getByRole('button', { name: 'Remove take Signal motion study 2.webm', exact: true }).click()
    takeShot = (await snapshot()).board.shots.find(shot => shot.id === added.id)
    assert.equal(takeShot.takes.length, 1); assert.equal(takeShot.selectedTakeId, firstTake)
    assert.deepEqual((await snapshot()).assetIds, beforeDetach.assetIds)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.deepEqual((await snapshot()).board, beforeDetach.board)
    await page.getByRole('button', { name: 'Remove reference connect-reference.png', exact: true }).click()
    assert.deepEqual((await snapshot()).board.shots.find(shot => shot.id === added.id).referenceAssetIds, [])
    assert.deepEqual((await snapshot()).assetIds, beforeDetach.assetIds)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.deepEqual((await snapshot()).board, beforeDetach.board)
    pass('Removing a selected take chooses the remaining take; detach/Undo never deletes project media')

    const beforePreview = await snapshot()
    const preview = await rpc('edit_storyboard', { operation: 'update_shot', shotId: added.id, patch: { title: 'Agent and human, one board' } })
    assert.equal(preview.previewOnly, true)
    assert.deepEqual((await snapshot()).board, beforePreview.board)
    assert.equal((await snapshot()).historyCount, beforePreview.historyCount)
    assert.equal((await snapshot()).revision, beforePreview.revision)
    await rpc('edit_storyboard', preview.suggestedApplyPayload)
    await cards().filter({ hasText: 'Agent and human, one board' }).waitFor()
    const afterApply = await snapshot(), inspected = await rpc('get_storyboard')
    assert.deepEqual(inspected.board, afterApply.board)
    assert.ok(inspected.assets.every(asset => !Object.hasOwn(asset, 'url') && !Object.hasOwn(asset, 'path')))
    await rpc('undo', { previewOnly: false }); assert.deepEqual((await snapshot()).board, beforePreview.board)
    await rpc('redo', { previewOnly: false }); assert.deepEqual((await snapshot()).board, afterApply.board)
    assert.match((await tryApply(preview.suggestedApplyPayload)).error || '', /preview|expired|used|stale|changed/i)
    pass('MCP read/preview/apply shares the visible board and standard history; previews do not mutate and tokens are one-use')

    const stale = await rpc('edit_storyboard', { operation: 'update_shot', shotId: added.id, patch: { title: 'Must not overwrite a newer edit' } })
    await page.getByLabel('Shot title', { exact: true }).fill('A newer human edit')
    await page.getByRole('button', { name: 'Save shot', exact: true }).click()
    const afterHuman = await snapshot()
    assert.match((await tryApply(stale.suggestedApplyPayload)).error || '', /stale|changed|preview|revision/i)
    assert.deepEqual((await snapshot()).board, afterHuman.board)
    assert.equal((await snapshot()).historyCount, afterHuman.historyCount)
    pass('A newer visible human edit invalidates an older MCP preview without overwriting or adding history')

    await page.getByLabel('Shot title', { exact: true }).fill('An unsaved human draft')
    await apply({ operation: 'update_shot', shotId: added.id, patch: { title: 'A newer assistant edit' } })
    await page.getByRole('button', { name: 'Reload shot', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Save shot', exact: true }).isDisabled(), true)
    assert.equal(await page.getByLabel('Shot title', { exact: true }).inputValue(), 'An unsaved human draft')
    await page.getByRole('button', { name: 'Reload shot', exact: true }).click()
    assert.equal(await page.getByLabel('Shot title', { exact: true }).inputValue(), 'A newer assistant edit')
    pass('An unsaved human form cannot silently overwrite a newer assistant edit; Reload resolves the conflict')

    const beforeDraft = await snapshot()
    await page.getByLabel('Shot description', { exact: true }).fill('Keep this unsaved idea while I explore other shots.')
    await cards().first().click()
    await selectShot(added.id)
    assert.equal(await page.getByLabel('Shot description', { exact: true }).inputValue(), 'Keep this unsaved idea while I explore other shots.')
    await page.evaluate(() => window.storyboardTest.setPanelVisible(false))
    await cards().first().waitFor({ state: 'detached' })
    await page.evaluate(() => window.storyboardTest.setPanelVisible(true))
    await selectShot(added.id)
    assert.equal(await page.getByLabel('Shot description', { exact: true }).inputValue(), 'Keep this unsaved idea while I explore other shots.')
    assert.deepEqual((await snapshot()).board, beforeDraft.board, 'Navigating an unsaved draft never authors it')
    await apply({ operation: 'update_shot', shotId: added.id, patch: { description: 'An assistant changed the shared description.' } })
    await page.getByRole('button', { name: 'Reload shot', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Save shot', exact: true }).isDisabled(), true)
    assert.equal(await page.getByLabel('Shot description', { exact: true }).inputValue(), 'Keep this unsaved idea while I explore other shots.')
    await page.getByRole('button', { name: 'Reload shot', exact: true }).click()
    assert.equal(await page.getByLabel('Shot description', { exact: true }).inputValue(), 'An assistant changed the shared description.')
    pass('Unsaved drafts survive shot navigation and panel remount while retaining conflict protection')

    const order = (await snapshot()).board.shots.map(shot => shot.id)
    await page.getByRole('button', { name: 'Move shot left', exact: true }).click()
    const moved = (await snapshot()).board.shots.map(shot => shot.id), position = order.indexOf(added.id)
    assert.equal(moved[position - 1], added.id)
    await page.getByRole('button', { name: 'Move shot right', exact: true }).click()
    assert.deepEqual((await snapshot()).board.shots.map(shot => shot.id), order)
    pass('Explicit left/right controls reorder stable shot IDs without touching timeline clips')

    const beforeRemove = await snapshot()
    await page.getByRole('button', { name: 'Delete shot', exact: true }).click()
    assert.deepEqual((await snapshot()).board, beforeRemove.board, 'Deletion waits for its explicit confirmation')
    await page.getByRole('button', { name: 'Confirm remove shot', exact: true }).click()
    assert.equal((await snapshot()).board.shots.length, 4)
    assert.deepEqual((await snapshot()).assetIds, beforeRemove.assetIds)
    assert.equal((await snapshot()).timeline, beforeRemove.timeline)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.deepEqual((await snapshot()).board, beforeRemove.board)
    pass('Confirmed shot deletion is undoable and leaves existing project media and timeline untouched')

    const beforeSave = await snapshot()
    assert.equal(await page.evaluate(() => window.storyboardTest.save()), true)
    const saved = await page.evaluate(() => window.storyboardTest.saved())
    assert.deepEqual(saved.storyboard, beforeSave.board)
    assert.doesNotMatch(JSON.stringify(saved.storyboard), /data:|blob:|\/fixture-only\//, 'Authored board contains asset IDs, not session URLs or machine paths')
    assert.equal((await snapshot()).dirty, false)
    await apply({ operation: 'update_board', patch: { title: 'Unsaved temporary title' } })
    assert.ok(await page.evaluate(() => window.storyboardTest.reopen()))
    await page.waitForFunction(title => window.storyboardTest.snapshot().board.title === title, beforeSave.board.title)
    assert.deepEqual((await snapshot()).board, beforeSave.board)
    assert.equal((await snapshot()).historyCount, 0)
    assert.ok((await snapshot()).filePaths.some(value => value.includes('/autosave/')))
    pass('Actual project save/open and autosave serialization preserve the board through RAM-only filesystem boundaries')

    const beforeSwitch = await rpc('edit_storyboard', { operation: 'update_board', patch: { title: 'Wrong project edit' } })
    await page.evaluate(() => window.storyboardTest.switchProject())
    await page.waitForFunction(() => window.storyboardTest.snapshot().board.shots.length === 0)
    assert.equal(await cards().count(), 0)
    assert.match((await tryApply(beforeSwitch.suggestedApplyPayload)).error || '', /changed|stale|project|preview|revision/i)
    assert.equal((await snapshot()).board.shots.length, 0)
    assert.equal((await snapshot()).historyCount, 0)
    await page.evaluate(() => window.storyboardTest.reopen())
    await cards().nth(4).waitFor()
    pass('Project switching clears visible old shots and refuses an apply reviewed for the previous project')

    await selectShot(added.id)
    await page.evaluate(() => { window.storyboardTest.removeAsset('take-2'); window.storyboardTest.removeAsset('reference-3'); window.storyboardTest.removeAsset('song-1') })
    const missing = await rpc('get_storyboard')
    assert.ok(missing.assets.find(asset => asset.id === 'take-2')?.missing)
    assert.ok(missing.assets.find(asset => asset.id === 'reference-3')?.missing)
    assert.ok(missing.assets.find(asset => asset.id === 'song-1')?.missing)
    await page.locator('.sb-reference-list').getByText('Missing media (reference-3)', { exact: true }).waitFor()
    await page.locator('.sb-take-list').getByText('Missing media (take-2)', { exact: true }).waitFor()
    assert.equal(missing.board.shots.find(shot => shot.id === added.id).takes.length, 2, 'Missing media keeps authored take associations recoverable')
    await capture('03-missing-media')
    pass('Missing song/reference/take media is inspectable and visibly recoverable without deleting authored associations')

    await page.evaluate(() => window.storyboardTest.reset())
    await cards().nth(3).waitFor()
    const beforeTimeline = await snapshot()
    await page.evaluate(() => window.storyboardTest.seedTimelineEdit())
    const timelineEdit = await snapshot()
    assert.equal(timelineEdit.historyCount, 0)
    assert.equal(timelineEdit.timelineHistoryCount, 1)
    assert.equal(timelineEdit.timelineHistoryIndex, -1)
    assert.equal(await page.getByRole('button', { name: 'Undo', exact: true }).isEnabled(), true)
    assert.equal(await page.getByRole('button', { name: 'Redo', exact: true }).isDisabled(), true)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.equal((await snapshot()).timeline, beforeTimeline.timeline)
    assert.equal(await page.getByRole('button', { name: 'Undo', exact: true }).isDisabled(), true)
    assert.equal(await page.getByRole('button', { name: 'Redo', exact: true }).isEnabled(), true)
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    assert.equal((await snapshot()).timeline, timelineEdit.timeline)
    assert.deepEqual((await snapshot()).board, beforeTimeline.board)
    pass('Toolbar Undo/Redo follows actual timeline history availability as well as board-only history')

    await page.evaluate(() => window.storyboardTest.reset())
    const keyboardState = await snapshot()
    await cards().nth(1).focus(); await page.keyboard.press('Enter')
    assert.equal(await page.getByLabel('Shot title', { exact: true }).inputValue(), keyboardState.board.shots[1].title)
    await page.getByLabel('Shot description', { exact: true }).focus(); await page.keyboard.press('Control+a'); await page.keyboard.press('Backspace')
    assert.equal((await snapshot()).board.shots.length, 4, 'Text editing must not trigger shot deletion')
    await page.keyboard.press('Tab')
    assert.notEqual(await page.evaluate(() => document.activeElement?.tagName), 'BODY')
    await page.getByRole('button', { name: 'Expand board', exact: true }).click()
    await page.getByRole('button', { name: 'Collapse board', exact: true }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('button', { name: 'Expand board', exact: true }).evaluate(node => node === document.activeElement), true)
    pass('Cards are keyboard-activatable and form text editing stays local without deleting shots')

    for (const width of [1440, 1100, 900, 640, 480]) {
      await noOverflow(width)
      await capture(`04-layout-${width}`)
    }
    assert.equal(await page.locator('.sb-workspace').evaluate(node => getComputedStyle(node).display), 'block', 'Narrow layout stacks board and detail regions')
    pass('Board and details fit 1440px, 1100px, 900px, 640px and stacked 480px layouts without horizontal overflow')

    await page.setViewportSize({ width: 1100, height: 700 })
    await page.evaluate(() => window.storyboardTest.setPanelHeight(320))
    const compactHeight = await page.locator('.storyboard-panel').evaluate(node => node.getBoundingClientRect().height)
    assert.equal(compactHeight, 320)
    await page.getByRole('button', { name: 'Delete shot', exact: true }).scrollIntoViewIfNeeded()
    assert.equal(await page.getByRole('button', { name: 'Delete shot', exact: true }).isVisible(), true)
    await capture('04-layout-bottom-panel-320')
    await page.getByRole('button', { name: 'Expand board', exact: true }).click()
    assert.ok(await page.locator('.storyboard-panel').evaluate(node => node.getBoundingClientRect().height > 320))
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.storyboard-panel').evaluate(node => node.getBoundingClientRect().height), compactHeight)
    assert.equal(await page.getByRole('button', { name: 'Expand board', exact: true }).evaluate(node => node === document.activeElement), true)
    await page.evaluate(() => window.storyboardTest.setPanelHeight(null))
    pass('The 320px Editor-style panel scrolls independently; Expand and Escape restore its height and keyboard focus')

    const futureBoard = { version: 99, title: 'Future authored board', futureData: { preserve: ['all', 'unknown', 'data'] }, shots: [] }
    await page.evaluate(board => window.storyboardTest.setRawStoryboard(board), futureBoard)
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByRole('button', { name: 'Add shot', exact: true }).isDisabled(), true)
    assert.equal(await cards().count(), 0)
    assert.deepEqual(await page.evaluate(() => window.storyboardTest.rawStoryboard()), futureBoard)
    const unsupported = await page.evaluate(async () => {
      try { await window.storyboardTest.runMcpAction('edit_storyboard', { operation: 'add_shot', shot: {} }); return null }
      catch (error) { return error.message }
    })
    assert.match(unsupported || '', /unsupported|version/i)
    assert.deepEqual(await page.evaluate(() => window.storyboardTest.rawStoryboard()), futureBoard)
    pass('Unsupported future boards show a read-only error and reject edits without resetting unknown project data')

    await page.evaluate(() => window.storyboardTest.reset({ empty: true }))
    await page.getByText('Start with the story.', { exact: true }).waitFor()
    assert.equal(await cards().count(), 0)
    await page.getByRole('button', { name: 'Add shot', exact: true }).click()
    await cards().first().waitFor()
    assert.equal((await snapshot()).board.shots.length, 1)
    assert.equal((await snapshot()).historyCount, 1)
    pass('An empty existing project starts with an actionable empty state and Add shot creates its first undoable shot')

    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.evaluate(() => window.storyboardTest.reset())
    const final = await snapshot()
    await selectShot(final.board.shots[1].id)
    await capture('05-demo-board')
    await safe()
    const result = { success: true, groups, output, errors, blockedRequests, snapshot: await snapshot() }
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2))
    console.log('STORYBOARD_RESULT ' + JSON.stringify({ success: true, groups, output }))
  } catch (error) {
    await capture('failure').catch(() => {})
    fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({ error: error.stack, errors, blockedRequests,
      snapshot: await snapshot().catch(() => null), body: await page.locator('body').innerText().catch(() => '') }, null, 2))
    console.error(`Storyboard fixture artifacts: ${output}`)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
