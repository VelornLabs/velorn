// Real renderer, synthetic model metadata/IPC and isolated RAM history only.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5209')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw Error('Loopback fixture required')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-agent-reasoning-'))
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1200, height: 1000 }, serviceWorkers: 'block' })
  const page = await context.newPage(), errors = [], groups = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(10000)
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(?:api|v1|prompt|queue|history|upload|view|ws)(?:\/|$)/.test(url.pathname)) return route.continue()
    return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const model = () => page.getByRole('combobox', { name: 'Model', exact: true })
  const thinking = () => page.getByRole('combobox', { name: 'Thinking level', exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const pass = text => { groups.push(text); console.log(`PASS ${text}`) }
  try {
    await page.goto(new URL('/tests/fixtures/connected-agent.html?strict=1', base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    const baseline = (await snapshot()).authored
    await page.evaluate(() => window.connectedAgentTest.setCodexModels([
      { id: 'fixture-sol', displayName: 'Fixture Sol', isDefault: true, defaultReasoningEffort: 'low', supportedReasoningEfforts: ['low','medium','high','xhigh','ultra'].map(reasoningEffort => ({reasoningEffort})) },
      { id: 'fixture-luna', displayName: 'Fixture Luna', defaultReasoningEffort: 'medium', supportedReasoningEfforts: ['low','medium'].map(reasoningEffort => ({reasoningEffort})) },
    ]))
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    await model().locator('option[value="fixture-sol"]').waitFor({ state: 'attached' })
    await model().selectOption('fixture-sol')
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    assert.equal(await thinking().inputValue(), 'medium')
    await thinking().selectOption('ultra')
    await thinking().waitFor({state:'hidden'})
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    await model().selectOption('fixture-luna')
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    assert.equal(await thinking().inputValue(), 'medium')
    assert.equal(await thinking().locator('option[value="ultra"]').count(), 0)
    await thinking().selectOption('low')
    await thinking().waitFor({state:'hidden'})
    pass('Catalog-driven levels default to Medium and unsupported Ultra disappears on model switch')
    assert.match(await page.locator('.ca-selected-model').innerText(), /fixture-luna · Light/)
    await page.getByRole('textbox', { name: 'Message your agent', exact: true }).fill('Synthetic thinking selection; do not execute tools.')
    await button('Send message').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().requests.length === 1)
    const request = (await snapshot()).requests[0]
    assert.equal(request.reasoningEffort, 'low')
    assert.equal(request.model, 'fixture-luna')
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    assert.equal(await thinking().isDisabled(), true)
    await page.evaluate(id => window.connectedAgentTest.settle(id, {success:true,text:'Synthetic Light reply.'}), request.requestId)
    await button('Back to chat').click()
    await page.getByText('Synthetic Light reply.', {exact:true}).waitFor()
    assert.match(await page.locator('.ca-requested-model').last().innerText(), /Thinking: Light/)
    pass('Frozen request carries Light explicitly; reply records it and busy picker cannot change it')
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    await thinking().selectOption('medium')
    await thinking().waitFor({state:'hidden'})
    assert.match(await page.locator('.ca-requested-model').last().innerText(), /Thinking: Light/)
    assert.match(await page.locator('.ca-selected-model').innerText(), /Medium/)
    await button('Close assistant panel').click(); await button('Open agent').click()
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    await model().locator('option[value="fixture-luna"]').waitFor({state:'attached'})
    assert.equal(await thinking().inputValue(), 'medium')
    pass('Next-message choice persists across remount without relabelling historical replies')
    await thinking().scrollIntoViewIfNeeded()
    await page.screenshot({path:path.join(output,'desktop-thinking.png'),fullPage:true})
    await button('Back to chat').click()
    await page.evaluate(() => { window.electronAPI.connectedAgent.reasoningControlVersion = undefined })
    await page.getByRole('textbox', { name: 'Message your agent', exact: true }).fill('Do not send through an outdated native connection.')
    await button('Send message').click()
    await page.getByRole('alert').filter({hasText:'Fully quit and reopen'}).waitFor()
    assert.equal((await snapshot()).requests.length, 1)
    await page.evaluate(() => { window.electronAPI.connectedAgent.reasoningControlVersion = 1 })
    pass('An old native/preload connection cannot silently ignore the selected effort')
    await button('Assistant settings').click(); if (!await page.locator('.ca-more-options').evaluate(e => e.open)) await page.locator('.ca-more-options > summary').click(); if (await page.locator('.ca-thinking-options > summary').count()) await page.locator('.ca-thinking-options > summary').evaluate(e => { e.parentElement.open = true })
    await page.getByLabel('Assistant selection', {exact:true}).selectOption('lmstudio'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click()
    assert.equal(await thinking().count(), 0)
    assert.deepEqual((await snapshot()).authored, baseline)
    assert.deepEqual(errors, [])
    pass('LM Studio remains unchanged and no project state was authored')
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({groups,errors,output},null,2))
    console.log(output)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
