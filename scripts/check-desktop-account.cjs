// Real TitleBar, account sheet and useMobileCompanion, synthetic native APIs.
// Owns its loopback Vite server/browser profile; all other traffic is blocked.
const assert=require('node:assert/strict')
const fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')

async function main() {
  const {createServer}=await import('vite')
  const server=await createServer({root:path.resolve(__dirname,'..'),server:{host:'127.0.0.1',port:0,strictPort:false,hmr:false}})
  await server.listen()
  const origin=`http://127.0.0.1:${server.httpServer.address().port}`
  const output=await fs.mkdtemp(path.join(os.tmpdir(),'velorn-desktop-account-'))
  const errors=[],blocked=[],dialogs=[],checks=[]
  let browser,page
  try {
    browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome',args:['--no-sandbox']})
    page=await browser.newPage({viewport:{width:1440,height:900}})
    page.setDefaultTimeout(8000)
    page.on('pageerror',error=>errors.push(error.message))
    page.on('dialog',async dialog=>{dialogs.push(dialog.type());await dialog.dismiss()})
    await page.route('**/*',route=>new URL(route.request().url()).origin===origin ? route.continue() : (blocked.push(route.request().url()),route.abort()))
    await page.goto(`${origin}/tests/fixtures/desktop-account.html`)
    const trigger=page.getByRole('button',{name:'Velorn account',exact:true})
    const rawTrigger=page.locator('.desktop-account-button')
    const sheet=page.getByRole('dialog',{name:'Your Velorn account',exact:true})
    const calls=()=>page.evaluate(()=>window.desktopAccountFixture.calls)
    const mutations=async()=> (await calls()).filter(call=>['connect','disconnect-device','disconnect-account','account-sign-out','account-switch-account','disable'].includes(call.method))
    const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
    const state=async(mode,hasProject=true,extra)=>{
      await page.evaluate(([mode,hasProject,extra])=>window.desktopAccountFixture.setState(mode,hasProject,extra),[mode,hasProject,extra])
      await settle()
      if(hasProject && extra?.bridge!==false)await page.waitForFunction(()=>window.desktopAccountFixture.stats().listeners===1)
    }
    const open=async()=>{await trigger.click();await sheet.waitFor()}
    const close=async()=>{if(await sheet.count()){await page.keyboard.press('Escape');await sheet.waitFor({state:'hidden'})};await settle()}
    const pass=name=>checks.push(name)
    await trigger.waitFor()
    await open()
    assert.match(await sheet.textContent(),/Open or create a project to sign in/)
    assert.match(await sheet.textContent(),/Editing, your own Codex and local LM Studio work without one/)
    assert.equal(await sheet.getByRole('button',{name:'Sign in',exact:true}).count(),0)
    assert.equal((await calls()).some(call=>call.method==='attach'),false,'No-project profile cannot mount hidden connection owner')
    assert.equal((await page.evaluate(()=>window.desktopAccountFixture.stats())).subscriptions,0)
    await page.screenshot({path:path.join(output,'signedout-no-project-1440.png')})
    await close()
    assert.equal(await trigger.evaluate(el=>el===document.activeElement),true,'Escape returns focus to avatar')
    pass('signed-out/no-project account guidance is read-only and desktop remains login-free')

    await state('signedout',true,{bridge:false})
    await open()
    const signIn=sheet.getByRole('button',{name:'Sign in',exact:true})
    await signIn.waitFor()
    assert.equal((await calls()).filter(call=>call.method==='request-agent').length,1,'Opening profile lazily requests the existing agent owner once')
    assert.equal((await page.evaluate(()=>window.desktopAccountFixture.stats())).listeners,1)
    assert.equal(await sheet.getByLabel('Computer name',{exact:true}).count(),0,'Name entry is optional, not a required sign-in step')
    assert.equal(await signIn.isEnabled(),true)
    await sheet.getByText('Fixture desktop',{exact:true}).waitFor()
    await page.screenshot({path:path.join(output,'remembered-computer-name.png')})
    await sheet.getByRole('button',{name:'Rename',exact:true}).click()
    await sheet.getByLabel('Computer name',{exact:true}).fill('Discard this edit')
    await page.evaluate(()=>window.desktopAccountFixture.emit())
    assert.equal(await sheet.getByLabel('Computer name',{exact:true}).inputValue(),'Discard this edit','Status polling does not overwrite a rename draft')
    await sheet.getByRole('button',{name:'Cancel rename',exact:true}).click()
    await sheet.getByText('Fixture desktop',{exact:true}).waitFor()
    assert.equal(await sheet.getByLabel('Computer name',{exact:true}).count(),0)
    await sheet.getByRole('button',{name:'Rename',exact:true}).click()
    await sheet.getByLabel('Computer name',{exact:true}).fill('')
    assert.equal(await signIn.isDisabled(),true)
    await sheet.getByLabel('Computer name',{exact:true}).fill('Fixture edit computer')
    await signIn.hover()
    const contrast=await signIn.evaluate(el=>{
      const style=getComputedStyle(el)
      const luminance=color=>color.match(/[\d.]+/g).slice(0,3).map(Number).map(value=>value/255).map(value=>value<=0.04045 ? value/12.92 : ((value+0.055)/1.055)**2.4).reduce((sum,value,index)=>sum+value*[0.2126,0.7152,0.0722][index],0)
      const foreground=luminance(style.color),background=luminance(style.backgroundColor)
      return (Math.max(foreground,background)+0.05)/(Math.min(foreground,background)+0.05)
    })
    assert.ok(contrast>=4.5,'Primary sign-in button text remains readable on hover')
    await page.evaluate(()=>window.desktopAccountFixture.hold('connect'))
    await signIn.click()
    await page.waitForFunction(()=>window.desktopAccountFixture.calls.some(call=>call.method==='connect'))
    assert.equal(await sheet.getByRole('button',{name:/Opening sign-in/}).isDisabled(),true)
    await sheet.getByRole('button',{name:/Opening sign-in/}).evaluate(button=>{button.click();button.click()})
    assert.equal((await mutations()).filter(call=>call.method==='connect').length,1)
    const connect=(await mutations())[0]
    assert.equal(connect.name,'Fixture edit computer')
    assert.equal(connect.automatic,true)
    assert.equal(connect.reauthenticate,true,'Desktop Sign in must not silently reuse a browser account')
    assert.equal(connect.userActivated,true)
    assert.ok(connect.scope && connect.snapshot.contextId)
    await page.evaluate(()=>window.desktopAccountFixture.release())
    await sheet.getByText('Finish signing in in your browser.',{exact:true}).waitFor()
    assert.equal(await sheet.getByRole('button',{name:'Waiting for sign-in…',exact:true}).isDisabled(),true)
    await page.screenshot({path:path.join(output,'waiting-browser-1440.png')})
    await close()
    await state('confirm-account');await open()
    await sheet.getByText('Confirm your Velorn account in the desktop prompt.',{exact:true}).waitFor()
    await close()
    await state('error');await open()
    await sheet.getByRole('button',{name:'Sign in',exact:true}).click()
    await sheet.getByText('Synthetic phone setup failed. Try again.',{exact:true}).waitFor()
    assert.equal(await sheet.getByRole('button',{name:'Sign in',exact:true}).isEnabled(),true)
    await close()
    pass('real mobile hook starts scoped native browser setup once, displays waiting/native-confirm/error and permits retry')

    await state('linked');await open()
    await sheet.getByText('Jaime Example',{exact:true}).waitFor()
    await sheet.getByText('creator@example.test',{exact:true}).waitFor()
    await sheet.getByText('Connected as',{exact:true}).waitFor()
    await sheet.getByText('Computer',{exact:true}).waitFor()
    await sheet.getByText('Available for this account',{exact:true}).waitFor()
    assert.equal((await trigger.textContent()).trim(),'JE','Avatar derives initials from native account display name')
    assert.equal(await sheet.getByText('Fixture desktop',{exact:true}).count(),1)
    assert.equal(await sheet.getByText('Ready for your phone.',{exact:true}).count(),1)
    const beforeStats=await page.evaluate(()=>window.desktopAccountFixture.stats())
    for(let i=0;i<12;i++) {await page.evaluate(()=>{window.desktopAccountFixture.rerender();window.desktopAccountFixture.emit()});await settle()}
    assert.deepEqual(await page.evaluate(()=>window.desktopAccountFixture.stats()),beforeStats,'Repeated parent renders/status snapshots cannot create another phone hook subscription')
    assert.equal(beforeStats.listeners,1)
    assert.equal(beforeStats.maxListeners,1)
    // Exercise both ends of the dialog while device details are collapsed.
    await sheet.getByRole('button',{name:'Close account',exact:true}).focus()
    await page.keyboard.press('Shift+Tab')
    assert.equal(await sheet.getByRole('button',{name:'Sign out',exact:true}).evaluate(el=>el===document.activeElement),true)
    await page.keyboard.press('Tab')
    assert.equal(await sheet.getByRole('button',{name:'Close account',exact:true}).evaluate(el=>el===document.activeElement),true)
    for(let i=0;i<12;i++) {await page.keyboard.press('Tab');assert.equal(await sheet.evaluate(el=>el.contains(document.activeElement)),true,'Tab never escapes the account dialog')}
    await page.locator('#outside-button').evaluate(el=>el.focus())
    assert.equal(await sheet.evaluate(el=>el.contains(document.activeElement)),true,'Programmatic editor focus cannot escape the dialog')
    await close()
    assert.equal(await trigger.evaluate(el=>el===document.activeElement),true)
    await open()
    await page.mouse.click(200,200)
    await sheet.waitFor({state:'hidden'})
    assert.equal(await trigger.evaluate(el=>el===document.activeElement),true,'Outside dismissal returns focus to avatar')
    assert.equal((await calls()).filter(call=>call.method==='outside').length,0,'Backdrop click does not trigger editor behind sheet')
    pass('known account identity, stable single existing hook owner, keyboard trap and Escape/outside focus restoration')

    await open()
    await sheet.getByText('Connected devices · 2',{exact:true}).click()
    const android=sheet.locator('li').filter({hasText:'Fixture Android'})
    await android.getByRole('button',{name:'Disconnect',exact:true}).click()
    await page.waitForFunction(()=>window.desktopAccountFixture.calls.some(call=>call.method==='disconnect-device'))
    assert.equal(await sheet.getByText('Fixture Android',{exact:true}).count(),0)
    assert.equal(await sheet.getByText('Fixture iPhone',{exact:true}).count(),1)
    const disconnect=(await mutations()).find(call=>call.method==='disconnect-device')
    assert.equal(disconnect.deviceId,'synthetic-phone-one')
    assert.equal(disconnect.userActivated,true)
    assert.ok(disconnect.scope)
    await sheet.getByRole('button',{name:'Stop phone sharing',exact:true}).click()
    await sheet.getByText('Signed in. Phone sharing is off.',{exact:true}).waitFor()
    assert.equal(await sheet.getByText('Jaime Example',{exact:true}).count(),1,'Stopping the real hook preserves signed-in account identity')
    assert.equal(await sheet.getByRole('button',{name:'Enable phone sharing',exact:true}).isEnabled(),true)
    assert.equal((await mutations()).filter(call=>call.method==='disable').length,1)
    await page.screenshot({path:path.join(output,'sharing-paused-1440.png')})
    await close()
    await state('paused');await open()
    await sheet.getByText('Jaime Example',{exact:true}).waitFor()
    assert.equal(await sheet.getByText('Signed in. Phone sharing is off.',{exact:true}).count(),1)
    assert.equal(await sheet.getByRole('button',{name:'Sign in',exact:true}).count(),0)
    assert.equal(await sheet.getByRole('button',{name:'Enable phone sharing',exact:true}).isEnabled(),true)
    await sheet.getByText('Connected devices · 2',{exact:true}).click()
    assert.equal(await sheet.getByRole('button',{name:'Disconnect',exact:true}).first().isDisabled(),true)
    const connectsBefore=(await mutations()).filter(call=>call.method==='connect').length
    await sheet.getByRole('button',{name:'Sign out',exact:true}).click()
    await sheet.getByRole('button',{name:'Sign in',exact:true}).waitFor()
    assert.equal((await mutations()).filter(call=>call.method==='account-sign-out').length,1)
    assert.equal((await mutations()).filter(call=>call.method==='connect').length,connectsBefore,'Paused account disconnection must not resume access')
    await sheet.getByText('Fixture desktop',{exact:true}).waitFor()
    assert.equal(await sheet.getByLabel('Computer name',{exact:true}).count(),0)
    assert.equal(await sheet.getByRole('button',{name:'Sign in',exact:true}).isEnabled(),true)
    await close()
    await state('signedout');await open()
    await sheet.getByText('Fixture desktop',{exact:true}).waitFor()
    assert.equal(await sheet.getByLabel('Computer name',{exact:true}).count(),0,'Remounted hook uses native remembered name without showing the editor')
    await close()
    pass('device disconnect reaches exact native scope; paused identity remains linked and account disconnect does not resume access')

    await state('unknown');await open()
    await sheet.getByText('Account details unavailable',{exact:true}).waitFor()
    assert.equal((await trigger.textContent()).trim(),'','Old record must not invent user initials from the computer name')
    assert.equal(await sheet.getByText('Fixture desktop',{exact:true}).count(),1)
    await page.screenshot({path:path.join(output,'linked-unknown-name-1440.png')})
    await close()
    const attachesBefore=(await calls()).filter(call=>call.method==='attach').length
    await state('linked',false);await open()
    await sheet.getByText('Jaime Example',{exact:true}).waitFor()
    assert.match(await sheet.textContent(),/Open or create a project to manage your account on this computer/)
    assert.equal(await sheet.getByRole('button',{name:'Sign out',exact:true}).count(),0)
    assert.equal((await page.evaluate(()=>window.desktopAccountFixture.stats())).listeners,0)
    assert.equal((await calls()).filter(call=>call.method==='attach').length,attachesBefore,'Linked no-project view also stays read-only')
    await close()
    await state('busy');await open()
    await sheet.getByText('Connected devices · 2',{exact:true}).click()
    for(const label of ['Sign out','Switch account','Stop phone sharing'])assert.equal(await sheet.getByRole('button',{name:label,exact:true}).isDisabled(),true)
    assert.equal(await sheet.getByRole('button',{name:'Disconnect',exact:true}).first().isDisabled(),true)
    const beforeBusy=(await mutations()).length
    await sheet.getByRole('button',{name:'Sign out',exact:true}).evaluate(el=>el.click())
    assert.equal((await mutations()).length,beforeBusy)
    await state('export')
    await sheet.waitFor({state:'hidden'})
    assert.equal(await rawTrigger.isDisabled(),true)
    await rawTrigger.evaluate(el=>el.click())
    assert.equal(await sheet.count(),0)
    assert.equal((await mutations()).length,beforeBusy)
    pass('legacy linked identity is truthful; busy actions and export avatar are guarded')

    await state('linked');await open()
    const beforeCancel=await mutations()
    await page.evaluate(()=>window.desktopAccountFixture.accountDecision('cancel'))
    for(const label of ['Sign out','Switch account']) {
      await sheet.getByRole('button',{name:label,exact:true}).click()
      await sheet.getByText('creator@example.test',{exact:true}).waitFor()
      await sheet.getByText('Connected devices · 2',{exact:true}).waitFor()
    }
    assert.deepEqual(await mutations(),beforeCancel)
    await page.evaluate(()=>window.desktopAccountFixture.accountDecision('accept'))
    await page.screenshot({path:path.join(output,'clear-account-controls.png')})
    await page.evaluate(()=>window.desktopAccountFixture.hold('account-switch-account'))
    await sheet.getByRole('button',{name:'Switch account',exact:true}).click()
    await page.waitForFunction(()=>window.desktopAccountFixture.calls.some(call=>call.method==='account-switch-account'))
    await sheet.getByRole('button',{name:'Switch account',exact:true}).evaluate(el=>{el.click();el.click()})
    assert.equal((await mutations()).filter(call=>call.method==='account-switch-account').length,1)
    const switchCall=(await mutations()).find(call=>call.method==='account-switch-account')
    assert.equal(switchCall.userActivated,true)
    assert.ok(switchCall.scope && switchCall.snapshot.contextId)
    await page.evaluate(()=>window.desktopAccountFixture.release())
    await sheet.getByRole('button',{name:'Waiting for sign-in…',exact:true}).waitFor()
    assert.equal(await sheet.getByText('creator@example.test',{exact:true}).count(),0)
    await close()
    pass('clear account actions: cancel preserves identity/devices, switch runs once and waits for browser sign-in')

    await state('linked');await open()
    for(const [result,text] of [
      [{success:true,provider:'luna',available:false,status:'not-eligible'},'Velo access has not been enabled for this account'],
      [{success:true,provider:'luna',available:false,status:'exhausted'},'Velo allowance used up — no automatic refills'],
      [{success:false,error:'Private internal detail'},'Could not check availability'],
      [{success:true,provider:'luna',available:true,status:'eligible'},'Available for this account'],
    ]) {
      await page.evaluate(result=>window.desktopAccountFixture.vee(result),result)
      await sheet.getByRole('button',{name:'Refresh Velo availability'}).click()
      await sheet.getByText(text,{exact:true}).waitFor()
      assert.doesNotMatch(await sheet.textContent(),/Private internal detail/)
    }
    await page.screenshot({path:path.join(output,'account-email-vee-available.png')})
    await page.evaluate(()=>window.desktopAccountFixture.vee({success:true,provider:'luna',available:true,status:'eligible'},true))
    await sheet.getByRole('button',{name:'Refresh Velo availability'}).click()
    await sheet.getByText('Checking availability…',{exact:true}).waitFor()
    await state('signedout');await page.evaluate(()=>window.desktopAccountFixture.releaseVee())
    await settle();await open()
    assert.equal(await sheet.getByText('creator@example.test',{exact:true}).count(),0)
    assert.equal(await sheet.getByText('Available for this account',{exact:true}).count(),0)
    await close()
    pass('account email, automatic read-only Velo status, allowance/offline distinctions and stale result fencing')

    for(const name of ['linked','long-name','malicious-name']) {
      await state(name);await open()
      if(name==='malicious-name') {
        assert.equal(await sheet.locator('img').count(),0)
        assert.equal(await page.evaluate(()=>window.fixtureInjection),undefined)
        assert.match(await sheet.locator('.desktop-account-name').textContent(),/^<img/)
      }
      for(const [width,height] of [[1024,768],[1440,900],[1024,500]]) {
        await page.setViewportSize({width,height});await settle()
        const bounds=await sheet.boundingBox()
        assert.ok(bounds.x>=0 && bounds.x+bounds.width<=width+1 && bounds.y>=0 && bounds.y+bounds.height<=height+1,`${name} sheet fits ${width}x${height}`)
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'No window horizontal overflow')
        assert.equal(await sheet.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'No sheet horizontal overflow')
        await sheet.getByText('Connected devices · 2',{exact:true}).evaluate(el=>{if(!el.parentElement.open)el.click()})
        await sheet.getByRole('button',{name:'Close account',exact:true}).focus()
        await sheet.getByRole('button',{name:'Sign out',exact:true}).focus()
        const action=await sheet.getByRole('button',{name:'Sign out',exact:true}).boundingBox()
        assert.ok(action.y>=0 && action.y+action.height<=height+1,'Bottom action reachable at short height')
        await sheet.evaluate(el=>el.scrollTop=0)
        await page.screenshot({path:path.join(output,`${name}-${width}x${height}.png`)})
      }
      await close()
    }
    pass('1024/1440 desktop and short-height layouts fit; long and malicious account names remain inert text')
    assert.deepEqual(await page.evaluate(()=>window.desktopAccountFixture.forbiddenCalls),[])
    assert.deepEqual(errors,[])
    assert.deepEqual(blocked,[])
    assert.deepEqual(dialogs,[])
    console.log(JSON.stringify({success:true,output,checks,syntheticOnly:true},null,2))
  } catch(error) {
    if(page)await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{})
    const activeFocus=page ? await page.evaluate(()=>({tag:document.activeElement?.tagName,id:document.activeElement?.id,className:document.activeElement?.className})).catch(()=>null) : null
    console.error(JSON.stringify({output,checks,errors,blocked,activeFocus}))
    throw error
  } finally {await browser?.close();await server.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
