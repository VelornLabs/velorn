// Synthetic native consent/lifecycle regression. Every grant and provider reply
// is mocked: no actual command, file operation, model inference or spend.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5199')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.username || base.password) throw new Error('Loopback fixture only')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-agent-full-access-'))
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, serviceWorkers: 'block' })
  const page = await context.newPage(), errors = [], blocked = []
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|view|ws|v1|api)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const checkbox = name => page.getByRole('checkbox', { name, exact: true })
  const full = () => checkbox('Full computer access (experimental)')
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const composer = page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const openSettings = async () => {
    if (await button('Assistant settings').getAttribute('aria-expanded') !== 'true') await button('Assistant settings').click()
    // These legacy regressions intentionally exercise the individual controls.
    if (!await page.locator('.ca-more-options').evaluate(node => node.open)) await page.locator('.ca-more-options > summary').click()
    const advanced = page.locator('summary').filter({ hasText: /^Access options$/ })
    if (!(await advanced.evaluate(node => node.parentElement.open))) await advanced.click()
  }
  const back = async () => { if (await button('Back to chat').isVisible()) await button('Back to chat').click() }
  const enable = async () => {
    await openSettings(); await checkbox('Velorn tools').check(); await full().check()
    await page.waitForFunction(() => Boolean(window.connectedAgentTest.snapshot().fullAccessGrant))
    await frame(); assert.equal(await full().isChecked(), true)
  }
  const grantCalls = async enabled => (await snapshot()).calls.filter(call => call.method === 'setFullAccess' && call.enabled === enabled)
  const send = async text => {
    await back(); const before = (await snapshot()).requests.length
    await composer.fill(text); await button('Send message').click()
    await page.waitForFunction(count => window.connectedAgentTest.snapshot().requests.length > count, before)
    return (await snapshot()).requests.at(-1)
  }
  const settle = async request => {
    await page.evaluate(id => window.connectedAgentTest.settle(id, { success: true, text: 'Synthetic response only.' }), request.requestId)
    await button('Send message').waitFor()
  }
  const navigate = async (query = '?dock=1') => {
    await page.goto(new URL(`/tests/fixtures/connected-agent.html${query}`, base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    if (query.includes('dock')) await button('Assistant').click()
    await composer.waitFor()
  }
  let groups = 0
  const pass = label => console.log(`PASS ${++groups}: ${label}`)
  try {
    await navigate()
    const baseline = (await snapshot()).authored
    await openSettings()
    assert.equal(await full().isChecked(), false); assert.equal(await full().isDisabled(), true)
    await page.locator('.ca-full-access-details > summary').click()
    const warning = await page.locator('.ca-full-access-details').innerText()
    for (const phrase of ['run automatically', 'Normal timeline Undo', 'may not be undoable', 'computer commands', 'normal OS user permissions', 'Remember on this desktop', 'Generation spending']) assert.ok(warning.includes(phrase), phrase)
    assert.equal((await grantCalls(true)).length, 0)
    assert.match(await page.locator('.ca-full-access-consent').innerText(), /Giving an agent full access can be dangerous/)
    pass('Default-off concise controls retain the complete authority disclosure behind Learn more')

    await checkbox('Velorn tools').check()
    await page.evaluate(() => { window.connectedAgentTest.setFullAccessResponse({ success: true, enabled: false }); window.connectedAgentTest.setHoldFullAccess(true) })
    await full().click(); await frame()
    assert.equal(await full().isChecked(), false); assert.equal(await full().isDisabled(), true)
    assert.equal(await page.getByLabel('Assistant selection', { exact: true }).isDisabled(), true)
    assert.equal(await button('New chat').isDisabled(), true)
    assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
    await page.evaluate(() => { window.connectedAgentTest.releaseFullAccess(); window.connectedAgentTest.setHoldFullAccess(false) })
    await page.getByRole('alert').filter({ hasText: 'was not enabled' }).waitFor()
    assert.equal(await full().isChecked(), false)
    pass('Checking waits for native confirmation; cancelled confirmation never grants or shows an active badge')

    await page.evaluate(() => window.connectedAgentTest.setFullAccessResponse({ success: true, enabled: true }))
    await full().click(); await page.getByRole('alert').filter({ hasText: 'no valid session grant' }).waitFor()
    assert.equal(await full().isChecked(), false)
    await page.evaluate(() => window.connectedAgentTest.setFullAccessResponse({ success: false, error: 'Synthetic native grant error.' }))
    await full().click(); await page.getByRole('alert').filter({ hasText: 'Synthetic native grant error' }).waitFor()
    assert.equal(await full().isChecked(), false)
    pass('Malformed and rejected native grants remain off and show explicit errors')

    await page.evaluate(() => window.connectedAgentTest.setFullAccessResponse(null))
    await enable()
    const enabled = (await snapshot()).fullAccessGrant
    assert.ok(enabled.conversationId); assert.equal(enabled.expectedContext.schemaVersion, 1)
    assert.ok(enabled.expectedContext.projectKey.includes('PRIVATE_PATH'))
    assert.equal(JSON.stringify((await snapshot()).storage).includes(enabled.token), false)
    assert.equal(JSON.stringify((await snapshot()).storage).includes('fullAccess'), false)
    assert.equal(await checkbox('Share images').isChecked(), true)
    await checkbox('Share images').uncheck()
    assert.match(await page.locator('.ca-settings').innerText(), /Automatic image sharing is off.*can still read/s)
    await page.locator('.ca-full-access-consent').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(output, 'settings-warning.png'), fullPage: true })
    assert.match(await page.locator('.ca-approval-help').innerText(), /automatic/i)
    assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
    assert.match(await page.locator('.ca-full-access-active').innerText(), /Full access · automatic/)
    await back()
    assert.equal(await page.locator('.ca-full-access-badge').isVisible(), false, 'Full access status belongs in settings, not above the conversation')
    assert.equal(await page.locator('.ca-chat [data-testid="agent-approval-status"]').count(), 0)
    assert.equal(await page.locator('.ca-chat .ca-full-access-badge').count(), 0)
    assert.equal(await page.getByRole('radio', { name: 'Ask first', exact: true }).count(), 0)
    assert.equal(await page.getByRole('radio', { name: 'Auto-approve editing', exact: true }).count(), 0)
    assert.match(await page.getByLabel('Current assistant permissions').innerText(), /direct file access on/)
    pass('Native grant stays in RAM; full access controls and disclosures remain in settings while chat omits routine permission indicators')

    await page.getByRole('navigation', { name: 'Fixture workspace modes' }).getByRole('button', { name: 'Generate', exact: true }).click()
    assert.equal(await page.locator('.ca-full-access-badge').isVisible(), false)
    assert.equal((await snapshot()).fullAccessGrant.token, enabled.token, 'Removing the persistent banner does not revoke access on navigation')
    const explicitPrompt = 'Synthetic full access request for /tmp/EXPLICIT_OUTSIDE_PROJECT_fixture.json and http://localhost:8188. Do not execute anything.'
    const request = await send(explicitPrompt)
    assert.equal(request.fullAccess, true); assert.equal(request.fullAccessToken, enabled.token)
    assert.equal(request.conversationId, enabled.conversationId)
    assert.equal(request.toolsEnabled, true); assert.equal(request.allowToolImages, false)
    assert.deepEqual(request.images, [])
    assert.equal(request.messages.at(-1).content, explicitPrompt)
    assert.ok(!JSON.stringify((await snapshot()).storage).includes('EXPLICIT_OUTSIDE_PROJECT'))
    assert.ok(!JSON.stringify((await snapshot()).storage).includes('localhost:8188'))
    assert.ok(!JSON.stringify({ context: request.context, messages: request.messages }).includes(enabled.token))
    await openSettings(); assert.equal(await full().isDisabled(), true)
    assert.equal(await checkbox('Velorn tools').isDisabled(), true)
    assert.equal(await page.getByLabel('Assistant selection', { exact: true }).isDisabled(), true)
    await page.evaluate(id => window.connectedAgentTest.emitEvent({ requestId: id, type: 'tool', callId: 'full-fixture', toolName: 'run_command', status: 'running', summary: 'Synthetic activity only' }), request.requestId)
    await page.getByTestId('agent-activity').filter({ hasText: 'Synthetic activity only' }).waitFor()
    // Deliberately injected legacy approval tests fail-closed UI handling; the
    // current native full runtime/host do not emit routine approval cards.
    await page.evaluate(id => window.connectedAgentTest.emitEvent({ requestId: id, type: 'approval', approvalId: 'route-review', toolName: 'fixture_tool', arguments: {}, warnings: ['Injected legacy approval fixture; never auto-accept.'] }), request.requestId)
    await button('Deny').waitFor(); await button('Deny').click()
    await settle(request)
    await page.screenshot({ path: path.join(output, 'chat-active.png'), fullPage: true })
    pass('Workspace navigation retains grant; sends carry scoped token and unexpected legacy approval cards are not silently accepted')

    await openSettings(); await full().uncheck(); await frame()
    assert.equal((await snapshot()).fullAccessGrant, null); assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
    const normal = await send(explicitPrompt)
    assert.equal(normal.fullAccess, false); assert.equal(normal.fullAccessToken, undefined)
    assert.ok(!normal.messages.at(-1).content.includes('EXPLICIT_OUTSIDE_PROJECT'))
    assert.ok(!normal.messages.at(-1).content.includes('localhost:8188'))
    await settle(normal)
    pass('Disabling immediately removes the badge, revokes native grant and sends no token on restricted turns')

    for (const code of ['UNAUTHORIZED', 'STALE_APPROVAL']) {
      await enable()
      const refused = await send('Synthetic expired grant check.')
      await page.evaluate(({ requestId, code }) => window.connectedAgentTest.settle(requestId,
        { success: false, code, error: 'Synthetic full-access grant expired; confirm again.' }), { requestId: refused.requestId, code })
      await button('Send message').waitFor()
      await page.getByRole('alert').filter({ hasText: 'grant expired' }).waitFor()
      assert.equal((await snapshot()).fullAccessGrant, null)
      assert.equal(await page.locator('.ca-full-access-badge').count(), 0)
      await openSettings(); assert.equal(await full().isChecked(), false)
    }
    pass('Native missing or stale grant failures clear the checkbox and badge instead of keeping misleading access state')

    await enable(); await back()
    const oldChat = await page.getByLabel('Conversation', { exact: true }).inputValue()
    await button('New chat').click(); await frame()
    const newChat = await page.getByLabel('Conversation', { exact: true }).inputValue()
    assert.equal((await snapshot()).fullAccessGrant, null)
    await openSettings(); assert.equal(await full().isChecked(), false); await back()
    await page.getByLabel('Conversation', { exact: true }).selectOption(oldChat)
    await openSettings(); assert.equal(await full().isChecked(), false)
    await enable(); await back()
    await page.getByLabel('Conversation', { exact: true }).selectOption(newChat); await frame()
    assert.equal((await snapshot()).fullAccessGrant, null)
    await enable(); await back()
    await button('Conversation options').click(); await page.getByRole('menuitem', { name: 'Delete conversation', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Delete conversation', exact: true }).click()
    await frame(); assert.equal((await snapshot()).fullAccessGrant, null)
    pass('New, switched and deleted chats revoke full access instead of restoring a saved permission')

    await enable()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('lmstudio'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click(); await frame()
    await openSettings()
    assert.equal((await snapshot()).fullAccessGrant, null)
    assert.equal(await checkbox('Full Velorn access').isChecked(), false)
    assert.equal(await page.getByRole('button', { name: 'Full access', exact: true }).isEnabled(), true)
    assert.match(await page.locator('.ca-access-modes').innerText(), /LM Studio does not include a computer-command tool/)
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('codex'); if (await page.getByRole('group', { name: 'Confirm assistant switch' }).count()) await page.getByRole('group', { name: 'Confirm assistant switch' }).getByRole('button', { name: /^Start .* chat$/ }).click(); await frame()
    await openSettings()
    assert.equal(await full().isChecked(), false)
    pass('Provider switches revoke permission; LM Studio exposes separate Full Velorn access without claiming arbitrary computer commands')

    await enable(); await checkbox('Velorn tools').uncheck(); await frame()
    assert.equal((await snapshot()).fullAccessGrant, null); assert.equal(await full().isChecked(), false)
    await enable(); await back()
    const active = await send('Stop me before changing computer permission.')
    await button('Stop response').click(); await openSettings(); await full().uncheck(); await frame()
    assert.ok((await snapshot()).calls.some(call => call.method === 'cancel' && call.requestId === active.requestId))
    assert.equal((await snapshot()).fullAccessGrant, null)
    assert.deepEqual((await snapshot()).authored, baseline)
    pass('Disabling project tools revokes full access; Stop followed by disable cancels and revokes without authored changes')

    await enable(); await page.evaluate(() => window.connectedAgentTest.switchProject('beta')); await frame()
    assert.equal((await snapshot()).fullAccessGrant, null)
    await openSettings(); assert.equal(await full().isChecked(), false)
    await enable()
    const storage = (await snapshot()).storage
    await page.addInitScript(value => { window.__connectedAgentFixtureStorage = value }, storage)
    await page.reload(); await page.waitForFunction(() => window.connectedAgentTest?.ready); await button('Assistant').click()
    await openSettings(); assert.equal(await full().isChecked(), false)
    assert.equal((await grantCalls(true)).length, 0)
    pass('Project changes and renderer restart do not inherit full access even when all saved preferences/history are replayed')

    await checkbox('Velorn tools').check()
    await page.evaluate(() => { delete window.electronAPI.connectedAgent.setFullAccess })
    await full().click(); await page.getByRole('alert').filter({ hasText: 'Fully quit and reopen' }).waitFor()
    assert.equal(await full().isChecked(), false)
    pass('Older preload bridge is feature-detected and requests a restart instead of pretending access is enabled')

    await navigate('')
    await enable(); await button('Close assistant panel').click(); await frame()
    assert.equal((await snapshot()).fullAccessGrant, null)
    await button('Open agent').click(); await openSettings(); assert.equal(await full().isChecked(), false)
    await checkbox('Velorn tools').check()
    await page.evaluate(() => window.connectedAgentTest.setHoldFullAccess(true))
    await full().click(); await button('Close assistant panel').click()
    await page.evaluate(() => { window.connectedAgentTest.releaseFullAccess(); window.connectedAgentTest.setHoldFullAccess(false) })
    await frame(); assert.equal((await snapshot()).fullAccessGrant, null)
    await button('Open agent').click(); await openSettings(); assert.equal(await full().isChecked(), false)
    assert.ok((await grantCalls(false)).length >= 3)
    pass('Unmount/remount revokes grants, including a native confirmation that arrives after the panel was closed')

    await enable()
    for (const width of [900, 760]) {
      await page.setViewportSize({ width, height: 700 })
      await page.locator('.ca-full-access-consent').scrollIntoViewIfNeeded()
      const geometry = await page.locator('.ca-full-access-consent').evaluate(node => ({ clientWidth: node.clientWidth, scrollWidth: node.scrollWidth }))
      assert.ok(geometry.scrollWidth <= geometry.clientWidth + 1, `Danger warning overflows at ${width}px`)
      assert.equal(await full().isVisible(), true)
      assert.equal(await page.locator('.ca-full-access-active').isVisible(), true)
      await page.screenshot({ path: path.join(output, `warning-${width}px.png`), fullPage: true })
    }
    pass('Warning, checkbox and settings-only active badge remain legible at narrow viewport sizes')

    assert.deepEqual(errors, []); assert.deepEqual(blocked, []); assert.deepEqual((await snapshot()).forbiddenCalls, [])
    pass('No real provider, command, network, filesystem or generation operation ran')
    console.log(`Artifacts: ${output}`)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
