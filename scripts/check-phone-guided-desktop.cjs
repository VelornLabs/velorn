// Isolated renderer controls, mocked actions, no Electron/live account access.
const assert = require('node:assert/strict'), fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
async function main() {
  const { createServer } = await import('vite')
  const server = await createServer({ root: path.resolve(__dirname, '..'), server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false } })
  await server.listen()
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'velorn-guided-desktop-'))
  let browser
  const errors = [], blocked = []
  try {
    browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/google-chrome', args: ['--no-sandbox'] })
    const page = await browser.newPage({ viewport: { width: 800, height: 1000 } })
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : (blocked.push(route.request().url()), route.abort()))
    await page.goto(`${origin}/tests/fixtures/phone-guided-desktop.html`)
    const change = value => page.evaluate(async value => {
      window.guidedDesktopFixture.state(value)
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
    }, value)
    const calls = () => page.evaluate(() => window.guidedDesktopFixture.calls)
    const chat = page.getByTestId('phone-chat')
    const settings = page.getByTestId('phone-settings')
    const connect = page.getByRole('button', { name: 'Enable phone access', exact: true })
    await connect.waitFor()
    assert.match(await page.locator('main').textContent(), /Desktop editing, your own Codex, and local LM Studio do not require a Velorn account/)
    const phoneLink = page.getByRole('link', { name: 'connect.velorn.ai', exact: true })
    assert.equal(await phoneLink.getAttribute('href'), 'https://connect.velorn.ai')
    assert.equal(await phoneLink.getAttribute('rel'), 'noopener noreferrer')
    assert.match(await page.locator('main').textContent(), /same account.*Keep this computer awake with Velorn running and a project open/s)
    assert.doesNotMatch(await page.locator('main').textContent(), /older pairing|private-link|Pair a phone|Pairing code|Local HTTP/i)
    assert.equal(await page.getByRole('button', { name: 'Pair a phone', exact: true }).count(), 0)
    assert.deepEqual(await calls(), [], 'Fresh settings do not enable phone access or ask the agent to act')
    await page.screenshot({ path: path.join(output, 'packaged-phone-first-use.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.equal(await phoneLink.isVisible(), true)
    await page.screenshot({ path: path.join(output, 'packaged-phone-narrow.png'), fullPage: true })
    await page.setViewportSize({ width: 800, height: 1000 })
    await page.getByLabel('Computer name').fill('')
    assert.equal(await connect.isDisabled(), true)
    await page.getByLabel('Computer name').fill('Studio desktop')
    await connect.click()
    await page.getByRole('button', { name: 'Opening phone setup…' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Opening phone setup…' }).isDisabled(), true)
    assert.deepEqual(await calls(), [{ method: 'connect', name: 'Studio desktop' }])
    console.log('PASS: named setup sends one action, prevents duplicate clicks and keeps desktop login-free')
    await change('linked')
    assert.equal(await chat.locator('.ca-mobile-request').count(), 0, 'A connected phone does not insert a permanent banner above the conversation')
    assert.equal(await chat.getByRole('button').count(), 0, 'Routine phone controls live in settings, not chat')
    await page.getByText('Connected devices · 2', { exact: true }).waitFor()
    assert.equal(await page.getByText('Fixture Android · Connected').isVisible(), false)
    await page.getByText('Connected devices · 2', { exact: true }).click()
    assert.equal(await page.getByText(/Open this address on your phone/).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Forget phone', exact: true }).count(), 0)
    await page.getByText('Fixture Android · Connected').locator('..').getByRole('button', { name: 'Disconnect', exact: true }).click()
    assert.equal(await page.getByText('Fixture Android · Connected').count(), 0)
    assert.equal(await page.getByText('Fixture iPhone · Offline').count(), 1)
    assert.deepEqual((await calls()).at(-1), { method: 'disconnect', id: 'phone-one' })
    console.log('PASS: exact device disconnect preserves the other row; guided-only mode has no false legacy pairing instructions')
    await change('disabled')
    assert.equal(await page.getByRole('button', { name: 'Disconnect Velorn account', exact: true }).isDisabled(), true)
    await change('linked')
    await page.screenshot({ path: path.join(output, 'guided-desktop.png'), fullPage: true })
    await page.getByRole('button', { name: 'Disconnect Velorn account', exact: true }).click()
    await connect.waitFor()
    assert.deepEqual((await calls()).at(-1), { method: 'unregister' })
    await change('failure')
    await page.getByText('Phone setup could not start.').waitFor()
    assert.equal(await connect.isEnabled(), true)
    await change('unavailable')
    assert.equal(await connect.count(), 0)
    await change('waiting')
    await page.getByText(/Online and ready for your phone/).waitFor()
    assert.equal(await connect.count(), 0)
    assert.equal(await page.getByText('Phone connection setup', { exact: true }).count(), 0)
    assert.equal(await chat.locator('.ca-mobile-request').count(), 0, 'An idle waiting connection does not clutter the chat')
    assert.equal(await page.getByRole('button', { name: 'Stop all phone sharing', exact: true }).isVisible(), true)
    assert.equal(await page.getByRole('button', { name: 'Pair a phone', exact: true }).isVisible(), false)
    await page.getByText('Advanced · sharing options', { exact: true }).click()
    const preview = page.getByRole('checkbox', { name: 'Share Editor / Storyboard still previews', exact: true })
    assert.equal(await preview.isVisible(), true)
    await preview.check()
    assert.deepEqual((await calls()).at(-1), { method: 'preview', value: true })
    const refresh = settings.getByRole('button', { name: 'Refresh phone preview', exact: true })
    await refresh.click()
    assert.deepEqual((await calls()).at(-1), { method: 'refresh-preview' })
    assert.equal(await chat.getByRole('button', { name: 'Refresh phone preview', exact: true }).count(), 0)
    assert.doesNotMatch(await page.locator('main').textContent(), /older pairing|private-link|Pair a phone|Pairing code|Local HTTP/i)
    await page.getByRole('button', { name: 'Stop all phone sharing', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'stop' })
    assert.equal((await calls()).some(call => /legacy/.test(call.method)), false)
    await page.screenshot({ path: path.join(output, 'guided-waiting.png'), fullPage: true })
    await change('manual')
    assert.equal(await connect.isEnabled(), true, 'old registrations have an explicit automatic-access opt-in')
    console.log('PASS: hosted-only first use provides the public phone address and same-account guidance without legacy controls; shared previews and Stop remain available')
    const beforeReview = (await calls()).length
    await change('request')
    assert.equal(await chat.getByText('Synthetic phone message awaiting your decision.', { exact: true }).isVisible(), true)
    assert.doesNotMatch(await chat.innerText(), /Phone paired|Waiting for connection|Refresh phone preview|Disconnect/)
    await chat.getByRole('button', { name: 'Accept phone request', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'decide', approved: true })
    assert.equal(await chat.locator('.ca-mobile-request').count(), 0)
    await change('request-disabled')
    assert.equal(await chat.getByRole('button', { name: 'Accept phone request', exact: true }).isDisabled(), true)
    await chat.getByRole('button', { name: 'Decline', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'decide', approved: false })
    await change('approval')
    const fullApproval = chat.getByRole('group', { name: 'Allow phone full access?', exact: true })
    assert.equal(await fullApproval.getByRole('button', { name: 'Approve', exact: true }).isDisabled(), true)
    assert.equal((await calls()).length, beforeReview + 2, 'Rendering a native approval does not approve it')
    await fullApproval.getByRole('checkbox', { name: 'I understand and accept these risks.', exact: true }).check()
    await fullApproval.getByRole('button', { name: 'Approve', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'decide-native', id: 'native-one', approved: true, riskAcknowledged: true, trustLocal: false })
    await change('paid-approval')
    const paidApproval = chat.getByRole('group', { name: 'Approve generation spending?', exact: true })
    assert.equal(await paidApproval.isVisible(), true)
    assert.equal(await paidApproval.getByRole('checkbox').isChecked(), false, 'Local trust still requires an explicit choice')
    await paidApproval.getByRole('button', { name: 'Decline', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'decide-native', id: 'native-paid', approved: false, riskAcknowledged: false, trustLocal: false })
    await change('request-error')
    assert.match(await chat.innerText(), /The phone approval expired. No action was approved./)
    assert.equal(await chat.getByRole('button', { name: 'Disconnect', exact: true }).count(), 0)
    await page.screenshot({ path: path.join(output, 'actionable-phone-error.png'), fullPage: true })
    await chat.getByRole('button', { name: 'Dismiss', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'dismiss-request-error' })
    assert.equal(await chat.locator('.ca-mobile-request').count(), 0)
    console.log('PASS: idle chat has no phone controls; pending messages, risk acknowledgements, paid-generation decisions and approval errors remain actionable')
    await change('legacy-new')
    await page.getByRole('button', { name: 'Pair a phone', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'legacy-enable' })
    assert.match(await page.locator('main').textContent(), /Older private-link pairing remains available/)
    await change('legacy-active')
    assert.equal(await page.getByText('http://192.0.2.1:5212', { exact: true }).isVisible(), true)
    assert.match(await page.locator('main').textContent(), /Pairing code: 123456/)
    await page.getByRole('button', { name: 'Forget older pairing and stop sharing', exact: true }).click()
    assert.deepEqual((await calls()).at(-1), { method: 'forget-legacy' })
    await change('legacy-compat')
    assert.equal(await page.getByRole('button', { name: 'Pair a phone', exact: true }).isEnabled(), true)
    console.log('PASS: development/older native capability retains private-link pairing and forget controls')
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    console.log('PASS: disabled actions, retry notice, account disconnect and unsupported availability render correctly')
    console.log(JSON.stringify({ passed: 6, output, syntheticOnly: true }))
  } finally { await browser?.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
