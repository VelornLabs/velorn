// Actual persistent Agent dock/composer; only synthetic RAM project/provider.
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5206')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw new Error('Use an isolated loopback fixture')
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(10000)
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-project-starters-')), errors = [], blocked = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|api|v1)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const composer = () => page.getByRole('textbox', { name: 'Message your agent', exact: true })
  const state = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  const tick = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const settle = async text => {
    const request = (await state()).requests.at(-1)
    await page.evaluate(({ id, text }) => window.connectedAgentTest.settle(id, { success: true, text }), { id: request.requestId, text })
    await button('Stop response').waitFor({ state: 'hidden' })
  }
  let groups = 0
  const pass = text => console.log(`PASS ${++groups}: ${text}`)
  try {
    await page.goto(new URL('/tests/fixtures/connected-agent.html?dock=1&strict=1&blank=1', base).href)
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    await button('Assistant').click()
    await page.getByRole('heading', { name: 'What would you like to work on today?', exact: true }).waitFor()
    const baseline = await state()
    assert.equal(await button('Music video').isVisible(), false)
    await page.getByText('Ideas to get started', { exact: true }).click()
    for (const name of ['Music video', 'UGC', 'Commercial', 'Short film', 'Edit my project', 'Freeform']) assert.equal(await button(name).count(), 1)
    assert.equal(await page.locator('.ca-messages').evaluate(node => node.scrollTop), 0)
    assert.equal(baseline.requests.length, 0)
    await page.screenshot({ path: path.join(output, 'blank-project-dock.png') })
    pass('Fresh project shows six optional starters without an automatic introduction request')
    await button('Music video').click()
    assert.match(await composer().inputValue(), /song and my ideas/)
    assert.equal(await composer().evaluate(node => document.activeElement === node), true)
    assert.equal((await state()).requests.length, 0)
    assert.deepEqual((await state()).authored, baseline.authored)
    assert.deepEqual((await state()).storage, baseline.storage)
    await button('Short film').click()
    assert.match(await composer().inputValue(), /short film/)
    assert.doesNotMatch(await composer().inputValue(), /music video/)
    pass('Choice stages only; switching an untouched starter does not leave conflicting drafts')
    await composer().fill('Keep my own idea here. Local only.  ')
    await button('Commercial').click()
    const draft = await composer().inputValue()
    assert.ok(draft.startsWith('Keep my own idea here. Local only.  \n\n'))
    await button('Commercial').click(); assert.equal(await composer().inputValue(), draft)
    await button('ComfyUI').click(); await button('Editor').click()
    assert.equal(await composer().inputValue(), draft)
    pass('User-edited draft survives choice, repeat click, and workspace navigation')
    await button('New chat').click()
    assert.equal(await composer().inputValue(), '')
    await page.getByText('Ideas to get started', { exact: true }).click()
    await button('Music video').click(); await button('Send message').click()
    await page.waitForFunction(() => window.connectedAgentTest.snapshot().requests.length === 1)
    const request = (await state()).requests[0]
    assert.equal(request.toolsEnabled, false)
    assert.notEqual(request.researchEnabled, true); assert.notEqual(request.fullAccess, true)
    assert.notEqual(request.autoApproveEdits, true)
    assert.equal(request.images.length, 0)
    assert.equal(await page.getByRole('group', { name: 'Project starters', exact: true }).count(), 0)
    await settle('Do you already have a song, or would you like to create one?')
    assert.equal(await page.getByRole('group', { name: 'Project starters', exact: true }).count(), 0)
    pass('Explicit Send uses normal provider path and unchanged permissions; starters leave an active conversation')
    await page.evaluate(() => window.connectedAgentTest.switchProject())
    await page.getByRole('heading', { name: /What would you like to work on in Signal/ }).waitFor()
    assert.equal(await button('Continue this project').isVisible(), false)
    assert.equal(await button('Music video').isVisible(), false)
    await page.getByText('Ideas to get started', { exact: true }).click()
    await button('Continue this project').click()
    assert.match(await composer().inputValue(), /saved brief/)
    assert.match(await composer().inputValue(), /Don't restart the plan/)
    await button('Edit my project').click()
    assert.match(await composer().inputValue(), /help with the edit/)
    await page.screenshot({ path: path.join(output, 'existing-project-dock.png') })
    pass('Existing work gets a named welcome and Continue option, with optional starters still reachable')
    await composer().fill('x'.repeat(11999))
    await button('Music video').click()
    assert.equal((await composer().inputValue()).length, 11999)
    await page.getByText('Your draft is too long to add a starter. Shorten it first; nothing has been sent.', { exact: true }).waitFor()
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(true)); await tick()
    assert.equal(await button('Continue this project').isDisabled(), true)
    assert.equal(await button('Music video').isDisabled(), true)
    await button('Music video').evaluate(node => node.click())
    assert.equal((await state()).requests.length, 1)
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(false)); await tick()
    pass('Overlong drafts are not lost and export blocks starter actions without changing access')
    await composer().fill('')
    await button('Assistant settings').click()
    await page.getByLabel('Assistant selection', { exact: true }).selectOption('lmstudio')
    await button('Start LM Studio chat').click()
    await page.locator('.ca-more-starters > summary').click()
    await button('Freeform').click()
    assert.equal(await composer().inputValue(), "Let's work freely. I'll tell you what I need as we go.")
    assert.equal((await state()).requests.length, 1)
    pass('The same starters work with LM Studio without selecting a model or enabling tools')
    await page.setViewportSize({ width: 900, height: 760 }); await tick()
    assert.ok(await page.locator('.ca-docked').evaluate(node => node.scrollWidth <= node.clientWidth))
    assert.equal(await composer().isVisible(), true)
    await page.screenshot({ path: path.join(output, 'existing-project-narrow.png') })
    const final = await state()
    assert.equal(final.forbiddenCalls.length, 0)
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    pass('Narrow dock stays usable; no real provider, generation, project IO, or network traffic')
    console.log(JSON.stringify({ success: true, groups, output }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
