// Synthetic renderer-only check. Every Router method is in-memory, and all
// external requests are blocked. This does not use the user's keys/profile.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5242')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw new Error('Use an isolated loopback fixture')
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1280, height: 1050 } })
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-comfy-router-')), errors = [], blocked = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const request = route.request(), url = new URL(request.url())
    if (url.origin === base.origin && request.method() === 'GET' && !/^\/(prompt|queue|history|upload|api|v1)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const dialog = () => page.getByRole('dialog', { name: 'Create an image', exact: true })
  const state = () => page.evaluate(() => window.routerPanelTest.snapshot())
  const set = values => page.evaluate(values => window.routerPanelTest.set(values), values)
  const emit = () => page.evaluate(() => window.routerPanelTest.emit())
  const methods = async () => (await state()).calls.map(call => call.method)
  const key = () => page.getByLabel('Comfy Router API key', { exact: true })
  const prompt = () => page.getByLabel('Describe your image', { exact: true })
  const count = async method => (await methods()).filter(value => value === method).length
  const tick = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const assertDecodedPreview = async () => {
    await page.waitForFunction(() => {
      const image = document.querySelector('img[alt="Imported Router image preview"]')
      return image?.complete && image.naturalWidth === 1024 && image.naturalHeight === 1024
    })
    const snapshot = await state()
    assert.equal(snapshot.preview.type, 'image'); assert.match(snapshot.preview.path, /^assets\/images\/velorn-router-job-1(?:_\d+)?\.jpg$/)
    assert.match(snapshot.preview.url, /^blob:/)
  }
  let groups = 0
  const pass = text => console.log(`PASS ${++groups}: ${text}`)
  try {
    await page.goto(new URL('/tests/fixtures/comfy-router.html', base).href)
    await button('Open cloud images').click()
    await page.getByText('Not connected', { exact: true }).waitFor(); await tick()
    assert.deepEqual(await methods(), ['status', 'list'])
    assert.equal(await button('Close cloud images').evaluate(node => document.activeElement === node), true)
    await page.keyboard.press('Shift+Tab')
    assert.equal(await button('Done').evaluate(node => document.activeElement === node), true)
    await page.keyboard.press('Tab')
    assert.equal(await button('Close cloud images').evaluate(node => document.activeElement === node), true)
    assert.equal(await key().getAttribute('type'), 'password')
    assert.match(await dialog().innerText(), /Local ComfyUI does not need to be running/)
    pass('Opening reads only cached status/jobs; modal focus is trapped and no local ComfyUI is required')

    await set({ connectError: true })
    await key().fill('synthetic-router-key-only'); await button('Connect Router').click()
    await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor()
    assert.equal(await key().inputValue(), '')
    assert.doesNotMatch(await dialog().innerText(), /synthetic-router-key-only/)
    await set({ connectError: false })
    await key().fill('synthetic-router-key-only'); await button('Connect Router').click()
    await page.getByText('Connected for this session', { exact: true }).waitFor()
    assert.equal(await key().inputValue(), '')
    assert.equal(await count('submit'), 0)
    assert.equal((await state()).calls.filter(call => call.method === 'connect').every(call => call.correctKey), true)
    await button('Get a Comfy API key').click(); await tick()
    assert.equal(await count('guide'), 1)
    pass('Private password is cleared on success/failure, errors cannot echo the key, and connection performs no generation')

    await prompt().fill('A cinematic city at blue hour')
    await button('Preview cost').click()
    await page.getByLabel('Generation cost preview').waitFor()
    assert.match(await page.getByLabel('Generation cost preview').innerText(), /6\.33 credits.*US\$0\.03/)
    assert.equal(await count('submit'), 0)
    await prompt().fill('A cinematic city at sunrise')
    assert.equal(await button('Request generation').count(), 0)
    await button('Preview cost').click()
    await button('Request generation').waitFor()
    await set({ policy: 'local-only' }); await emit()
    await page.getByText('Local-only generation is enabled.', { exact: true }).waitFor()
    assert.equal(await button('Request generation').isDisabled(), true)
    await button('Open generation spending settings').click()
    assert.equal((await state()).spendingOpens, 1); assert.equal((await state()).policy, 'local-only')
    assert.equal(await count('submit'), 0)
    pass('Cost preview is free of inference, prompt changes invalidate it, and local-only policy opens settings without changing policy')

    await set({ policy: 'ask-cloud', approve: false }); await emit(); await tick()
    await button('Request generation').click()
    await page.getByRole('alert').filter({ hasText: 'native confirmation' }).waitFor()
    assert.equal((await state()).jobs.length, 0)
    assert.equal(await button('Request generation').count(), 0)
    await set({ approve: true, holdSubmit: true })
    await button('Preview cost').click(); await button('Request generation').click()
    await page.getByText('Waiting for confirmation or submission…', { exact: true }).waitFor()
    assert.equal(await button('Preview cost').isDisabled(), true)
    await emit(); await tick()
    assert.equal(await button('Preview cost').isDisabled(), true)
    await page.evaluate(() => window.routerPanelTest.releaseSubmit())
    await page.getByText('Queued', { exact: true }).waitFor()
    await set({ holdSubmit: false })
    assert.equal(await count('submit'), 2)
    assert.equal((await state()).calls.filter(call => call.method === 'submit').every(call => call.nativeConfirmation), true)
    pass('Generation reaches native confirmation only after explicit request; decline creates no job and pending submission cannot be duplicated')

    const first = page.getByRole('article', { name: 'Image request job-1', exact: true })
    assert.equal(await first.getByRole('button', { name: 'Import image to project' }).count(), 0)
    await first.getByRole('button', { name: 'Refresh status', exact: true }).click()
    await first.getByText('Running', { exact: true }).waitFor()
    assert.doesNotMatch(await first.innerText(), /\d+%/)
    await set({ nextStatus: 'COMPLETED' })
    await first.getByRole('button', { name: 'Refresh status', exact: true }).click()
    await first.getByRole('button', { name: 'Import image to project', exact: true }).waitFor()
    assert.equal((await state()).imports.length, 0)
    await set({ importError: 'Save a project before importing this image.' })
    await first.getByRole('button', { name: 'Import image to project', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Save a project' }).waitFor()
    assert.equal((await state()).imports.length, 0)
    await set({ importError: '' })
    await first.getByRole('button', { name: 'Import image to project', exact: true }).click()
    await first.getByRole('button', { name: 'Open / restore project image', exact: true }).waitFor()
    assert.equal(await first.getByRole('button', { name: 'Open / restore project image', exact: true }).isEnabled(), true)
    assert.deepEqual((await state()).imports, ['job-1'])
    await assertDecodedPreview()
    await first.getByRole('button', { name: 'Open / restore project image', exact: true }).click()
    await page.getByText('Showing the existing project image. No new generation or duplicate import.', { exact: true }).waitFor()
    assert.equal(await count('output'), 1); assert.equal((await state()).assets.length, 1)
    assert.deepEqual((await state()).imports, ['job-1'])
    pass('Known job states have no invented percentages; completed output imports explicitly, with truthful unsaved-project errors')

    const readsBeforeRepair = await count('output'), importsBeforeRepair = (await state()).imports.length
    await page.evaluate(() => window.routerPanelTest.breakPreviewUrl()); await tick()
    assert.equal((await state()).preview.url, null)
    assert.equal(await page.getByAltText('Imported Router image preview').getAttribute('src'), null)
    await first.getByRole('button', { name: 'Open / restore project image', exact: true }).click()
    await assertDecodedPreview()
    assert.equal(await count('output'), readsBeforeRepair)
    assert.equal((await state()).imports.length, importsBeforeRepair)
    assert.equal((await state()).assets.length, 1)
    pass('Actual imported JPEG decodes at 1024 × 1024; missing preview URL repairs in place without another download or copy')

    await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    await page.screenshot({ path: path.join(output, 'router-image-preview.png') })
    await button('Open cloud images').click(); await tick()
    await first.getByRole('button', { name: 'Open / restore project image', exact: true }).click()
    await page.getByText('Showing the existing project image. No new generation or duplicate import.', { exact: true }).waitFor()
    assert.equal(await count('output'), 1); assert.equal((await state()).assets.length, 1)
    assert.deepEqual((await state()).imports, ['job-1'])
    await page.evaluate(() => window.routerPanelTest.deleteImportedAssets())
    await first.getByRole('button', { name: 'Open / restore project image', exact: true }).click()
    await page.getByText('Image imported into project assets. Nothing was added to the timeline.', { exact: true }).waitFor()
    assert.equal(await count('output'), 2); assert.equal((await state()).assets.length, 1)
    assert.deepEqual((await state()).imports, ['job-1', 'job-1'])
    await assertDecodedPreview()
    assert.equal(await count('submit'), 2)
    pass('Actual import service deduplicates repeated/reopened callbacks and restores a deleted asset without new generation')

    await set({ uncertainSubmit: true })
    await prompt().fill('A synthetic image with an uncertain provider receipt')
    await button('Preview cost').click(); await button('Request generation').click()
    const uncertain = page.getByRole('article', { name: 'Image request job-2', exact: true })
    await uncertain.getByText('Submission outcome unknown', { exact: true }).waitFor()
    assert.equal(await uncertain.getByText('Failed', { exact: true }).count(), 0)
    assert.equal(await uncertain.getByRole('button', { name: 'Import image to project' }).count(), 0)
    assert.equal(await button('Request generation').count(), 0)
    assert.match(await uncertain.innerText(), /unconfirmed, not a confirmed failure/i)
    assert.match(await page.getByRole('alert').innerText(), /Do not resubmit/i)
    const submittedCount = await count('submit')
    await emit(); await tick()
    assert.equal(await count('submit'), submittedCount)
    assert.equal(submittedCount, 3)
    await set({ uncertainSubmit: false })
    pass('Uncertain submission receipts remain unknown, not failed, with no import, retry button or automatic resubmission')

    await page.evaluate(() => window.routerPanelTest.addJob({ jobId: 'job-cancel', status: 'IN_PROGRESS', outputAvailable: false }))
    const cancel = page.getByRole('article', { name: 'Image request job-cancel', exact: true })
    await cancel.getByRole('button', { name: 'Request cancellation', exact: true }).click()
    await cancel.getByText('Cancellation requested', { exact: true }).waitFor()
    assert.match(await dialog().innerText(), /completed work may still be billed/)
    assert.equal(await cancel.getByRole('button', { name: 'Request cancellation' }).count(), 0)
    await page.evaluate(() => window.routerPanelTest.addJob({ jobId: 'job-failed', status: 'COMPLETED', errorType: 'provider-error', outputAvailable: true }))
    const failed = page.getByRole('article', { name: 'Image request job-failed', exact: true })
    await failed.waitFor()
    assert.equal(await failed.getByRole('button', { name: 'Import image to project' }).count(), 0)
    await set({ refreshError: 'Provider status is temporarily unavailable.' })
    await failed.getByRole('button', { name: 'Refresh status', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'temporarily unavailable' }).waitFor()
    await set({ refreshError: '' })
    pass('Cancellation is explicitly best-effort; failed provider output cannot offer import and refresh failures stay visible')

    await page.evaluate(() => {
      window.routerPanelTest.addJob({ jobId: 'job-rejected', status: 'FAILED', errorType: 'REQUEST_REJECTED',
        outputAvailable: false, canRefresh: false, needsReconnect: false, submissionRejected: true,
        errorMessage: 'Queued Router generation is not enabled for this key or model. Check that the key belongs to a Comfy workspace and that the model supports queued requests. (HTTP 403 · not_enabled) No automatic retry was made.',
        diagnostics: { httpStatus: 403, errorType: 'not_enabled', requestId: 'c673156d-cbe2-4c55-bf73-b9b4dd5824ad' } })
      window.routerPanelTest.addJob({ jobId: 'job-legacy-rejected', status: 'FAILED', errorType: 'REQUEST_REJECTED',
        outputAvailable: false, canRefresh: false, needsReconnect: false, submissionRejected: true,
        errorMessage: 'The earlier submission was rejected. Detailed provider error information was not recorded by that Velorn version.' })
    })
    const rejected = page.getByRole('article', { name: 'Image request job-rejected', exact: true })
    const legacy = page.getByRole('article', { name: 'Image request job-legacy-rejected', exact: true })
    await rejected.getByText('Rejected', { exact: true }).waitFor()
    await rejected.locator('summary').filter({ hasText: 'Error details' }).click()
    assert.match(await rejected.innerText(), /HTTP 403/)
    assert.match(await rejected.innerText(), /not_enabled/)
    assert.match(await rejected.innerText(), /c673156d-cbe2-4c55-bf73-b9b4dd5824ad/)
    for (const item of [rejected, legacy]) {
      assert.equal(await item.getByRole('button', { name: 'Refresh status', exact: true }).count(), 0)
      assert.equal(await item.getByRole('button', { name: 'Import image to project', exact: true }).count(), 0)
      assert.doesNotMatch(await item.innerText(), /Reconnect the Router key/)
    }
    assert.match(await legacy.innerText(), /not recorded/)
    assert.equal(await legacy.locator('summary').count(), 0)
    const submissionsBeforeReopen = await count('submit')
    await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    await button('Open cloud images').click(); await rejected.waitFor()
    assert.match(await rejected.innerText(), /HTTP 403/)
    assert.match(await legacy.innerText(), /not recorded/)
    assert.equal(await count('submit'), submissionsBeforeReopen)
    pass('Known 403 rejections retain useful details after reopening, without refresh/reconnect/import or invented legacy diagnostics')

    await page.screenshot({ path: path.join(output, 'router-desktop.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(output, 'router-phone.png') })
    assert.equal(await dialog().evaluate(node => node.scrollWidth <= node.clientWidth), true)
    await button('Forget session key').click()
    await page.getByText('Not connected', { exact: true }).waitFor()
    assert.equal((await state()).connected, false)
    await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    assert.equal(await button('Open cloud images').evaluate(node => document.activeElement === node), true)
    assert.equal((await state()).subscribers, 0)
    await button('Open cloud images').click(); await tick()
    assert.equal(await key().inputValue(), '')
    assert.equal(await prompt().inputValue(), '')
    assert.equal((await state()).subscribers, 1)
    assert.deepEqual((await state()).storageWrites, [])
    assert.equal((await state()).timelineWrites, 0)
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    pass('Narrow layout, key forgetting, reopen and subscription cleanup work without browser storage, external traffic or timeline changes')
    console.log(JSON.stringify({ success: true, groups, output }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
