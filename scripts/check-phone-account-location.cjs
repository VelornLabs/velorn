// Real desktop views; isolated RAM/native stubs. No real pairing or account IO.
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
;(async () => {
  const base = 'http://127.0.0.1:5173', output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-phone-account-location-'))
  const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/google-chrome' })
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } }), errors = [], blocked = []
  page.setDefaultTimeout(10000); page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', r => new URL(r.request().url()).origin === base ? r.continue() : (blocked.push(r.request().url()), r.abort()))
  await page.routeWebSocket(() => true, s => s.close())
  const button = name => page.getByRole('button', { name, exact: true })
  const sheet = page.getByRole('dialog', { name: 'Your Velorn account', exact: true })
  const snapshot = () => page.evaluate(() => window.connectedAgentTest.snapshot())
  try {
    await page.goto(base + '/tests/fixtures/connected-agent.html?strict=1&mobile=1&accountPanel=1')
    await page.waitForFunction(() => window.connectedAgentTest?.ready)
    await button('Assistant settings').click()
    assert.equal(await button('Enable phone access').count(), 0)
    assert.equal(await button('Pair a phone').count(), 0)
    const before = await snapshot()
    await button('Manage phone sharing').click(); await sheet.waitFor()
    await sheet.locator('.desktop-account-advanced > summary').click()
    await sheet.getByText('Legacy pairing', { exact: true }).click()
    await sheet.getByRole('button', { name: 'Pair a phone', exact: true }).waitFor()
    assert.equal((await snapshot()).calls.filter(c => c.method === 'mobile.enable').length, 0)
    assert.deepEqual((await snapshot()).storage, before.storage)
    assert.deepEqual((await snapshot()).authored, before.authored)
    await page.screenshot({ path: path.join(output, 'legacy-options.png') })
    await page.keyboard.press('Escape'); await sheet.waitFor({ state: 'hidden' })
    assert.equal(await button('Manage phone sharing').evaluate(e => e === document.activeElement), true)
    await button('Manage phone sharing').click()
    // Reopening leaves advanced controls collapsed and cannot enable anything.
    assert.equal(await sheet.locator('.desktop-account-advanced').evaluate(e => e.open), false)
    await sheet.locator('.desktop-account-advanced > summary').click()
    await sheet.getByText('Legacy pairing', { exact: true }).click()
    await sheet.getByRole('button', { name: 'Pair a phone', exact: true }).click()
    await sheet.getByText('SYNTHETIC123', { exact: true }).waitFor()
    assert.equal((await snapshot()).calls.filter(c => c.method === 'mobile.enable').length, 1)
    assert.deepEqual((await snapshot()).authored, before.authored)
    await page.keyboard.press('Escape'); await sheet.waitFor({ state: 'hidden' })
    await button('Manage phone sharing').click()
    assert.equal((await snapshot()).calls.filter(c => c.method === 'mobile.enable').length, 1, 'Reopen never re-pairs')
    await sheet.locator('.desktop-account-advanced > summary').click()
    await sheet.getByText('Legacy pairing', { exact: true }).click()
    await page.evaluate(() => window.connectedAgentTest.setExportBusy(true))
    assert.equal(await sheet.getByRole('button', { name: 'Forget older pairing and stop sharing', exact: true }).isDisabled(), true)
    assert.equal(await sheet.getByRole('button', { name: 'Stop all phone sharing', exact: true }).isDisabled(), true)
    assert.equal((await snapshot()).requests.length, 0)
    console.log('PASS: Assistant link opens account; legacy pairing stays nested; focus returns; reads preserve state; explicit pairing happens once; export guards remain')
    await page.goto(base + '/tests/fixtures/desktop-account.html?independent=1')
    await page.waitForFunction(() => window.desktopAccountFixture)
    await page.evaluate(() => window.desktopAccountFixture.setState('paused-running', true))
    await button('Velorn account').click(); await sheet.waitFor()
    await sheet.getByRole('button', { name: 'Enable phone sharing', exact: true }).waitFor()
    await sheet.locator('.desktop-account-advanced > summary').click()
    assert.equal(await sheet.getByRole('button', { name: 'Enable phone access', exact: true }).count(), 0)
    assert.equal(await sheet.getByRole('button', { name: 'Pair a phone', exact: true }).count(), 0, 'Builds without legacy support cannot expose pairing')
    assert.equal((await page.evaluate(() => window.desktopAccountFixture.calls)).filter(c => c.method === 'desktop-account').length, 0)
    await sheet.getByRole('button', { name: 'Enable phone sharing', exact: true }).click()
    await sheet.getByRole('button', { name: 'Stop phone sharing', exact: true }).waitFor()
    assert.equal((await page.evaluate(() => window.desktopAccountFixture.calls)).filter(c => c.action === 'enable-phone').length, 1)
    assert.equal(await sheet.getByText('Connected devices · 2', { exact: true }).count(), 1)
    await page.screenshot({ path: path.join(output, 'account-sharing.png') })
    console.log('PASS: Current account sharing uses existing independent action, has no duplicate enable/pair controls, and retains both devices')
    assert.deepEqual(errors, []); assert.deepEqual(blocked, []); console.log(output)
  } catch (e) { await page.screenshot({ path: path.join(output, 'failure.png') }); console.log(output); throw e }
  finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
