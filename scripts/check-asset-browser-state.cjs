// Fresh browser context: actual panels/stores, synthetic image rows only.
// No production app, user project, Electron preload, filesystem IPC or MCP.
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5198')
if (base.hostname !== '127.0.0.1' || base.protocol !== 'http:') throw new Error('Fixture requires a loopback Vite server')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-asset-browser-state-'))
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1200, height: 800 } })
  const page = await context.newPage(), errors = [], groups = []
  const pass = label => { groups.push(label); console.log(`PASS ${groups.length}: ${label}`) }
  page.setDefaultTimeout(10000)
  page.on('pageerror', error => errors.push(error.message))
  await page.routeWebSocket(url => url.hostname === base.hostname && url.port === base.port, socket => socket.close())
  const snapshot = () => page.evaluate(() => window.assetBrowserTest.snapshot())
  const ready = () => page.waitForFunction(() => window.assetBrowserTest?.resetLayout && document.querySelector('[data-testid="asset-browser-scroll"]'))
  const scroller = page.getByTestId('asset-browser-scroll')
  const left = page.getByTestId('actual-left-panel')
  const folder = name => left.locator('[data-is-folder]').filter({ has: page.getByText(name, { exact: true }) })
  const browse = async () => {
    await left.getByRole('button', { name: 'Root', exact: true }).click()
    await folder('Shots').click()
    await left.getByTitle('List view', { exact: true }).click()
    await folder('Takes').getByTitle('Expand', { exact: true }).click()
    await folder('Details').getByTitle('Expand', { exact: true }).click()
    await left.getByPlaceholder('Search...').fill('Match')
    await scroller.hover()
    await page.mouse.wheel(0, 900)
    await page.waitForFunction(() => window.assetBrowserTest.snapshot().scrollTop > 200)
    const state = await snapshot()
    assert.equal(state.currentFolderId, 'shots'); assert.equal(state.viewMode, 'list')
    assert.equal(state.searchQuery, 'Match'); assert.deepEqual(state.expandedFolderIds, ['details', 'takes'])
    assert.equal(state.savedView, 'list'); assert.ok(state.scrollHeight > state.clientHeight)
    assert.equal(state.dirty, false, 'Browsing must not mark the project dirty')
    return state
  }
  const restored = async expected => {
    await ready()
    await page.waitForFunction(top => Math.abs(window.assetBrowserTest.snapshot().domScrollTop - top) <= 2, expected.domScrollTop)
    const state = await snapshot()
    for (const key of ['viewMode', 'currentFolderId', 'searchQuery', 'expandedFolderIds', 'authored']) assert.deepEqual(state[key], expected[key], key)
    assert.equal(state.searchValue, expected.searchQuery)
    assert.equal(state.dirty, false, 'Remounting must not mark the project dirty')
    assert.ok(Math.abs(state.scrollTop - expected.scrollTop) <= 2, 'Saved scroll changed during remount')
    await left.getByRole('button', { name: 'Shots', exact: true }).waitFor()
    assert.equal(await folder('Takes').getByTitle('Collapse', { exact: true }).count(), 1)
    assert.equal(await folder('Details').getByTitle('Collapse', { exact: true }).count(), 1)
    assert.match(await left.getByTitle('List view', { exact: true }).getAttribute('class'), /bg-sf-dark-600/)
  }
  const reset = state => {
    assert.equal(state.currentFolderId, null); assert.equal(state.searchQuery, '')
    assert.equal(state.scrollTop, 0); assert.deepEqual(state.expandedFolderIds, [])
    assert.equal(state.viewMode, 'list'); assert.equal(state.savedView, 'list')
  }
  try {
    await page.goto(new URL('/tests/fixtures/asset-browser-state.html', base).href)
    await ready()
    const pristine = await snapshot()
    const baseline = await browse()
    assert.equal(baseline.authored, pristine.authored, 'Browsing must not change saved project fields')
    await page.getByRole('button', { name: 'Switch workspace', exact: true }).click()
    assert.equal((await snapshot()).domScrollTop, null)
    await page.getByRole('button', { name: 'Return to editor', exact: true }).click()
    await restored(baseline)
    pass('Workspace unmount/remount retains folder, list view, search, expanded branches and actual scroll')

    await left.getByTitle('Effects', { exact: true }).click()
    assert.equal(await scroller.count(), 0)
    await left.getByTitle('Assets', { exact: true }).click()
    await restored(baseline)
    pass('Assets → Effects → Assets restores browse state without changing project assets')

    await left.getByTitle('Assets', { exact: true }).click()
    assert.equal(await scroller.count(), 0)
    await left.getByTitle('Assets', { exact: true }).click()
    await restored(baseline)
    await page.getByRole('button', { name: 'Remount layout', exact: true }).click()
    await restored(baseline)
    pass('Sidebar collapse/expand and layout remount preserve the same browse state')
    await page.screenshot({ path: path.join(output, 'browse-state-restored.png') })

    await page.evaluate(() => window.assetBrowserTest.clearProject())
    await page.waitForFunction(() => window.assetBrowserTest.snapshot().assetCount === 0)
    reset(await snapshot())
    assert.equal(await left.getByPlaceholder('Search...').inputValue(), '')
    await page.evaluate(() => window.assetBrowserTest.loadProject('Synthetic new project'))
    await ready(); reset(await snapshot())
    pass('clearProject and new-project hydration reset project-specific browsing but retain the list preference')

    await browse()
    await page.getByRole('button', { name: 'Switch workspace', exact: true }).click()
    await page.evaluate(() => window.assetBrowserTest.loadProject('Synthetic replacement project'))
    reset(await snapshot())
    await page.getByRole('button', { name: 'Return to editor', exact: true }).click()
    await ready(); reset(await snapshot())
    assert.equal((await snapshot()).domScrollTop, 0)
    pass('A project loaded while the sidebar is absent cannot restore old folder/search/scroll state')

    await browse()
    await page.getByRole('button', { name: 'Switch workspace', exact: true }).click()
    const removed = await page.evaluate(() => window.assetBrowserTest.removeFolder('shots'))
    assert.equal(removed.ok, true)
    await page.getByRole('button', { name: 'Return to editor', exact: true }).click()
    await ready()
    await page.waitForFunction(() => window.assetBrowserTest.snapshot().currentFolderId === null)
    const afterDelete = await snapshot()
    assert.deepEqual(afterDelete.folderIds, ['archive'])
    assert.deepEqual(afterDelete.expandedFolderIds, [])
    assert.equal(afterDelete.scrollTop, 0); assert.equal(afterDelete.domScrollTop, 0)
    assert.equal(afterDelete.viewMode, 'list')
    pass('Deleting the current folder while unmounted falls back to root and prunes deleted expanded branches')

    await page.evaluate(() => window.assetBrowserTest.loadProject('Synthetic checkpoint project'))
    await ready(); await browse()
    await page.getByRole('button', { name: 'Switch workspace', exact: true }).click()
    await page.evaluate(() => window.assetBrowserTest.restoreCheckpointWithoutShots())
    await page.getByRole('button', { name: 'Return to editor', exact: true }).click()
    await ready()
    await page.waitForFunction(() => window.assetBrowserTest.snapshot().currentFolderId === null)
    const afterCheckpoint = await snapshot()
    assert.deepEqual(afterCheckpoint.folderIds, ['archive'])
    assert.deepEqual(afterCheckpoint.expandedFolderIds, [])
    assert.equal(afterCheckpoint.scrollTop, 0); assert.equal(afterCheckpoint.domScrollTop, 0)
    assert.equal(afterCheckpoint.viewMode, 'list')
    pass('Checkpoint-style folder replacement while hidden safely prunes stale browsing on remount')

    await page.reload(); await ready()
    const reloaded = await snapshot()
    reset(reloaded)
    assert.equal(reloaded.domScrollTop, 0)
    pass('View preference survives a fresh renderer; transient browse state starts clean')
    assert.deepEqual(errors, [], 'Renderer exceptions')
    const result = { success: true, groups, output, snapshot: { ...reloaded, authored: undefined } }
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2))
    console.log('ASSET_BROWSER_STATE_RESULT ' + JSON.stringify(result))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {})
    fs.writeFileSync(path.join(output, 'failure.log'), `${error.stack}\n${errors.join('\n')}`)
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
