const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const base=process.env.VELORN_TEST_URL||'http://127.0.0.1:5248',output=fs.mkdtempSync(path.join(os.tmpdir(),'velorn-lmstudio-preview-check-'))
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base))throw Error('Isolated loopback preview only')
async function main(){
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',headless:true})
  const page=await browser.newPage({viewport:{width:1120,height:1030}}),errors=[],external=[],checks=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/*',r=>new URL(r.request().url()).origin===base?r.continue():(external.push(r.request().url()),r.abort()))
  await page.routeWebSocket(()=>true,s=>s.close())
  const frame=()=>page.frames().find(f=>f.url().includes('/codex-setup-preview-frame.html'))
  const button=name=>frame().getByRole('button',{name,exact:true})
  const panel=()=>frame().getByRole('region',{name:'LM Studio setup',exact:true})
  const snapshot=()=>frame().evaluate(()=>window.connectedAgentTest.snapshot())
  const settings=async()=>JSON.parse((await snapshot()).storage['velorn.connected-agent.settings.v1']||'{}')
  const ready=async()=>{await page.waitForFunction(()=>window.lmStudioSetupPreview?.ready);await button('Choose LM Studio').waitFor()}
  const restart=async scenario=>{await page.getByRole('button',{name:scenario,exact:true}).click();await ready();await button('Choose LM Studio').click();await panel().waitFor()}
  const connected=async()=>{await panel().getByText('Connected to LM Studio.',{exact:true}).waitFor();await button('Check again').waitFor()}
  const model=()=>frame().getByLabel('LM Studio model',{exact:true})
  const trouble=()=>panel().locator('summary').filter({hasText:'Troubleshooting'})
  const safe=async baseline=>{
    const state=await snapshot()
    assert.equal(state.requests.length,0);assert.deepEqual(state.forbiddenCalls,[]);assert.deepEqual(state.authored,baseline)
    assert.equal(state.fullAccessGrant,null);assert.equal(state.fullAccessRemembered,false);assert.equal(state.localFullAccessRemembered,false)
    assert.equal(state.spendingPolicy,'local-only')
    assert.equal(state.calls.filter(call=>/send|download|loadModel|setupHelper|codexLogin/.test(call.method)).length,0)
    assert.deepEqual(await page.evaluate(()=>window.lmStudioSetupPreview.sendAttempts()),[],'No hidden provider-send attempts during setup')
  }
  try{
    const response=await page.goto(`${base}/tests/fixtures/lmstudio-setup-preview.html`)
    assert.match(response.headers()['content-security-policy'],/connect-src 'none'/)
    await ready();const baseline=(await snapshot()).authored
    assert.equal((await snapshot()).calls.filter(call=>call.method==='inspect'&&call.options?.provider==='lmstudio').length,0,'LM Studio is not inspected before the owner chooses it')
    await button('Choose LM Studio').press('Enter');await connected()
    assert.equal(await panel().count(),1);assert.equal(await frame().getByRole('dialog',{name:'Optional tools',exact:true}).count(),0)
    assert.equal(await frame().evaluate(()=>document.activeElement?.textContent),'Connect LM Studio','Keyboard entry focuses the one-panel heading')
    assert.doesNotMatch(await panel().innerText(),/Fully quit and reopen|Set up an editing assistant|Choose executable/)
    assert.equal(await model().inputValue(),'');assert.equal(await button('Use model').isDisabled(),true)
    assert.equal((await settings()).lmstudioModel,undefined)
    assert.equal(await panel().locator('details').getAttribute('open'),null)
    await model().selectOption('preview-local-alternate')
    assert.equal((await settings()).lmstudioModel,undefined,'Picking a row stages the model without applying it')
    await panel().getByText('Not currently loaded. LM Studio may load it when you send a message.',{exact:true}).waitFor()
    await page.screenshot({path:path.join(output,'ready-choice.png'),fullPage:true})
    await button('Use model').click();await panel().waitFor({state:'detached'})
    assert.equal((await settings()).lmstudioModel,'preview-local-alternate');await safe(baseline)
    const existingSelection=await settings()
    await button('Assistant settings').click();await frame().locator('.ca-setup-help > summary').click();await button('Setup helper').click();await connected()
    assert.equal(await model().inputValue(),'preview-local-alternate')
    await button('Use model').click();await panel().waitFor({state:'detached'})
    assert.deepEqual(await settings(),existingSelection)
    assert.equal(await frame().evaluate(()=>document.activeElement?.getAttribute('aria-label')),'Message your agent','Reusing the selected model restores focus to chat')
    checks.push('direct single panel without generic-tools detours','keyboard entry focuses setup','connection-first metadata only','ready models require explicit selection and Use','nonloaded model is not silently loaded','troubleshooting collapsed')
    checks.push('existing selected model preserved through setup','Use unchanged model restores composer focus')

    await restart('Server ready');await connected();const beforeLater=await settings()
    await button('Not now').click();await panel().waitFor({state:'detached'})
    assert.equal((await settings()).lmstudioModel,beforeLater.lmstudioModel)
    assert.equal(await frame().evaluate(()=>document.activeElement?.getAttribute('aria-label')),'Message your agent','Not now restores focus to chat')
    await button('Connect LM Studio').click();await connected()
    assert.equal(await model().inputValue(),'');await safe(baseline)
    checks.push('Not now and explicit resume preserve model')

    await restart('Server stopped');await panel().getByText('LM Studio’s server is not reachable yet.',{exact:true}).waitFor()
    assert.match(await panel().innerText(),/This does not mean LM Studio is missing/)
    assert.match(await panel().innerText(),/Developer tab/)
    assert.equal(await button('Already installed? Choose its location').isVisible(),true)
    await button('Get LM Studio').click();await page.getByRole('heading',{name:'Simulated official guide',exact:true}).waitFor()
    assert.deepEqual(await page.evaluate(()=>window.lmStudioSetupPreview.guideCalls()),['https://lmstudio.ai/download'])
    await page.getByRole('button',{name:'Back to Velorn',exact:true}).click()
    const beforeLocate=await snapshot()
    await button('Already installed? Choose its location').press('Enter')
    await page.getByRole('heading',{name:'Simulated LM Studio location picker',exact:true}).waitFor()
    assert.equal(await button('Already installed? Choose its location').isDisabled(),true)
    assert.equal(await button('Not now').isDisabled(),true)
    await button('Already installed? Choose its location').evaluate(el=>el.click())
    assert.equal((await page.evaluate(()=>window.lmStudioSetupPreview.actionCalls())).length,1)
    await page.getByRole('button',{name:'Cancel simulated app action',exact:true}).click()
    await panel().getByText('Cancelled. Nothing was changed.',{exact:true}).waitFor()
    assert.deepEqual((await snapshot()).storage,beforeLocate.storage)
    await button('Already installed? Choose its location').click();await page.getByRole('button',{name:'Select simulated LM Studio',exact:true}).click()
    await panel().getByText('A simulated installation was located. It was not opened.',{exact:true}).waitFor()
    await panel().getByText('LM Studio’s server is not reachable yet.',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>window.lmStudioSetupPreview.actionCalls())).filter(c=>c.action==='open').length,0)
    await page.screenshot({path:path.join(output,'server-stopped.png'),fullPage:true})
    await button('Open LM Studio').click();await page.getByRole('button',{name:'Cancel simulated app action',exact:true}).click()
    await panel().getByText('Cancelled. Nothing was changed.',{exact:true}).waitFor()
    await button('Open LM Studio').click();await page.getByRole('button',{name:'Open simulated LM Studio',exact:true}).click()
    await page.getByRole('button',{name:'Start simulated local server',exact:true}).click()
    await page.getByRole('button',{name:'Back to Velorn',exact:true}).click()
    await button('Check again').click();await connected();assert.equal(await model().inputValue(),'')
    await safe(baseline)
    checks.push('stopped server is not misreported as missing installation','existing app locate visible and keyboard accessible','cancel native locate preserves synthetic state','duplicate/busy guards','locating does not launch or connect','cancel app launch','explicit simulated server start then metadata recheck')

    await restart('No models');await connected()
    assert.equal(await model().count(),0);assert.equal(await button('Use model').count(),0)
    assert.match(await panel().innerText(),/No chat models were found/);assert.match(await panel().innerText(),/Discover/)
    await page.screenshot({path:path.join(output,'no-models.png'),fullPage:true})
    await button('Open LM Studio').click();await page.getByRole('button',{name:'Open simulated LM Studio',exact:true}).click()
    await page.getByRole('button',{name:'Load example model',exact:true}).click()
    await page.getByRole('button',{name:'Back to Velorn',exact:true}).click()
    await button('Check again').click();await connected();await model().waitFor();assert.equal(await model().inputValue(),'')
    await safe(baseline)
    checks.push('empty models give explicit LM Studio guidance','fixed guide simulated only','model availability rechecks without loading or auto-selecting')

    await trouble().click();const oldSettings=await settings()
    await frame().getByLabel('LM Studio server address',{exact:true}).fill('http://127.0.0.1:5678/v1')
    await button('Save address and check').click()
    await panel().getByRole('alert').filter({hasText:'The saved address is unchanged.'}).waitFor()
    assert.deepEqual(await settings(),oldSettings,'Unsupported port is rejected without replacing the saved address')
    await frame().getByLabel('LM Studio server address',{exact:true}).fill('http://localhost:1234/v1/')
    await frame().getByLabel('Custom model ID',{exact:true}).fill('preview-custom-model')
    assert.deepEqual(await settings(),oldSettings,'Address and custom model drafts do not save on typing')
    await button('Save address and check').click();await connected()
    assert.equal((await settings()).endpoint,'http://localhost:1234/v1/');assert.equal((await settings()).lmstudioModel,undefined)
    assert.ok((await snapshot()).calls.some(c=>c.method==='inspect'&&c.options.endpoint==='http://localhost:1234/v1/'))
    await button('Use custom model').click();await panel().waitFor({state:'detached'})
    assert.equal((await settings()).lmstudioModel,'preview-custom-model');await safe(baseline)
    checks.push('unsupported endpoint rejected without saved-state mutation','custom endpoint staged until explicit save and metadata check','custom ID explicitly applied without inference validation')

    await restart('Server ready');await connected()
    await frame().evaluate(()=>window.connectedAgentTest.setHoldInspect(true));await button('Check again').click()
    await frame().waitForFunction(()=>window.connectedAgentTest.snapshot().pendingInspects.length===1)
    await button('Not now').click();await panel().waitFor({state:'detached'})
    await frame().evaluate(()=>{window.connectedAgentTest.setHoldInspect(false);window.connectedAgentTest.releaseInspect(null,{success:false,error:'Stale synthetic failure',code:'CONNECTION_FAILED'})})
    await button('Connect LM Studio').click();await connected();assert.equal(await model().inputValue(),'')
    assert.doesNotMatch(await panel().innerText(),/Stale synthetic failure/)
    await frame().evaluate(()=>window.connectedAgentTest.setConnectionError('Synthetic endpoint disconnected','CONNECTION_FAILED'))
    await button('Check again').click();await panel().getByText('LM Studio’s server is not reachable yet.',{exact:true}).waitFor()
    await frame().evaluate(()=>window.connectedAgentTest.setConnectionError(''))
    await button('Check again').click();await connected();await safe(baseline)
    checks.push('stale inspection cannot revive cancelled setup','connection error recovers on explicit recheck')

    await page.setViewportSize({width:780,height:740});await model().selectOption('preview-local-small')
    assert.equal(await frame().evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true)
    await page.screenshot({path:path.join(output,'narrow-ready.png'),fullPage:true})
    assert.equal(await frame().evaluate(()=>window.fetch('/no-network').then(()=>false,()=>true)),true)
    await safe(baseline);assert.deepEqual(errors,[]);assert.deepEqual(external,[]);assert.equal(page.context().pages().length,1)
    const sent=await frame().evaluate(()=>window.electronAPI.connectedAgent.send({prompt:'never sent'}));assert.equal(sent.success,false)
    assert.equal((await snapshot()).requests.length,0);assert.deepEqual(await page.evaluate(()=>window.lmStudioSetupPreview.sendAttempts()),[{prompt:'never sent'}])
    for(const target of ['/src/App.jsx','/@fs/etc/passwd','/electron/main.js','/package.json'])assert.equal((await fetch(base+target)).status,404)
    assert.equal((await fetch(base,{method:'POST',body:'not stored'})).status,403)
    checks.push('narrow layout','no account changes/inference/native app/files/model download','authored project unchanged','CSP network guard and no external tabs','static allowlist and POST rejection')
    console.log(JSON.stringify({success:true,output,checks},null,2))
  }catch(error){await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});console.error({output,errors,external});throw error}
  finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
