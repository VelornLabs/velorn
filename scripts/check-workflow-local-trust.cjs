const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = new URL(process.env.VELORN_TEST_URL || 'http://127.0.0.1:5209')
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1') throw new Error('Use an isolated loopback fixture')
async function main() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 800, height: 700 } })
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'velorn-workflow-local-trust-')), errors = [], blocked = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin === base.origin && !/^\/(prompt|queue|history|upload|api|v1)(\/|$)/.test(url.pathname)) return route.continue()
    blocked.push(url.href); return route.abort()
  })
  await page.routeWebSocket(() => true, socket => socket.close())
  const forget = () => page.getByRole('button', { name: 'Forget local choice for Synthetic H3 video', exact: true })
  const state = () => page.evaluate(() => window.workflowLocalTrustTest.snapshot())
  const expand = () => page.locator('summary').click()
  try {
    await page.goto(new URL('/tests/fixtures/workflow-local-trust.html', base).href)
    await page.getByText('Remembered local workflows (1)', { exact: true }).waitFor()
    assert.equal(await forget().isVisible(), false)
    await expand()
    assert.match(await page.locator('main').innerText(), /not a guarantee/)
    assert.match(await page.locator('main').innerText(), /Known paid workflows still follow Generation spending/)
    assert.match(await page.locator('main').innerText(), /This works with Local only/)
    assert.match(await page.locator('main').innerText(), /Trust as local and run/)
    assert.equal(await forget().isVisible(), true)
    console.log('PASS: remembered choices are collapsed initially, labeled truthfully and expandable')
    await page.getByRole('button', { name: 'Disable actions' }).click()
    assert.equal(await forget().isDisabled(), true)
    assert.equal((await state()).calls.filter(item => item.method === 'revoke').length, 0)
    await page.getByRole('button', { name: 'Enable actions' }).click()
    await page.evaluate(() => window.workflowLocalTrustTest.fail(true))
    await forget().click()
    await page.getByRole('alert').getByText('Synthetic save failure').waitFor()
    assert.equal(await forget().isVisible(), true)
    assert.equal((await state()).entries.length, 1)
    console.log('PASS: disabled actions cannot revoke; failed save preserves the listed choice with visible error')
    await page.evaluate(() => window.workflowLocalTrustTest.fail(false))
    await forget().click()
    await page.getByText('No workflows marked as local yet.').waitFor()
    assert.deepEqual((await state()).calls.filter(item => item.method === 'revoke').map(item => item.payload), [{ id: 'a'.repeat(64) }, { id: 'a'.repeat(64) }])
    await page.getByRole('button', { name: 'Unmount', exact: true }).click()
    assert.equal((await state()).listeners, 0)
    await page.getByRole('button', { name: 'Remount', exact: true }).click()
    await expand()
    await page.getByText('No workflows marked as local yet.').waitFor()
    console.log('PASS: revoke addresses exact native ID; remount reads current persistent status and cleans listeners')
    await page.evaluate(() => window.workflowLocalTrustTest.replace([{ id: 'b'.repeat(64), title: 'Newly trusted local workflow' }]))
    await page.getByText('Newly trusted local workflow', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(output, 'local-trust-settings.png') })
    assert.deepEqual(errors, []); assert.deepEqual(blocked, [])
    console.log('PASS: native status changes refresh choices; narrow layout has no horizontal overflow')
    console.log(JSON.stringify({ groups: 4, screenshot: path.join(output, 'local-trust-settings.png'), externalRequests: blocked.length }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
